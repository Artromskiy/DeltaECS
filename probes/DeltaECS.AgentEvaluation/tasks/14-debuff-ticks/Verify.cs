using System;
using System.Numerics;
using ApiChoiceProbe;
using Delta.ECS;

using var s = new Scenario();
ComponentId slowA = s.World.Components.Register<SlowDebuff>(new SchemaId(200));
ComponentId slowB = s.World.Components.Register<SlowDebuff>(new SchemaId(201));
ComponentId burn = s.World.Components.Register<BurnDebuff>(new SchemaId(202));
ComponentId chill = s.World.Components.Register<ChillDebuff>(new SchemaId(203));
ComponentId ignored = s.World.Components.Register<IgnoredDebuff>(new SchemaId(204));
s.World.Components.BindInterface<SlowDebuff, IDebuff>();
s.World.Components.BindInterface<BurnDebuff, IDebuff>();
s.World.Components.BindInterface<ChillDebuff, IDebuff>();
s.World.Components.BindInterface<IgnoredDebuff, IDebuff>();
Entity first = s.Units[0], second = s.Units[1];
s.World.Add(first, slowA, new SlowDebuff(30));
s.World.Add(first, slowB, new SlowDebuff(40));
s.World.Add(first, burn, new BurnDebuff(50));
s.World.Add(first, ignored, new IgnoredDebuff(100));
s.World.Add(second, slowA, new SlowDebuff(60));
s.World.Add(second, burn, new BurnDebuff(70));
int noiseBefore = s.World.Get<Noise>(second).Value;
ComponentId[] configured = { slowA, slowB, burn, chill };
var solution = new Solution(s, configured, 3);
solution.Execute();
Check.That(s.World.Get<SlowDebuff>(first, slowA).Remaining == 27, "First slow registration did not tick");
Check.That(s.World.Get<SlowDebuff>(first, slowB).Remaining == 37, "Same-type alternate registration did not tick");
Check.That(s.World.Get<BurnDebuff>(first, burn).Remaining == 44, "Burn did not tick");
Check.That(s.World.Get<IgnoredDebuff>(first, ignored).Remaining == 100, "Unselected interface registration changed");
Check.That(s.World.Get<SlowDebuff>(second, slowA).Remaining == 57, "Second entity did not tick");
Check.That(s.World.Get<Noise>(second).Value == noiseBefore, "Unselected component changed");
solution.Execute();
Check.That(s.World.Get<BurnDebuff>(second, burn).Remaining == 58, "Repeated invocation did not use current membership");
Entity late = s.SpawnUnit(new Vector2(12, 3), 10, 700);
s.World.Add(late, chill, new ChillDebuff(20));
s.World.Add(late, slowB, new SlowDebuff(10));
solution.Execute();
Check.That(s.World.Get<ChillDebuff>(late, chill).Remaining == 16, "Third component type was not dispatched");
Check.That(s.World.Get<SlowDebuff>(late, slowB).Remaining == 7, "New entity or configured alternate was missed");
Check.That(s.World.Get<SlowDebuff>(first, slowA).Remaining == 21, "Existing component stopped ticking");
Console.WriteLine("PASS 14-debuff-ticks");
