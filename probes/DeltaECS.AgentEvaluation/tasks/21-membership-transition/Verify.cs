using System;
using System.Numerics;
using ApiChoiceProbe;
using Delta.ECS;
using var s = new Scenario();
var solution = new Solution(s);
s.World.Add(s.Units[1], s.MarkedId);
s.World.Add(s.Units[1], s.PausedId);
solution.Execute();
Check.That(s.World.Get<Health>(s.Units[0]).Value == 11 && s.World.Has(s.Units[0], s.MarkedId) && !s.World.Has(s.Units[0], s.PausedId), "transition for newly qualifying entity");
Check.That(s.World.Get<Health>(s.Units[1]).Value == 9 && !s.World.Has(s.Units[1], s.MarkedId), "below threshold transition");
Check.That(s.World.Has(s.Units[1], s.PausedId), "paused membership should survive");
Check.That(!s.World.Has(s.Units[1], s.MarkedId), "below-threshold marked membership was not removed");
Check.That(s.World.Get<Health>(s.Units[3]).Value == 5, "enemy below threshold was not updated");
Check.That(s.World.Get<Health>(s.Units[6]).Value == 8 && s.World.Has(s.Units[6], s.MarkedId), "non-enemy value or membership changed");
Check.That(s.World.Get<Noise>(s.Units[0]).Value == 1234, "unrelated component changed");
Entity added = s.SpawnUnit(new Vector2(2, 2), 6, 999, enemy: true, paused: true);
solution.Execute();
Check.That(s.World.Get<Health>(added).Value == 11 && s.World.Has(added, s.MarkedId) && !s.World.Has(added, s.PausedId), "new entity or live second-stage selection failed");
Check.That(s.World.Has(s.Units[4], s.MarkedId) && !s.World.Has(s.Units[4], s.PausedId), "updated threshold should transition existing paused entity");
Console.WriteLine("PASS 21-membership-transition");
