using System;
using System.Collections.Generic;
using ApiChoiceProbe;
using Delta.ECS;
using var s = new EffectScenario();
var solution = new Solution(s);
solution.Execute();
Check.That(s.World.Get<Burn>(s.A, s.PoisonId).Turns == 3, "second registration tick missing");
Check.That(!s.World.Has(s.A, s.BurnId), "expired registration not removed");
Check.That(s.World.Has(s.A, s.FrostId) && s.World.Has(s.A, s.PoisonId), "unexpired effect removed");
Check.That(s.World.Get<Frost>(s.A).Turns == 1 && s.World.Get<Burn>(s.A, s.PoisonAltId).Turns == 3, "every configured instance must tick exactly once");
Check.That(s.World.Get<Shock>(s.A).Turns == 2 && s.World.Get<Untracked>(s.A).Turns == 3, "configured and unconfigured types were not distinguished");
Check.That(s.World.Get<Noise>(s.A).Value == 1234, "unrelated value changed");
solution.Execute();
Check.That(!s.World.Has(s.A, s.FrostId) && s.World.Has(s.A, s.PoisonId), "second tick/removal failed");
Check.That(s.World.Has(s.A, s.PoisonAltId), "same CLR type registration was skipped");
Check.That(s.World.Get<Burn>(s.A, s.PoisonId).Turns == 2 && s.World.Get<Burn>(s.A, s.PoisonAltId).Turns == 2, "alternate registration counters differ");
Check.That(s.World.Get<Shock>(s.A).Turns == 1 && s.World.Get<Untracked>(s.A).Turns == 3, "additional configured type or unconfigured instance mishandled");
Entity added = s.World.Create(s.BurnId);
s.World.GetRef<Burn>(added, s.BurnId) = new(3);
solution.Execute();
Check.That(s.World.Get<Burn>(added, s.BurnId).Turns == 2, "new effect membership missed");
Check.That(!s.World.Has(s.A, s.ShockId) && s.World.Has(s.A, s.UntrackedId), "expired configured type or unconfigured type membership incorrect");
Check.That(s.World.Get<Burn>(s.A, s.PoisonId).Turns == 1 && s.World.Get<Burn>(s.A, s.PoisonAltId).Turns == 1, "later calls did not tick every surviving registration");
Check.That(s.World.Get<Untracked>(s.A).Turns == 3, "unconfigured effect was ticked");
Check.That(s.World.AliveEntityCount == 2, "effect cleanup destroyed entity");
Console.WriteLine("PASS 19-expiring-effects");
