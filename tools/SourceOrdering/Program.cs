using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

if (args.Length is < 1 or > 2)
{
    Console.Error.WriteLine("Usage: SourceOrdering <project-directory> [--check]");
    return 2;
}

string projectDirectory = Path.GetFullPath(args[0]);
bool checkOnly = args.Length == 2 && args[1] == "--check";
if (args.Length == 2 && !checkOnly)
{
    Console.Error.WriteLine($"Unknown argument: {args[1]}");
    return 2;
}

int changedCount = 0;
foreach (string path in Directory.EnumerateFiles(projectDirectory, "*.cs", SearchOption.AllDirectories))
{
    if (IsExcluded(path, projectDirectory) || IsGenerated(path))
    {
        continue;
    }

    byte[] bytes = File.ReadAllBytes(path);
    (Encoding encoding, int preambleLength) = DetectEncoding(bytes);
    string source = encoding.GetString(bytes, preambleLength, bytes.Length - preambleLength);
    SyntaxTree tree = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Preview), path);
    CompilationUnitSyntax root = tree.GetCompilationUnitRoot();
    if (tree.GetDiagnostics().Any(static diagnostic => diagnostic.Severity == DiagnosticSeverity.Error))
    {
        Console.Error.WriteLine($"Skipped source-order pass (parse errors): {Path.GetRelativePath(projectDirectory, path)}");
        continue;
    }

    string mainTypeName = GetPrimaryTypeName(root, GetMainTypeName(path));
    string lineEnding = source.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
    CompilationUnitSyntax ordered = (CompilationUnitSyntax)new SourceOrderRewriter(mainTypeName, lineEnding).Visit(root)!;
    string result = ordered.ToFullString();
    if (result == source)
    {
        continue;
    }

    changedCount++;
    if (checkOnly)
    {
        Console.Error.WriteLine($"Source order needs update: {Path.GetRelativePath(projectDirectory, path)}");
        continue;
    }

    byte[] output = encoding.GetBytes(result);
    byte[] preamble = encoding.GetPreamble();
    if (preamble.Length == 0 && preambleLength != 0)
    {
        preamble = bytes[..preambleLength];
    }

    WriteFile(path, preamble, output);
}

if (checkOnly && changedCount != 0)
{
    return 1;
}

return 0;

static bool IsExcluded(string path, string root)
{
    string relative = Path.GetRelativePath(root, path);
    return relative.Split(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar)
        .Any(static segment => segment is ".git" or "obj" or "bin" or "artifacts" or ".vs");
}

static bool IsGenerated(string path)
{
    string fileName = Path.GetFileName(path);
    if (fileName.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
        || fileName.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase))
    {
        return true;
    }

    using StreamReader reader = new(path, detectEncodingFromByteOrderMarks: true);
    char[] header = new char[512];
    int length = reader.ReadBlock(header, 0, header.Length);
    return new string(header, 0, length).Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
}

static (Encoding Encoding, int PreambleLength) DetectEncoding(byte[] bytes)
{
    if (bytes.AsSpan().StartsWith(Encoding.UTF8.GetPreamble()))
    {
        return (new UTF8Encoding(encoderShouldEmitUTF8Identifier: true), Encoding.UTF8.GetPreamble().Length);
    }

    if (bytes.AsSpan().StartsWith(Encoding.UTF32.GetPreamble()))
    {
        return (Encoding.UTF32, Encoding.UTF32.GetPreamble().Length);
    }

    Encoding utf32BigEndian = new UTF32Encoding(bigEndian: true, byteOrderMark: true);
    if (bytes.AsSpan().StartsWith(utf32BigEndian.GetPreamble()))
    {
        return (utf32BigEndian, utf32BigEndian.GetPreamble().Length);
    }

    if (bytes.AsSpan().StartsWith(Encoding.Unicode.GetPreamble()))
    {
        return (Encoding.Unicode, Encoding.Unicode.GetPreamble().Length);
    }

    if (bytes.AsSpan().StartsWith(Encoding.BigEndianUnicode.GetPreamble()))
    {
        return (Encoding.BigEndianUnicode, Encoding.BigEndianUnicode.GetPreamble().Length);
    }

    return (new UTF8Encoding(encoderShouldEmitUTF8Identifier: false), 0);
}

static string GetMainTypeName(string path)
{
    string fileName = Path.GetFileNameWithoutExtension(path);
    int suffixStart = fileName.IndexOf('.', StringComparison.Ordinal);
    return suffixStart < 0 ? fileName : fileName[..suffixStart];
}

static string GetPrimaryTypeName(CompilationUnitSyntax root, string fileTypeName)
{
    MemberDeclarationSyntax[] types = EnumerateTopLevelTypes(root.Members).ToArray();
    MemberDeclarationSyntax? primary = types.FirstOrDefault(type => GetTypeName(type) == fileTypeName)
        ?? types.FirstOrDefault(type => GetTypeModifiers(type).Any(SyntaxKind.PublicKeyword))
        ?? types.FirstOrDefault();
    return primary is null ? fileTypeName : GetTypeName(primary);
}

static IEnumerable<MemberDeclarationSyntax> EnumerateTopLevelTypes(
    IEnumerable<MemberDeclarationSyntax> members)
{
    foreach (MemberDeclarationSyntax member in members)
    {
        if (member is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax)
        {
            yield return member;
        }
        else if (member is NamespaceDeclarationSyntax namespaceDeclaration)
        {
            foreach (MemberDeclarationSyntax type in EnumerateTopLevelTypes(namespaceDeclaration.Members))
            {
                yield return type;
            }
        }
        else if (member is FileScopedNamespaceDeclarationSyntax fileScopedNamespace)
        {
            foreach (MemberDeclarationSyntax type in EnumerateTopLevelTypes(fileScopedNamespace.Members))
            {
                yield return type;
            }
        }
    }
}

static SyntaxTokenList GetTypeModifiers(MemberDeclarationSyntax type) => type switch
{
    BaseTypeDeclarationSyntax declaration => declaration.Modifiers,
    DelegateDeclarationSyntax declaration => declaration.Modifiers,
    _ => default
};

static string GetTypeName(MemberDeclarationSyntax type) => type switch
{
    BaseTypeDeclarationSyntax declaration => declaration.Identifier.ValueText,
    DelegateDeclarationSyntax declaration => declaration.Identifier.ValueText,
    _ => string.Empty
};

static void WriteFile(string path, byte[] preamble, byte[] content)
{
    string temporaryPath = Path.Combine(
        Path.GetDirectoryName(path)!,
        $".{Path.GetFileName(path)}.{Guid.NewGuid():N}.tmp");
    byte[] bytes = new byte[preamble.Length + content.Length];
    preamble.CopyTo(bytes, 0);
    content.CopyTo(bytes, preamble.Length);
    try
    {
        File.WriteAllBytes(temporaryPath, bytes);
        File.Move(temporaryPath, path, overwrite: true);
    }
    finally
    {
        if (File.Exists(temporaryPath))
        {
            File.Delete(temporaryPath);
        }
    }
}

internal sealed class SourceOrderRewriter(string mainTypeName, string lineEnding) : CSharpSyntaxRewriter
{
    private readonly string _mainTypeName = mainTypeName;
    private readonly string _lineEnding = lineEnding;

    public override SyntaxNode? VisitCompilationUnit(CompilationUnitSyntax node)
    {
        node = (CompilationUnitSyntax)base.VisitCompilationUnit(node)!;
        return node
            .WithExterns(OrderExterns(node.Externs))
            .WithUsings(OrderUsings(node.Usings))
            .WithMembers(OrderTypeSlots(node.Members, _mainTypeName));
    }

    public override SyntaxNode? VisitNamespaceDeclaration(NamespaceDeclarationSyntax node)
    {
        node = (NamespaceDeclarationSyntax)base.VisitNamespaceDeclaration(node)!;
        return node
            .WithExterns(OrderExterns(node.Externs))
            .WithUsings(OrderUsings(node.Usings))
            .WithMembers(OrderTypeSlots(node.Members, _mainTypeName));
    }

    public override SyntaxNode? VisitFileScopedNamespaceDeclaration(FileScopedNamespaceDeclarationSyntax node)
    {
        node = (FileScopedNamespaceDeclarationSyntax)base.VisitFileScopedNamespaceDeclaration(node)!;
        return node
            .WithExterns(OrderExterns(node.Externs))
            .WithUsings(OrderUsings(node.Usings))
            .WithMembers(OrderTypeSlots(node.Members, _mainTypeName));
    }

    public override SyntaxNode? VisitClassDeclaration(ClassDeclarationSyntax node)
    {
        node = (ClassDeclarationSyntax)base.VisitClassDeclaration(node)!;
        return node.WithMembers(OrderTypeMembers(node.Members, isInterface: false));
    }

    public override SyntaxNode? VisitStructDeclaration(StructDeclarationSyntax node)
    {
        node = (StructDeclarationSyntax)base.VisitStructDeclaration(node)!;
        return node.WithMembers(OrderTypeMembers(node.Members, isInterface: false));
    }

    public override SyntaxNode? VisitInterfaceDeclaration(InterfaceDeclarationSyntax node)
    {
        node = (InterfaceDeclarationSyntax)base.VisitInterfaceDeclaration(node)!;
        return node.WithMembers(OrderTypeMembers(node.Members, isInterface: true));
    }

    public override SyntaxNode? VisitRecordDeclaration(RecordDeclarationSyntax node)
    {
        node = (RecordDeclarationSyntax)base.VisitRecordDeclaration(node)!;
        return node.WithMembers(OrderTypeMembers(node.Members, isInterface: false));
    }

    private static SyntaxList<ExternAliasDirectiveSyntax> OrderExterns(SyntaxList<ExternAliasDirectiveSyntax> directives)
    {
        List<ExternAliasDirectiveSyntax> result = [];
        for (int index = 0; index < directives.Count;)
        {
            if (HasDirectives(directives[index]))
            {
                result.Add(directives[index++]);
                continue;
            }

            int end = index;
            while (end < directives.Count && !HasDirectives(directives[end]))
            {
                end++;
            }

            ExternAliasDirectiveSyntax[] run = directives.Skip(index).Take(end - index).ToArray();
            ExternAliasDirectiveSyntax[] ordered = run.OrderBy(static directive => directive.Identifier.ValueText, StringComparer.Ordinal).ToArray();
            result.AddRange(PreserveLeadingTrivia(run, ordered));
            index = end;
        }

        return SyntaxFactory.List(result);
    }

    private static T[] PreserveLeadingTrivia<T>(T[] original, T[] ordered) where T : SyntaxNode
    {
        if (original.Length == 0 || ordered.Length == 0 || ReferenceEquals(original[0], ordered[0]))
        {
            return ordered;
        }

        T first = original[0];
        SyntaxTriviaList preamble = first.GetLeadingTrivia();
        T[] result = ordered.Select(item => ReferenceEquals(item, first) ? (T)item.WithLeadingTrivia(default(SyntaxTriviaList)) : item).ToArray();
        result[0] = (T)result[0].WithLeadingTrivia(preamble);
        return result;
    }

    private static bool HasDirectives(SyntaxNode node)
        => node.GetLeadingTrivia().Any(static trivia => trivia.IsDirective)
            || node.GetTrailingTrivia().Any(static trivia => trivia.IsDirective);

    private static bool IsSystemUsing(UsingDirectiveSyntax directive)
    {
        string name = directive.Name?.ToString() ?? string.Empty;
        if (directive.Alias is not null && directive.Name is not null)
        {
            name = directive.Name.ToString();
        }

        return name.Equals("System", StringComparison.Ordinal)
            || name.StartsWith("System.", StringComparison.Ordinal);
    }

    private static string GetUsingSortName(UsingDirectiveSyntax directive)
        => directive.Alias?.Name.Identifier.ValueText ?? directive.Name?.ToString() ?? string.Empty;

    private static SyntaxList<MemberDeclarationSyntax> OrderTypeSlots(
        SyntaxList<MemberDeclarationSyntax> members,
        string mainName)
    {
        List<MemberDeclarationSyntax> result = [];
        for (int index = 0; index < members.Count;)
        {
            if (!IsType(members[index]) || HasDirectives(members[index]))
            {
                result.Add(members[index++]);
                continue;
            }

            int end = index;
            while (end < members.Count && IsType(members[end]) && !HasDirectives(members[end]))
            {
                end++;
            }

            result.AddRange(OrderTypes(members.Skip(index).Take(end - index).ToArray(), mainName));
            index = end;
        }

        return SyntaxFactory.List(result);
    }

    private static SyntaxList<MemberDeclarationSyntax> OrderTypeMembers(
        SyntaxList<MemberDeclarationSyntax> members,
        bool isInterface)
    {
        List<MemberDeclarationSyntax> result = [];
        for (int index = 0; index < members.Count;)
        {
            if (HasDirectives(members[index]))
            {
                result.Add(members[index++]);
                continue;
            }

            int end = index;
            while (end < members.Count && !HasDirectives(members[end]))
            {
                end++;
            }

            result.AddRange(OrderMemberRun(members.Skip(index).Take(end - index), isInterface));
            index = end;
        }

        return SyntaxFactory.List(result);
    }

    private static IEnumerable<MemberDeclarationSyntax> OrderMemberRun(
        IEnumerable<MemberDeclarationSyntax> members,
        bool isInterface)
        => members
            .Select((member, index) => new MemberOrder(member, index, GetMemberRank(member), GetAccessRank(member, isInterface), IsStatic(member)))
            .GroupBy(static item => GetNestedTypeKey(item.Member) ?? $"member:{item.Index}", StringComparer.Ordinal)
            .Select(static group => new MemberOrderGroup(group.OrderBy(static item => item.Index).ToArray()))
            .OrderBy(static group => group.Rank)
            .ThenBy(static group => group.AccessRank)
            .ThenBy(static group => group.IsStatic ? 0 : 1)
            .ThenBy(static group => group.FirstIndex)
            .SelectMany(static group => group.Items)
            .Select(static item => item.Member);

    private static IEnumerable<MemberDeclarationSyntax> OrderTypes(
        IReadOnlyList<MemberDeclarationSyntax> types,
        string mainName)
        => types
            .Select((type, index) => new TypeOrder(type, index, GetTypeKey(type), GetTypeAccessRank(type), GetTypeName(type) == mainName))
            .GroupBy(static item => item.Key, StringComparer.Ordinal)
            .Select(static group => new TypeOrderGroup(group.OrderBy(static item => item.Index).ToArray()))
            .OrderByDescending(static group => group.IsMain)
            .ThenBy(static group => group.AccessRank)
            .ThenBy(static group => group.FirstIndex)
            .SelectMany(static group => group.Items)
            .Select(static item => item.Type);

    private static bool IsType(MemberDeclarationSyntax member)
        => member is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax;

    private static int GetMemberRank(MemberDeclarationSyntax member) => member switch
    {
        FieldDeclarationSyntax field when field.Modifiers.Any(SyntaxKind.ConstKeyword) => 0,
        FieldDeclarationSyntax => 1,
        PropertyDeclarationSyntax or IndexerDeclarationSyntax or EventDeclarationSyntax or EventFieldDeclarationSyntax => 2,
        ConstructorDeclarationSyntax => 3,
        MethodDeclarationSyntax or DestructorDeclarationSyntax or OperatorDeclarationSyntax or ConversionOperatorDeclarationSyntax => 4,
        BaseTypeDeclarationSyntax or DelegateDeclarationSyntax => 5,
        _ => 6
    };

    private static int GetAccessRank(MemberDeclarationSyntax member, bool isInterface)
    {
        SyntaxTokenList modifiers = GetModifiers(member);
        bool isPrivate = modifiers.Any(SyntaxKind.PrivateKeyword);
        bool isProtected = modifiers.Any(SyntaxKind.ProtectedKeyword);
        bool isInternal = modifiers.Any(SyntaxKind.InternalKeyword);
        bool isPublic = modifiers.Any(SyntaxKind.PublicKeyword);
        if (isPublic)
        {
            return 0;
        }

        if (isProtected && isInternal)
        {
            return 1;
        }

        if (isPrivate && isProtected)
        {
            return 4;
        }

        if (isProtected)
        {
            return 2;
        }

        if (isInternal)
        {
            return 3;
        }

        if (isPrivate)
        {
            return 5;
        }

        return isInterface ? 0 : 5;
    }

    private static int GetTypeAccessRank(MemberDeclarationSyntax member)
    {
        SyntaxTokenList modifiers = GetModifiers(member);
        if (modifiers.Any(SyntaxKind.PublicKeyword))
        {
            return 0;
        }

        if (modifiers.Any(SyntaxKind.FileKeyword) || modifiers.Any(SyntaxKind.InternalKeyword))
        {
            return 1;
        }

        if (modifiers.Any(SyntaxKind.ProtectedKeyword) && modifiers.Any(SyntaxKind.InternalKeyword))
        {
            return 1;
        }

        return 2;
    }

    private static bool IsStatic(MemberDeclarationSyntax member)
    {
        SyntaxTokenList modifiers = GetModifiers(member);
        return modifiers.Any(SyntaxKind.StaticKeyword) || modifiers.Any(SyntaxKind.ConstKeyword);
    }

    private static SyntaxTokenList GetModifiers(MemberDeclarationSyntax member) => member switch
    {
        BaseFieldDeclarationSyntax field => field.Modifiers,
        BaseMethodDeclarationSyntax method => method.Modifiers,
        BasePropertyDeclarationSyntax property => property.Modifiers,
        BaseTypeDeclarationSyntax type => type.Modifiers,
        DelegateDeclarationSyntax @delegate => @delegate.Modifiers,
        _ => default
    };

    private static string? GetNestedTypeKey(MemberDeclarationSyntax member)
        => IsType(member) ? GetTypeKey(member) : null;

    private static string GetTypeKey(MemberDeclarationSyntax member)
    {
        string kind = member.Kind().ToString();
        string name = GetTypeName(member);
        int arity = member switch
        {
            TypeDeclarationSyntax type => type.TypeParameterList?.Parameters.Count ?? 0,
            DelegateDeclarationSyntax @delegate => @delegate.TypeParameterList?.Parameters.Count ?? 0,
            _ => 0
        };
        return $"{kind}:{name}`{arity}";
    }

    private static string GetTypeName(MemberDeclarationSyntax member) => member switch
    {
        BaseTypeDeclarationSyntax type => type.Identifier.ValueText,
        DelegateDeclarationSyntax @delegate => @delegate.Identifier.ValueText,
        _ => string.Empty
    };

    private SyntaxList<UsingDirectiveSyntax> OrderUsings(SyntaxList<UsingDirectiveSyntax> directives)
    {
        List<UsingDirectiveSyntax> result = [];
        for (int index = 0; index < directives.Count;)
        {
            if (HasDirectives(directives[index]))
            {
                result.Add(directives[index++]);
                continue;
            }

            int end = index;
            while (end < directives.Count && !HasDirectives(directives[end]))
            {
                end++;
            }

            UsingDirectiveSyntax[] run = directives.Skip(index).Take(end - index).ToArray();
            UsingDirectiveSyntax[] ordered = run
                .OrderBy(static directive => directive.GlobalKeyword.IsKind(SyntaxKind.GlobalKeyword) ? 0 : 1)
                .ThenBy(static directive => IsSystemUsing(directive) ? 0 : 1)
                .ThenBy(static directive => GetUsingSortName(directive), StringComparer.Ordinal).ToArray();
            ordered = PreserveLeadingTrivia(run, ordered);
            result.AddRange(AddUsingGroupSpacing(ordered));
            index = end;
        }

        return SyntaxFactory.List(result);
    }

    private UsingDirectiveSyntax[] AddUsingGroupSpacing(UsingDirectiveSyntax[] ordered)
    {
        for (int index = 1; index < ordered.Length; index++)
        {
            if (IsSystemUsing(ordered[index - 1]) == IsSystemUsing(ordered[index]))
            {
                continue;
            }

            SyntaxTriviaList leading = ordered[index].GetLeadingTrivia();
            ordered[index] = ordered[index].WithLeadingTrivia(CreateGroupBoundaryTrivia(leading));
        }

        return ordered;
    }

    private SyntaxTriviaList CreateGroupBoundaryTrivia(SyntaxTriviaList leading)
    {
        int lastLineBreak = leading.ToList().FindLastIndex(static trivia => trivia.IsKind(SyntaxKind.EndOfLineTrivia));
        string indentation = string.Concat(leading
            .Skip(lastLineBreak + 1)
            .Where(static trivia => trivia.IsKind(SyntaxKind.WhitespaceTrivia))
            .Select(static trivia => trivia.ToFullString()));
        List<SyntaxTrivia> result = [SyntaxFactory.EndOfLine(_lineEnding)];
        foreach (SyntaxTrivia trivia in leading.Where(static trivia => !trivia.IsKind(SyntaxKind.WhitespaceTrivia) && !trivia.IsKind(SyntaxKind.EndOfLineTrivia)))
        {
            result.Add(trivia);
            result.Add(SyntaxFactory.EndOfLine(_lineEnding));
        }

        if (indentation.Length != 0)
        {
            result.Add(SyntaxFactory.Whitespace(indentation));
        }

        return SyntaxFactory.TriviaList(result);
    }

    private sealed record MemberOrder(
        MemberDeclarationSyntax Member,
        int Index,
        int Rank,
        int AccessRank,
        bool IsStatic);

    private sealed class MemberOrderGroup(MemberOrder[] items)
    {
        internal MemberOrder[] Items { get; } = items;
        internal int Rank => Items[0].Rank;
        internal int AccessRank => Items[0].AccessRank;
        internal bool IsStatic => Items[0].IsStatic;
        internal int FirstIndex => Items[0].Index;
    }

    private sealed record TypeOrder(
        MemberDeclarationSyntax Type,
        int Index,
        string Key,
        int AccessRank,
        bool IsMain);

    private sealed class TypeOrderGroup(TypeOrder[] items)
    {
        internal TypeOrder[] Items { get; } = items;
        internal int AccessRank => Items[0].AccessRank;
        internal bool IsMain => Items.Any(static item => item.IsMain);
        internal int FirstIndex => Items[0].Index;
    }
}
