    internal static string Render(IterationRenderModel model)
    {
        IterationModel shape = model.Shape;
        string? contracts = model.RenderContracts && !shape.OrderedQueryReceiver && !shape.IsFunctor && shape.ComponentModels.Length > 0
            ? RenderContracts(model)
            : null;
        string? stampWriter = !shape.OrderedQueryReceiver && shape.ComponentModels.Count(static component => component.IsWrite) > 1 && !UsesDenseBinding(shape)
            ? RenderArchetypeStampWriter(shape)
            : null;
        string? invoker = shape.Parallel || shape.HasEntityTarget
            ? RenderParallelInvoker(shape)
            : null;
        string extension = GeneratorTemplates.ExtensionTemplate(
            $"DemandForEachExtensions_{GeneratorSupport.StableName(shape.Key)}",
            shape.IsFunctor,
            RenderExtensionsBody(model));
        string? componentSetKey = !shape.OrderedQueryReceiver && !shape.HasQuery && !shape.Api.Signature.HasExplicitIds
            ? GeneratorTemplates.PrimaryComponentSetKeyDeclaration(shape.Api.Selector.Arity)
            : null;
        string[] members = new[] { componentSetKey, contracts, stampWriter, invoker, extension }
            .OfType<string>()
            .ToArray();
        ImmutableArray<string> usings = ImmutableArray.Create("using System;")
            .AddRange(GeneratorSupport.EcsNamespaceUsings(shape.Namespace));
        return GeneratorTemplates.FileTemplate(new GeneratedFileModel(
            shape.Namespace,
            usings,
            members.ToImmutableArray()));
    }

    private static string RenderContracts(IterationRenderModel model)
    {
        IterationModel shape = model.Shape;
        SignatureProjection slots = shape.Api.Signature;
        string generic = slots.GenericList();
        string parameters = slots.ComponentParameters();
        string suffix = IsAllWrite(shape.ComponentModels) ? string.Empty : "_" + shape.Pattern;
        string entityParameter = model.SupportsScoped ? "scoped EntityRef entity" : "EntityRef entity";
        IEnumerable<string> contracts = new[]
        {
            AppendContract("ForEachAction" + suffix, generic, parameters),
            AppendContract("ForEachEntityAction" + suffix, generic, SignatureProjection.JoinParameters(entityParameter, parameters)),
        }.Concat(model.SupportedContextModes
            .SelectMany(mode =>
            {
                string context = SignatureProjection.ContextParameter(mode, "TContext", "context");
                string contextGeneric = SignatureProjection.JoinGeneric("TContext", generic);
                string modeSuffix = ContextDelegateSuffix(mode);
                return new[]
                {
                    AppendContract("ForEachContextAction" + modeSuffix + suffix, contextGeneric, SignatureProjection.JoinParameters(context, parameters)),
                    AppendContract(
                        "ForEachContextEntityAction" + modeSuffix + suffix,
                        contextGeneric,
                        SignatureProjection.JoinParameters(SignatureProjection.JoinParameters(context, entityParameter), parameters)),
                };
            }));
        return string.Join("\n", contracts) + "\n";
    }

    private static string AppendContract(string name, string generic, string parameters)
        => $"public delegate void {SignatureProjection.TypeWithArguments(name, generic)}({parameters});";

    private static string RenderArchetypeStampWriter(IterationModel shape)
    {
        string name = ArchetypeStampWriterName(shape);
        int[] writes = GeneratorTemplates.WriteIndices(shape.ComponentModels).ToArray();
        string fields = GeneratorTemplates.JoinNonEmpty(writes.Select(index => $"private readonly int _access{index};"));
        string constructorParameters = string.Join(", ", writes.Select(index => $"int access{index}"));
        string assignments = GeneratorTemplates.JoinNonEmpty(writes.Select(index => $"_access{index} = access{index};"));
        string increments = GeneratorTemplates.JoinNonEmpty(writes.Select(index =>
            $"GeneratedForEachRuntime.IncrementArchetypeStamp(stamps, _access{index});"));
        return $$"""
            [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
            internal struct {{name}} : IGeneratedArchetypeStampWriter
            {
            {{fields}}

                internal {{name}}({{constructorParameters}})
                {
            {{assignments}}
                }

                [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]
                void IGeneratedArchetypeStampWriter.Write(Stamp[] stamps)
                {
            {{increments}}
                }
            }
            """;
    }

    private static string RenderParallelInvoker(IterationModel shape)
    {
        SignatureProjection slots = shape.Api.Signature;
        string generic = slots.HasGenericSelectors ? slots.GenericList() : string.Empty;
        string stateGeneric = StateGeneric(shape, generic);
        string name = ParallelInvokerName(shape);
        string actionType = ActionType(shape);
        string rows = shape.IsStamp
            ? string.Empty
            : GeneratorTemplates.JoinNonEmpty(GeneratorTemplates.Indexed(shape.ComponentModels.Length, index =>
            {
                string componentType = shape.ComponentModels[index].TypeName;
                return $"ref {componentType} row{index} = ref slots.GetGeneratedReadReference<{componentType}>(_access{index});";
            }));
        string entityBase = string.Empty;
        string invocation = AppendClosedInvocation(shape, "_action", "_functor", "_context", shape.IsStamp ? "component" : "row", "entity");
        string loopBody;
        string visitHelpers = string.Empty;
        if (shape.IsStamp)
        {
            string entity = shape.HasEntity
                ? "EntityRef entity = slots.GetEntityRef(index);"
                : string.Empty;
            string components = GeneratorTemplates.JoinNonEmpty(GeneratorTemplates.Indexed(shape.ComponentModels.Length, index =>
                $"Stamp component{index} = slots.GetGeneratedStamp(_access{index}, index);"));
            loopBody = $$"""
                    for (int index = 0; index < count; index++)
                    {
            {{entity}}
                        {{components}}
                        {{invocation}};
                    }
            """;
        }
        else
        {
            if (shape.HasEntity)
            {
                var loopLines = new List<string>
                {
                    "for (int index = 0; index < count; index++)",
                    "{",
                    "    EntityRef entity = slots.GetEntityRef(index);"
                };
                loopLines.AddRange(GeneratorTemplates.Indexed(shape.ComponentModels.Length, index =>
                    $"    ref {shape.ComponentModels[index].TypeName} current{index} = ref global::System.Runtime.CompilerServices.Unsafe.Add(ref row{index}, slots.GetGeneratedRowOffset(index));"));
                loopLines.Add("    " + AppendClosedInvocation(
                    shape,
                    "_action",
                    "_functor",
                    "_context",
                    "current",
                    "entity",
                    index => $"current{index}") + ";");
                loopLines.Add("}");
                loopBody = AppendParallelTagSelectionLoop(
                    shape,
                    loopLines,
                    "_context",
                    "_action",
                    "_functor",
                    "row");
            }
            else
            {
                var cursors = new List<(string TypeName, string Name)>();

                for (int index = 0; index < shape.ComponentModels.Length; index++)
                {
                    cursors.Add((shape.ComponentModels[index].TypeName, $"row{index}"));
                }

                (string visitRefParameters, string visitRefArguments) = BuildVisitRefLists(cursors);
                var leading = new List<string>();
                var leadingArgs = new List<string>();
                if (shape.HasContext)
                {
                    leading.Add(SignatureProjection.ContextParameter(shape.ContextMode, ContextType(shape), "context"));
                    leadingArgs.Add(SignatureProjection.ContextArgument(shape.ContextMode, "_context"));
                }

                if (shape.IsFunctor)
                {
                    leading.Add(SignatureProjection.ContextParameter(shape.FunctorPassMode, shape.FunctorType!, "functor"));
                    leadingArgs.Add(SignatureProjection.ContextArgument(shape.FunctorPassMode, "_functor"));
                }
                else
                {
                    leading.Add($"{actionType} action");
                    leadingArgs.Add("_action");
                }

                var loopLines = new List<string>();
                var visitMethods = new List<string>();
                AppendUnrolledDenseSlotLoop(
                    loopLines,
                    visitMethods,
                    "                    ",
                    "        ",
                    "count",
                    visitRefParameters,
                    visitRefArguments,
                    (stepLines, stepIndent, offset, pin) =>
                    {
                        string invocation = AppendClosedInvocation(
                            shape,
                            "action",
                            "functor",
                            "context",
                            "row",
                            string.Empty,
                            index => AtOffset(pin("row" + index), offset));
                        stepLines.Add($"{stepIndent}{invocation};");
                    },
                    (advanceLines, advanceIndent, advance) =>
                    {
                        advanceLines.AddRange(GeneratorTemplates.Indexed(shape.ComponentModels.Length, index =>
                            $"{advanceIndent}row{index} = ref {UnsafeAdd($"row{index}", advance)};"));
                    },
                    visitLeadingParameters: string.Join(", ", leading),
                    visitLeadingArguments: string.Join(", ", leadingArgs));
                loopBody = string.Join("\n", loopLines);
                visitHelpers = string.Join("\n", visitMethods);
                loopBody = AppendParallelTagSelectionLoop(
                    shape,
                    loopLines,
                    "_context",
                    "_action",
                    "_functor",
                    "row");
            }
        }

        if (shape.IsStamp)
        {
            loopBody = AppendParallelStampTagSelectionLoop(shape, loopBody, "_context", "_action", "_functor");
        }

        return $$"""
            internal struct {{name}}{{stateGeneric}} : IGeneratedParallelInvoker
            {
            {{AppendInvokerFields(shape, actionType)}}
            {{AppendInvokerConstructor(shape, name, actionType)}}

                public bool RequiresSingleThread => {{(shape.ContextMode == ContextModeKind.Ref ? "true" : "false")}};

                [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]
                public void Invoke(ref GeneratedQuerySlots slots)
                {
            {{rows}}
            {{entityBase}}
                    int count = slots.Count;
            {{loopBody}}
                }
            {{visitHelpers}}
            {{AppendInvokerProperties(shape)}}
            }
            """;
    }

    private static string AppendInvokerFields(IterationModel shape, string actionType)
    {
        string context = shape.HasContext
            ? $"private {ContextType(shape)} _context;"
            : string.Empty;
        string callback = shape.IsFunctor
            ? $"private {shape.FunctorType} _functor;"
            : $"private readonly {actionType} _action;";
        return GeneratorTemplates.JoinNonEmpty(new[] { context, callback }
            .Concat(GeneratorTemplates.Indexed(shape.ComponentModels.Length,
                index => $"private readonly int _access{index};")));
    }

    private static string AppendInvokerConstructor(
        IterationModel shape,
        string name,
        string actionType)
    {
        string[] parameters = new[]
            {
                shape.HasContext ? $"{ContextType(shape)} context" : string.Empty,
                shape.IsFunctor ? $"{shape.FunctorType} functor" : $"{actionType} action",
                shape.Api.Signature.AccessParameters(tokens: true)
            }
            .Where(static parameter => parameter.Length != 0)
            .ToArray();

        string[] assignments = new[]
            {
                shape.HasContext ? "_context = context;" : string.Empty,
                shape.IsFunctor ? "_functor = functor;" : "_action = action;"
            }
            .Concat(GeneratorTemplates.Indexed(shape.ComponentModels.Length, index =>
                $"_access{index} = GeneratedForEachRuntime.Get{(shape.ComponentModels[index].IsWrite ? "Write" : "Read")}QueryComponentIndex(access{index});"))
            .Where(static assignment => assignment.Length != 0)
            .ToArray();

        return $$"""
                internal {{ConstructorName(name)}}({{string.Join(", ", parameters)}})
                {
            {{GeneratorTemplates.JoinNonEmpty(assignments)}}
                }
            """;
    }

    private static string AppendInvokerProperties(IterationModel shape)
        => GeneratorTemplates.JoinNonEmpty([
            shape.HasContext ? $"internal {ContextType(shape)} Context => _context;" : string.Empty,
            shape.IsFunctor ? $"internal {shape.FunctorType} Functor => _functor;" : string.Empty
        ]);

    private static string RenderClosedParallelMethod(
        IterationModel shape,
        string methodName,
        string componentParameters)
    {
        SignatureProjection slots = shape.Api.Signature;
        string generic = slots.HasGenericSelectors ? slots.GenericList() : string.Empty;
        string genericPrefix = StateGeneric(shape, generic);
        string contextParameter = shape.HasContext
            ? $", {SignatureProjection.ContextParameter(shape.ContextMode, ContextType(shape), "context")}"
            : string.Empty;
        string callbackParameter = shape.IsFunctor
            ? ", " + SignatureProjection.ContextParameter(shape.FunctorPassMode, shape.FunctorType!, "functor")
            : $", {ActionType(shape)} action";
        string invokerType = $"{ParallelInvokerName(shape)}{StateGeneric(shape, generic)}";
        string target = shape.HasEntityTarget
            ? ", global::System.ReadOnlySpan<Entity> entities, in Query query"
            : ", in Query query";
        string arguments = string.Join(", ", new[]
        {
            shape.HasContext ? "context" : null,
            shape.IsFunctor ? "functor" : "action",
            slots.AccessArguments(),
        }.Where(static value => !string.IsNullOrEmpty(value)));
        string execute = shape.HasEntityTarget
            ? "GeneratedForEachRuntime.ExecuteEntityListParallel(world, in query, entities, ref invoker, "
            : "GeneratedForEachRuntime.ExecuteParallelDense(world, in query, ref invoker, ";
        string body = $"""
                {(slots.HasDynamicIds ? $"GeneratedForEachRuntime.ValidateComponentIdCount(componentIds, {slots.Arity});" : string.Empty)}
                {GeneratorTemplates.Indent(AccessSetup(shape), "    ")}
                var invoker = new {invokerType}({arguments});
                {execute}{AppendParallelWriteIndices(shape)}, workerCount);
                {(shape is { HasContext: true, ContextMode: ContextModeKind.Ref } ? "context = invoker.Context;" : string.Empty)}
                {(shape is { IsFunctor: true, FunctorPassMode: ContextModeKind.Ref } ? "functor = invoker.Functor;" : string.Empty)}
            """;
        string signature = $"private static void {methodName}{genericPrefix}(World world{target}{componentParameters}{contextParameter}{callbackParameter}, int workerCount)";
        return GeneratorTemplates.Indent(GeneratorTemplates.RenderBlock(
            $"""
                [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]
                {signature}
                """.Trim(),
            body), "    ");
    }

    private static string AppendParallelWriteIndices(IterationModel shape)
    {
        if (!shape.ComponentModels.Any(static component => component.IsWrite))
        {
            return "global::System.ReadOnlySpan<int>.Empty";
        }

        string indices = string.Join(", ", GeneratorTemplates.WriteIndices(shape.ComponentModels)
            .Select(index => $"global::Delta.ECS.GeneratedForEachRuntime.GetWriteQueryComponentIndex(access{index})"));
        return $$"""stackalloc int[] { {{indices}} }""";
    }

    private static int StableProfileMethodId(string methodName)
    {
        unchecked
        {
            uint hash = FnvOffsetBasis;
            foreach (char character in methodName)
            {
                hash ^= character;
                hash *= FnvPrime;
            }

            return (int)(hash & 0x7FFF_FFFF);
        }
    }

    private static string AppendClosedInvocation(
        IterationModel shape,
        string actionName,
        string functorName,
        string contextName,
        string componentPrefix,
        string entityExpression,
        Func<int, string>? componentExpression = null)
    {
        var invocationArguments = new List<string>();
        if (shape.HasContext)
        {
            invocationArguments.Add(SignatureProjection.ContextArgument(shape.ContextMode, contextName));
        }

        if (shape.HasEntity)
        {
            invocationArguments.Add(entityExpression);
        }

        SignatureProjection slots = shape.Api.Signature;
        if (componentExpression is null)
        {
            string componentArguments = slots.ComponentArguments(componentPrefix);
            if (componentArguments.Length != 0)
            {
                invocationArguments.Add(componentArguments);
            }
        }
        else
        {
            for (int index = 0; index < slots.Arity; index++)
            {
                invocationArguments.Add(slots.ComponentArgument(index, componentExpression(index)));
            }
        }

        string invocation = shape.IsFunctor ? $"{functorName}.Invoke" : actionName;
        return $"{invocation}({string.Join(", ", invocationArguments)})";
    }

    private static string UnsafeAdd(string refExpression, string offsetExpression)
        => $"global::System.Runtime.CompilerServices.Unsafe.Add(ref {refExpression}, {offsetExpression})";

    private static string UnsafeAdd(string refExpression, int offset)
        => UnsafeAdd(refExpression, offset.ToString(CultureInfo.InvariantCulture));

    private static string AtOffset(string refExpression, int offset)
        => offset == 0 ? refExpression : UnsafeAdd(refExpression, offset);

    private static (string Parameters, string Arguments) BuildVisitRefLists(
        IReadOnlyList<(string TypeName, string Name)> cursors)
    {
        if (cursors.Count == 0)
        {
            return (string.Empty, string.Empty);
        }

        return (
            string.Join(", ", cursors.Select(static cursor => $"ref {cursor.TypeName} {cursor.Name}")),
            string.Join(", ", cursors.Select(static cursor => $"ref {cursor.Name}")));
    }

    /// <summary>
    /// Emits the dense unroll loop into <paramref name="loopLines"/> and private static
    /// Visit1/2/4 helpers into <paramref name="visitMethods"/> (constant offsets 0..3).
    /// Fast path peels on <c>(count &amp; ~3) != 0</c> (tst-friendly). Cursor refs are
    /// pinned into locals <c>b0..bn</c> for the Visit4 do-while so the JIT keeps stable
    /// base registers; locals advance by 4 at the end of each iteration and write back
    /// into the original cursors for the remainder tail. Remainder uses an if/else
    /// cascade (not <c>switch</c>) to avoid a jump table. Visit2/Visit4 call the action
    /// with direct <c>Unsafe.Add</c> offsets — no temporary slot refs inside Visit*.
    /// </summary>
    private static void AppendUnrolledDenseSlotLoop(
        List<string> loopLines,
        List<string> visitMethods,
        string loopIndent,
        string visitMethodIndent,
        string countName,
        string visitRefParameters,
        string visitRefArguments,
        Action<List<string>, string, int, Func<string, string>> emitStep,
        Action<List<string>, string, int> emitAdvance,
        string visitLeadingParameters = "",
        string visitLeadingArguments = "",
        string visitMethodGenerics = "",
        bool isolateSteps = false)
    {
        string visitParameters = string.IsNullOrEmpty(visitLeadingParameters)
            ? visitRefParameters
            : string.IsNullOrEmpty(visitRefParameters)
                ? visitLeadingParameters
                : visitLeadingParameters + ", " + visitRefParameters;

        string[] cursorNames = string.IsNullOrEmpty(visitRefArguments)
            ? []
            : visitRefArguments.Split([", "], StringSplitOptions.None)
                .Select(static part => part.StartsWith("ref ", StringComparison.Ordinal) ? part.Substring(4) : part)
                .ToArray();

        string ShiftedCursorArguments(string[] names, int shift)
        {
            if (names.Length == 0)
            {
                return string.Empty;
            }

            if (shift == 0)
            {
                return string.Join(", ", names.Select(static name => $"ref {name}"));
            }

            return string.Join(", ", names.Select(name => "ref " + UnsafeAdd(name, shift)));
        }

        string Call(string name, string[] names, int cursorShift = 0)
        {
            string cursors = ShiftedCursorArguments(names, cursorShift);
            string args = string.IsNullOrEmpty(visitLeadingArguments)
                ? cursors
                : string.IsNullOrEmpty(cursors)
                    ? visitLeadingArguments
                    : visitLeadingArguments + ", " + cursors;
            return $"{name}({args})";
        }

        Func<string, string> pinIdentity = static name => name;

        void EmitVisitMethod(int times, string functionName)
        {
            visitMethods.Add($"{visitMethodIndent}[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
            visitMethods.Add($"{visitMethodIndent}private static void {functionName}{visitMethodGenerics}({visitParameters})");
            visitMethods.Add($"{visitMethodIndent}{{");
            for (int step = 0; step < times; step++)
            {
                if (isolateSteps)
                {
                    visitMethods.Add($"{visitMethodIndent}    {{");
                    emitStep(visitMethods, visitMethodIndent + "        ", step, pinIdentity);
                    visitMethods.Add($"{visitMethodIndent}    }}");
                }
                else
                {
                    emitStep(visitMethods, visitMethodIndent + "    ", step, pinIdentity);
                }
            }

            visitMethods.Add($"{visitMethodIndent}}}");
            visitMethods.Add(string.Empty);
        }

        EmitVisitMethod(1, "Visit1");
        EmitVisitMethod(2, "Visit2");
        EmitVisitMethod(4, "Visit4");

        loopLines.Add($"{loopIndent}#pragma warning disable CS8619 // Unsafe.Add returns a maybe-null ref for unconstrained T; this loop only advances the reference.");
        loopLines.Add($"{loopIndent}if (({countName} & ~3) != 0)");
        loopLines.Add($"{loopIndent}{{");
        loopLines.Add($"{loopIndent}    int loops = {countName} >> 2;");
        string[] hotNames = cursorNames;
        if (cursorNames.Length > 0)
        {
            hotNames = new string[cursorNames.Length];
            for (int index = 0; index < cursorNames.Length; index++)
            {
                string local = "b" + index.ToString(CultureInfo.InvariantCulture);
                hotNames[index] = local;
                loopLines.Add($"{loopIndent}    ref var {local} = ref {cursorNames[index]};");
            }
        }

        loopLines.Add($"{loopIndent}    do");
        loopLines.Add($"{loopIndent}    {{");
        loopLines.Add($"{loopIndent}        {Call("Visit4", hotNames)};");
        for (int index = 0; index < hotNames.Length; index++)
        {
            loopLines.Add($"{loopIndent}        {hotNames[index]} = ref {UnsafeAdd(hotNames[index], 4)};");
        }

        if (hotNames.Length == 0)
        {
            emitAdvance(loopLines, loopIndent + "        ", 4);
        }

        loopLines.Add($"{loopIndent}        loops--;");
        loopLines.Add($"{loopIndent}    }} while (loops != 0);");
        if (cursorNames.Length > 0)
        {
            for (int index = 0; index < cursorNames.Length; index++)
            {
                loopLines.Add($"{loopIndent}    {cursorNames[index]} = ref {hotNames[index]};");
            }
        }

        loopLines.Add($"{loopIndent}}}");
        loopLines.Add($"{loopIndent}#pragma warning restore CS8619");
        loopLines.Add($"{loopIndent}int remaining = {countName} & 3;");
        loopLines.Add($"{loopIndent}if (remaining != 0)");
        loopLines.Add($"{loopIndent}{{");
        loopLines.Add($"{loopIndent}    if (remaining == 1)");
        loopLines.Add($"{loopIndent}    {{");
        loopLines.Add($"{loopIndent}        {Call("Visit1", cursorNames)};");
        loopLines.Add($"{loopIndent}    }}");
        loopLines.Add($"{loopIndent}    else if (remaining == 2)");
        loopLines.Add($"{loopIndent}    {{");
        loopLines.Add($"{loopIndent}        {Call("Visit2", cursorNames)};");
        loopLines.Add($"{loopIndent}    }}");
        loopLines.Add($"{loopIndent}    else");
        loopLines.Add($"{loopIndent}    {{");
        loopLines.Add($"{loopIndent}        {Call("Visit2", cursorNames)};");
        loopLines.Add($"{loopIndent}        {Call("Visit1", cursorNames, cursorShift: 2)};");
        loopLines.Add($"{loopIndent}    }}");
        loopLines.Add($"{loopIndent}}}");
    }

    private static string RenderExtensionsBody(IterationRenderModel model)
    {
        IterationModel shape = model.Shape;
        if (shape.OrderedQueryReceiver)
        {
            string orderedClosedMethodName = "ExecuteClosed_" + GeneratorSupport.StableName(shape.Key);
            string orderedClosedMethod = RenderClosedDenseMethod(shape, orderedClosedMethodName, shape.Api.Signature.HasExplicitIds
                ? ", " + shape.Api.Signature.ComponentIdParameters("componentId")
                : string.Empty);
            return RenderDenseBinding(shape) + "\n" + orderedClosedMethod + "\n" + RenderOrderedExtensionsBody(shape);
        }

        SignatureProjection slots = shape.Api.Signature;
        string className = "DemandForEachExtensions_" + GeneratorSupport.StableName(shape.Key);
        string generic = slots.HasGenericSelectors ? slots.GenericList() : string.Empty;
        string ids = slots.HasExplicitIds ? slots.ComponentIdParameters("componentId") : string.Empty;
        string stateGeneric = StateGeneric(shape, generic);
        string callback = ActionType(shape);
        string componentParameters = slots.HasExplicitIds ? ", " + slots.ComponentIdParameters("componentId") : string.Empty;
        string prefix = shape.HasEntityTarget
            ? "this World world, global::System.ReadOnlySpan<Entity> entities"
            : "this World world";
        string query = shape.HasQuery ? ", in Query query" : string.Empty;
        string contextParameter = shape.HasContext
            ? ", " + SignatureProjection.ContextParameter(shape.ContextMode, ContextType(shape), "context")
            : string.Empty;
        string closedMethodName = "ExecuteClosed_" + GeneratorSupport.StableName(shape.Key);
        string closed = shape.Parallel
            ? RenderClosedParallelMethod(shape, closedMethodName, componentParameters)
            : RenderClosedDenseMethod(shape, closedMethodName, componentParameters);
        string extension = RenderExtensionMethod(
            shape,
            prefix,
            query,
            contextParameter,
            ids,
            callback,
            stateGeneric,
            className,
            model.Profiling,
            closedMethodName);
        string operationInvoker = RenderOperationInvoker(
            shape,
            closedMethodName,
            model.Profiling,
            StableProfileMethodId(className + "." + shape.MethodName));
        return RenderDenseBinding(shape) + "\n" + closed + "\n" + operationInvoker + "\n" + extension;
    }

    private static string RenderOrderedExtensionsBody(IterationModel shape)
    {
        SignatureProjection slots = shape.Api.Signature;
        string generic = slots.HasGenericSelectors ? slots.GenericList() : string.Empty;
        string stateGeneric = StateGeneric(shape, generic);
        string whereGeneric = shape.OrderedWhereSource is { } whereSource
            ? GeneratedWhereTemplates.ViewMethodTypeParameters(whereSource)
            : string.Empty;
        string methodGeneric = SignatureProjection.TypeArguments(
            SignatureProjection.JoinGeneric(stateGeneric.Trim('<', '>'), whereGeneric));
        string receiverType = shape.OrderedWhereSource is { } orderedWhereSource
            ? GeneratedWhereTemplates.OrderedViewTypeName(orderedWhereSource)
                + GeneratedWhereTemplates.ViewMethodTypeArguments(orderedWhereSource)
            : "OrderedQuery";
        string ids = slots.HasExplicitIds ? slots.ComponentIdParameters("componentId") : string.Empty;
        string context = shape.HasContext
            ? SignatureProjection.ContextParameter(shape.ContextMode, ContextType(shape), "context")
            : string.Empty;
        string callback = shape.IsFunctor
            ? SignatureProjection.ContextParameter(shape.FunctorPassMode, shape.FunctorType!, "functor")
            : ActionType(shape) + " action";
        var parameters = new List<string> { "this " + receiverType + " orderedQuery" };
        if (ids.Length != 0)
        {
            parameters.Add(ids);
        }

        if (context.Length != 0)
        {
            parameters.Add(context);
        }

        parameters.Add(callback);
        string visibility = shape.IsFunctor || shape.ImplicitComponents ? "internal" : "public";
        string signature = $"{visibility} static {OperationType(shape)} {shape.MethodName}{methodGeneric}({string.Join(", ", parameters)})";
        string closedMethod = "ExecuteClosed_" + GeneratorSupport.StableName(shape.Key);
        bool mutableContext = shape.HasContext && shape.ContextMode == ContextModeKind.Ref;
        var setup = new List<string> { "var operationOrderedQuery = orderedQuery;" };
        if (slots.HasDynamicIds)
        {
            setup.Add("global::Delta.ECS.ComponentId[] operationComponentIds = componentIds.ToArray();");
        }

        var invokerArguments = new List<string> { "operationOrderedQuery" };
        if (slots.HasDynamicIds)
        {
            invokerArguments.Add("operationComponentIds");
        }
        else if (slots.HasExplicitIds)
        {
            invokerArguments.Add(slots.ComponentIdArguments("componentId"));
        }

        if (shape.HasContext && !mutableContext)
        {
            invokerArguments.Add("context");
        }

        if (!shape.IsFunctor)
        {
            invokerArguments.Add("action");
        }

        if (shape.Parallel)
        {
            invokerArguments.Add("workerCount");
        }

        string invoker = $"new {OperationInvokerType(shape)}({string.Join(", ", invokerArguments)})";
        string operation = (mutableContext, shape.IsFunctor) switch
        {
            (true, true) => $"new {OperationType(shape)}(context, functor, {invoker})",
            (true, false) => $"new {OperationType(shape)}(context, {invoker})",
            (false, true) => $"new {OperationType(shape)}(functor, {invoker})",
            _ => $"new {OperationType(shape)}({invoker})"
        };
        setup.Add($"return {operation};");
        string body = GeneratorTemplates.RenderBlock(string.Empty, string.Join("\n", setup));
        string operationInvoker = RenderOrderedOperationInvoker(shape, closedMethod);
        string extension = GeneratorTemplates.Indent(
            RenderMethod(
                GeneratorTemplates.Documentation(shape.Api),
                signature,
                body,
                null),
            "    ");
        return operationInvoker + "\n" + extension;
    }

