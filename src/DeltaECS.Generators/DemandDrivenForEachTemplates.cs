    private static string RenderClosedDenseMethod(
        IterationModel shape,
        string methodName,
        string componentParameters)
    {
        bool bound = UsesDenseBinding(shape);
        SignatureProjection slots = shape.Api.Signature;
        string generic = slots.HasGenericSelectors ? slots.GenericList() : string.Empty;
        string genericPrefix = StateGeneric(shape, generic);
        string contextParameter = shape.HasContext
            ? ", " + SignatureProjection.ContextParameter(shape.ContextMode, ContextType(shape), "context")
            : string.Empty;
        string callbackParameter = shape.IsFunctor
            ? ", " + SignatureProjection.ContextParameter(shape.FunctorPassMode, shape.FunctorType!, "functor")
            : ", " + ActionType(shape) + " action";
        string target = shape.HasEntityTarget ? ", global::System.ReadOnlySpan<Entity> entities, in Query query" : ", in Query query";
        bool copyRefContext = shape is { HasContext: true, ContextMode: ContextModeKind.Ref };
        string contextName = copyRefContext ? "contextCopy" : "context";
        string signature = $"private static void {methodName}{genericPrefix}(World world{target}{componentParameters}{contextParameter}{callbackParameter})";
        var lines = new List<string>
        {
            "[System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]",
            signature,
            "{",
            slots.HasDynamicIds
                ? $"    GeneratedForEachRuntime.ValidateComponentIdCount(componentIds, {slots.Arity});"
                : string.Empty,
            bound ? string.Empty : GeneratorTemplates.Indent(AccessSetup(shape).TrimEnd(), "    "),
        };
        var closedDenseVisitMethods = new List<string>();
        if (copyRefContext && !shape.HasEntityTarget)
        {
            lines.Add($"    {ContextType(shape)} contextCopy = context;");
        }
        if (shape.HasEntityTarget)
        {
            string invokerType = ParallelInvokerName(shape) + StateGeneric(shape, generic);
            string arguments = string.Join(", ", new[]
            {
                shape.HasContext ? "context" : null,
                shape.IsFunctor ? "functor" : "action",
                slots.AccessArguments(),
            }.Where(static value => !string.IsNullOrEmpty(value)));
            lines.Add($"    var invoker = new {invokerType}({arguments});");
            lines.Add($"    GeneratedForEachRuntime.ExecuteEntityList(world, in query, entities, ref invoker, {AppendParallelWriteIndices(shape)});");
            if (shape is { HasContext: true, ContextMode: ContextModeKind.Ref })
            {
                lines.Add("    context = invoker.Context;");
            }

            if (shape is { IsFunctor: true, FunctorPassMode: ContextModeKind.Ref })
            {
                lines.Add("    functor = invoker.Functor;");
            }
            lines.Add("}");
            return GeneratorTemplates.Indent(string.Join("\n", lines), "    ");
        }

        if (shape.IsFunctor)
        {
            lines.Add("    var action = functor;");
        }
        if (bound)
        {
            lines.Add("    " + OpenDenseBinding(shape, closed: false));
        }
        else if (shape.IsStamp)
        {
            lines.Add("    using var execution = GeneratedForEachRuntime.OpenReadDense(world, in query);");
        }
        else
        {
            lines.Add($"    using var execution = GeneratedForEachRuntime.{(shape.ComponentModels.Any(static component => component.IsWrite) ? "OpenWriteDense" : "OpenReadDense")}(world, in query);");
            lines.AddRange(SplitLines(AppendQueryComponentRoutes(shape, "    ")));
            lines.AddRange(SplitLines(AppendArchetypeWriteSetup(shape, "    ")));
        }
        if (bound)
        {
            lines.Add("    int chunkCount = execution.Rows.Length;");
            lines.Add("    ref var firstBatch = ref global::System.Runtime.InteropServices.MemoryMarshal.GetReference(execution.Rows);");
        }
        if (!shape.IsStamp)
        {
            for (int index = 0; index < shape.ComponentModels.Length; index++)
            {
                string type = ComponentType(shape, index);
                lines.Add($"    ref {type} component{index} = ref global::System.Runtime.CompilerServices.Unsafe.NullRef<{type}>();");
            }
        }

        bool usesReadSlots = shape.IsStamp || !shape.ComponentModels.Any(static component => component.IsWrite);
        var denseLoopLines = new List<string>();
        var visitMethods = new List<string>();
        if (!shape.IsStamp)
        {
            if (shape.HasEntity)
            {
                denseLoopLines.Add("for (int index = 0; index < count; index++)");
                denseLoopLines.Add("{");
                denseLoopLines.Add("    EntityRef entity = slots.GetEntityRef(index);");
                denseLoopLines.AddRange(GeneratorTemplates.Indexed(shape.ComponentModels.Length, index =>
                    $"    ref {ComponentType(shape, index)} current{index} = ref global::System.Runtime.CompilerServices.Unsafe.Add(ref component{index}, slots.GetGeneratedRowOffset(index));"));
                denseLoopLines.Add("    " + AppendClosedInvocation(
                    shape,
                    "action",
                    "action",
                    contextName,
                    "current",
                    "entity",
                    index => $"current{index}") + ";");
                denseLoopLines.Add("}");
            }
            else
            {
                var cursors = new List<(string TypeName, string Name)>();

                for (int index = 0; index < shape.ComponentModels.Length; index++)
                {
                    cursors.Add((ComponentType(shape, index), $"component{index}"));
                }

                (string visitRefParameters, string visitRefArguments) = BuildVisitRefLists(cursors);
                var leading = new List<string>();
                var leadingArgs = new List<string>();
                if (shape.HasContext)
                {
                    leading.Add(SignatureProjection.ContextParameter(shape.ContextMode, ContextType(shape), contextName));
                    leadingArgs.Add(SignatureProjection.ContextArgument(shape.ContextMode, contextName));
                }

                if (shape.IsFunctor)
                {
                    // Hot loop uses a local `action` copy so ref functors can write back after the loop.
                    leading.Add(SignatureProjection.ContextParameter(shape.FunctorPassMode, shape.FunctorType!, "action"));
                    leadingArgs.Add(SignatureProjection.ContextArgument(shape.FunctorPassMode, "action"));
                }
                else
                {
                    leading.Add($"{ActionType(shape)} action");
                    leadingArgs.Add("action");
                }

                AppendUnrolledDenseSlotLoop(
                    denseLoopLines,
                    visitMethods,
                    "        ",
                    string.Empty,
                    "count",
                    visitRefParameters,
                    visitRefArguments,
                    (stepLines, stepIndent, offset, pin) =>
                    {
                        string invocation = AppendClosedInvocation(
                            shape,
                            "action",
                            "action",
                            contextName,
                            "component",
                            string.Empty,
                            index => AtOffset(pin("component" + index), offset));
                        stepLines.Add($"{stepIndent}{invocation};");
                    },
                    (advanceLines, advanceIndent, advance) =>
                    {
                        advanceLines.AddRange(GeneratorTemplates.Indexed(shape.ComponentModels.Length,
                            index => $"{advanceIndent}component{index} = ref {UnsafeAdd($"component{index}", advance)};"));
                    },
                    visitLeadingParameters: string.Join(", ", leading),
                    visitLeadingArguments: string.Join(", ", leadingArgs),
                    visitMethodGenerics: genericPrefix);
            }
        }

        void AppendChunkLoop(bool filterTagSlots)
        {
            if (bound)
            {
                lines.Add("        int chunksRemaining = chunkCount;");
                lines.Add("        if (chunksRemaining > 0)");
                lines.Add("        {");
                lines.Add("            ref var batchCursor = ref firstBatch;");
                lines.Add("            do");
                lines.Add("            {");
                lines.Add("                ref var batch = ref batchCursor;");
                lines.Add("                int count = batch.Chunk.Count;");
            }
            else
            {
                lines.Add(shape.IsStamp || shape.HasEntity
                    ? "        while (execution.MoveNextTrusted(out var slots))"
                    : "        while (execution.MoveNextTrusted(out var componentRows, out int count))");
                lines.Add("        {");
            }

            if (!bound && (shape.IsStamp || shape.HasEntity))
            {
                lines.Add("            int count = slots.Count;");
            }

            for (int index = 0; index < shape.ComponentModels.Length; index++)
            {
                if (shape.IsStamp)
                {
                    continue;
                }

                string type = ComponentType(shape, index);
                lines.Add(bound
                    ? $"                component{index} = ref GeneratedForEachRuntime.GetGeneratedArrayReference(batch.Row{index});"
                    : shape.HasEntity
                    ? $"                component{index} = ref GeneratedForEachRuntime.GetGeneratedArrayReference(slots.GetGeneratedArray<{type}>(access{index}));"
                    : $"                component{index} = ref GeneratedForEachRuntime.GetGeneratedRow<{type}>(componentRows, route{index});");
            }

            if (shape.IsStamp)
            {
                lines.Add("            for (int index = 0; index < count; index++)");
                lines.Add("            {");
                if (shape.HasEntity)
                {
                    lines.Add("                EntityRef entity = slots.GetEntityRef(index);");
                }

                for (int index = 0; index < shape.ComponentModels.Length; index++)
                {
                    lines.Add($"                Stamp component{index} = slots.GetGeneratedStamp(access{index}, index);");
                }

                lines.Add("                " + AppendClosedInvocation(shape, "action", shape.IsFunctor ? "action" : "functor", contextName, "component", "entity") + ";");
                lines.Add("            }");
            }
            else if (filterTagSlots)
            {
                if (bound)
                {
                    AppendBoundTagSelectionLoop(lines, shape, contextName, denseLoopLines);
                }
                else
                {
                    AppendUnboundTagSelectionLoop(lines, shape, contextName, denseLoopLines, usesReadSlots);
                }
            }
            else
            {
                lines.AddRange(denseLoopLines);
            }

            if (bound)
            {
                lines.Add("                batchCursor = ref global::System.Runtime.CompilerServices.Unsafe.Add(ref batchCursor, 1);");
                lines.Add("                chunksRemaining--;");
                lines.Add("            } while (chunksRemaining != 0);");
                lines.Add("        }");
            }
            else
            {
                lines.Add("        }");
            }
        }

        if (!shape.IsStamp)
        {
            lines.Add("    if (execution.HasTagFilters)");
            lines.Add("    {");
            AppendChunkLoop(filterTagSlots: true);
            lines.Add("    }");
            lines.Add("    else");
            lines.Add("    {");
            AppendChunkLoop(filterTagSlots: false);
            lines.Add("    }");
        }
        else
        {
            AppendChunkLoop(filterTagSlots: false);
        }

        closedDenseVisitMethods = visitMethods;
        if (shape is { IsFunctor: true, FunctorPassMode: ContextModeKind.Ref })
        {
            lines.Add("    functor = action;");
        }
        if (copyRefContext)
        {
            lines.Add("    context = contextCopy;");
        }
        lines.Add("}");
        string closedMethod = GeneratorTemplates.Indent(string.Join("\n", lines), "    ");
        if (closedDenseVisitMethods.Count == 0)
        {
            return closedMethod;
        }

        string visitHelpers = string.Join("\n", closedDenseVisitMethods.Select(static line =>
            string.IsNullOrEmpty(line) ? line : "    " + line));
        return closedMethod + "\n\n" + visitHelpers;
    }

    private static string[] SplitLines(string text)
        => string.IsNullOrEmpty(text) ? Array.Empty<string>() : text.TrimEnd().Split(["\r\n", "\n"], StringSplitOptions.None);

    private static string RenderExtensionMethod(
        IterationModel shape,
        string prefix,
        string query,
        string contextParameter,
        string ids,
        string callback,
        string genericPrefix,
        string className,
        bool profiling,
        string closedMethodName)
    {
        string componentPart = string.IsNullOrEmpty(ids) ? string.Empty : $", {ids}";
        string methodName = shape.MethodName;
        string profileName = className + "." + methodName;
        string callbackName = shape.IsFunctor ? "functor" : "action";
        string callbackParameter = shape.IsFunctor
            ? ", " + SignatureProjection.ContextParameter(shape.FunctorPassMode, shape.FunctorType!, callbackName)
            : ", " + callback + " " + callbackName;
        string workerCountParameter = shape.Parallel ? ", int workerCount = 0" : string.Empty;
        string visibility = shape.IsFunctor || shape.ImplicitComponents ? "internal" : "public";
        string operationType = OperationType(shape);
        string signature = $"{visibility} static {operationType} {methodName}{genericPrefix}({prefix}{query}{componentPart}{contextParameter}{callbackParameter}{workerCountParameter})";
        string body = BuildDeferredBody(
            shape,
            profiling,
            StableProfileMethodId(profileName),
            closedMethodName);
        return GeneratorTemplates.Indent(
            RenderMethod(
                GeneratorTemplates.Documentation(shape.Api),
                signature,
                body,
                profiling ? profileName : null),
            "    ");
    }

    private static string OperationType(IterationModel shape)
        => OperationType(shape, OperationInvokerType(shape));

    private static string OperationType(IterationModel shape, string invoker, string? contextType = null)
    {
        string context = shape.HasContext ? contextType ?? ContextType(shape) : string.Empty;
        string functor = shape.IsFunctor ? shape.FunctorType! : string.Empty;
        bool mutableContext = shape.HasContext && shape.ContextMode == ContextModeKind.Ref;
        return (mutableContext, shape.IsFunctor) switch
        {
            (true, true) => $"global::Delta.ECS.EcsOperation<{context}, {functor}, {invoker}>",
            (true, false) => $"global::Delta.ECS.EcsOperation<{context}, {invoker}>",
            (false, true) => $"global::Delta.ECS.EcsOperation<{functor}, {invoker}>",
            _ => $"global::Delta.ECS.EcsOperation<{invoker}>"
        };
    }

    private static string OperationInvokerName(IterationModel shape)
        => "DemandForEachOperationInvoker_" + GeneratorSupport.StableName(shape.Key);

    private static string OperationInvokerGenericParameters(IterationModel shape)
    {
        string generic = shape.Api.Signature.HasGenericSelectors
            ? shape.Api.Signature.GenericList()
            : string.Empty;
        if (shape.HasContext && ContextType(shape) == "TContext")
        {
            generic = SignatureProjection.JoinGeneric("TContext", generic);
        }

        if (shape.OrderedWhereSource is { } whereSource)
        {
            generic = SignatureProjection.JoinGeneric(
                generic,
                GeneratedWhereTemplates.ViewMethodTypeParameters(whereSource));
        }

        return SignatureProjection.TypeArguments(generic);
    }

    private static string OperationInvokerType(IterationModel shape)
        => OperationInvokerName(shape) + OperationInvokerGenericParameters(shape);

    private static string RenderOperationInvoker(
        IterationModel shape,
        string closedMethodName,
        bool profiling,
        int methodId)
    {
        string genericParameters = OperationInvokerGenericParameters(shape);
        bool mutableContext = shape.HasContext && shape.ContextMode == ContextModeKind.Ref;
        string stateInterface = (mutableContext, shape.IsFunctor) switch
        {
            (true, true) => $"global::Delta.ECS.IEcsOperationInvoker<{ContextType(shape)}, {shape.FunctorType}>",
            (true, false) => $"global::Delta.ECS.IEcsOperationInvoker<{ContextType(shape)}>",
            (false, true) => $"global::Delta.ECS.IEcsOperationInvoker<{shape.FunctorType}>",
            _ => "global::Delta.ECS.IEcsOperationInvoker"
        };
        string visibility = shape.IsFunctor || shape.ImplicitComponents ? "internal" : "public";
        string fields = GeneratorTemplates.JoinNonEmpty(new[]
        {
            "private readonly global::Delta.ECS.World _world;",
            shape.HasEntityTarget ? "private readonly global::Delta.ECS.Entity[] _entities;" : string.Empty,
            "private readonly global::Delta.ECS.Query _query;",
            shape.Api.Signature.HasDynamicIds ? "private readonly global::Delta.ECS.ComponentId[] _componentIds;" : string.Empty,
            shape.Api.Signature.HasExplicitIds && !shape.Api.Signature.HasDynamicIds
                ? string.Join("\n", GeneratorTemplates.Indexed(shape.Api.Signature.Arity, index => $"private readonly global::Delta.ECS.ComponentId _componentId{index};"))
                : string.Empty,
            shape.HasContext && !mutableContext ? $"private readonly {ContextType(shape)} _context;" : string.Empty,
            shape.IsFunctor ? string.Empty : $"private readonly {ActionType(shape)} _action;",
            shape.Parallel ? "private readonly int _workerCount;" : string.Empty
        });
        string constructorParameters = string.Join(", ", new[]
        {
            "global::Delta.ECS.World world",
            shape.HasEntityTarget ? "global::Delta.ECS.Entity[] entities" : string.Empty,
            "global::Delta.ECS.Query query",
            shape.Api.Signature.HasDynamicIds ? "global::Delta.ECS.ComponentId[] componentIds" : string.Empty,
            shape.Api.Signature.HasExplicitIds && !shape.Api.Signature.HasDynamicIds
                ? shape.Api.Signature.ComponentIdParameters("componentId")
                : string.Empty,
            shape.HasContext && !mutableContext ? $"{ContextType(shape)} context" : string.Empty,
            shape.IsFunctor ? string.Empty : ActionType(shape) + " action",
            shape.Parallel ? "int workerCount" : string.Empty
        }.Where(static parameter => parameter.Length != 0));
        string constructorAssignments = GeneratorTemplates.JoinNonEmpty(new[]
        {
            "_world = world;",
            shape.HasEntityTarget ? "_entities = entities;" : string.Empty,
            "_query = query;",
            shape.Api.Signature.HasDynamicIds ? "_componentIds = componentIds;" : string.Empty,
            shape.Api.Signature.HasExplicitIds && !shape.Api.Signature.HasDynamicIds
                ? string.Join("\n", GeneratorTemplates.Indexed(shape.Api.Signature.Arity, index => $"_componentId{index} = {shape.Api.Signature.ComponentIdArgument(index, "componentId")};"))
                : string.Empty,
            shape.HasContext && !mutableContext ? "_context = context;" : string.Empty,
            shape.IsFunctor ? string.Empty : "_action = action;",
            shape.Parallel ? "_workerCount = workerCount;" : string.Empty
        });
        string methods = RenderOperationInvokerMethods(shape, closedMethodName, profiling, methodId, stateInterface);
        return $$"""
            [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
            {{visibility}} struct {{OperationInvokerName(shape)}}{{genericParameters}} : {{stateInterface}}
            {
            {{fields}}

                internal {{OperationInvokerName(shape)}}({{constructorParameters}})
                {
            {{GeneratorTemplates.Indent(constructorAssignments, "        ")}}
                }

            {{methods}}
            }
            """;
    }

    private static string RenderOperationInvokerMethods(
        IterationModel shape,
        string closedMethodName,
        bool profiling,
        int methodId,
        string stateInterface)
    {
        string generic = shape.Api.Signature.HasGenericSelectors ? shape.Api.Signature.GenericList() : string.Empty;
        string contextName = shape.HasContext
            ? shape.ContextMode == ContextModeKind.Ref ? "context" : "contextCopy"
            : "context";
        string functorName = "functor";
        var lines = new List<string>
        {
            "global::Delta.ECS.World world = _world;",
            shape.HasEntityTarget ? "global::Delta.ECS.Entity[] operationEntities = _entities;" : string.Empty,
            "global::Delta.ECS.Query operationQuery = _query;",
            shape.Api.Signature.HasDynamicIds ? "global::Delta.ECS.ComponentId[] operationComponentIds = _componentIds;" : string.Empty,
            shape.Api.Signature.HasExplicitIds && !shape.Api.Signature.HasDynamicIds
                ? string.Join("\n", GeneratorTemplates.Indexed(shape.Api.Signature.Arity, index => $"global::Delta.ECS.ComponentId {shape.Api.Signature.ComponentIdArgument(index, "componentId")} = _componentId{index};"))
                : string.Empty,
            shape.HasContext && shape.ContextMode != ContextModeKind.Ref
                ? $"{ContextType(shape)} contextCopy = _context;"
                : string.Empty,
            shape.IsFunctor ? string.Empty : $"{ActionType(shape)} action = _action;",
            shape.Parallel ? "int workerCount = _workerCount;" : string.Empty,
            BuildBody(shape, profiling, methodId, closedMethodName, contextName, functorName)
        };
        string body = GeneratorTemplates.JoinNonEmpty(lines);
        bool mutableContext = shape.HasContext && shape.ContextMode == ContextModeKind.Ref;
        string method = (mutableContext, shape.IsFunctor) switch
        {
            (true, true) => $"void {stateInterface}.Invoke(ref {ContextType(shape)} context, ref {shape.FunctorType} functor)",
            (true, false) => $"void {stateInterface}.Invoke(ref {ContextType(shape)} context)",
            (false, true) => $"void {stateInterface}.Invoke(ref {shape.FunctorType} functor)",
            _ => $"void {stateInterface}.Invoke()"
        };
        return GeneratorTemplates.RenderBlock(method, body);
    }

    private static string BuildDeferredBody(
        IterationModel shape,
        bool profiling,
        int methodId,
        string closedMethodName)
    {
        bool mutableContext = shape.HasContext && shape.ContextMode == ContextModeKind.Ref;
        var setup = new List<string>();
        if (shape.HasEntityTarget)
        {
            setup.Add("global::Delta.ECS.Entity[] operationEntities = entities.ToArray();");
        }

        if (shape.Api.Signature.HasDynamicIds)
        {
            setup.Add("global::Delta.ECS.ComponentId[] operationComponentIds = componentIds.ToArray();");
        }

        if (shape.HasQuery)
        {
            setup.Add("global::Delta.ECS.Query operationQuery = query;");
        }
        else if (shape.Api.Signature.HasExplicitIds)
        {
            string ids = shape.Api.Signature.HasDynamicIds
                ? "operationComponentIds"
                : shape.Api.Signature.ComponentIdArguments("componentId");
            setup.Add($"global::Delta.ECS.Query operationQuery = world.WhereAll({ids});");
        }
        else
        {
            string components = GeneratorTemplates.PrimaryComponentIds(
                "world",
                GeneratorTemplates.Indexed(shape.ComponentModels.Length, index => ComponentType(shape, index)).ToArray(),
                namespaceName: shape.Namespace);
            setup.Add($"global::System.ReadOnlySpan<global::Delta.ECS.ComponentId> operationComponents = {components};");
            setup.Add("global::Delta.ECS.Query operationQuery = world.WhereAll(operationComponents);");
        }

        var invokerArguments = new List<string> { "world" };
        if (shape.HasEntityTarget)
        {
            invokerArguments.Add("operationEntities");
        }

        invokerArguments.Add("operationQuery");
        if (shape.Api.Signature.HasDynamicIds)
        {
            invokerArguments.Add("operationComponentIds");
        }
        else if (shape.Api.Signature.HasExplicitIds)
        {
            invokerArguments.Add(shape.Api.Signature.ComponentIdArguments("componentId"));
        }

        if (shape.HasContext && !mutableContext)
        {
            invokerArguments.Add("context");
        }

        if (!shape.IsFunctor)
        {
            invokerArguments.Add("action");
        }

        if (shape.Parallel)
        {
            invokerArguments.Add("workerCount");
        }

        string invoker = $"new {OperationInvokerType(shape)}({string.Join(", ", invokerArguments)})";
        string operation = (mutableContext, shape.IsFunctor) switch
        {
            (true, true) => $"new {OperationType(shape)}(context, functor, {invoker})",
            (true, false) => $"new {OperationType(shape)}(context, {invoker})",
            (false, true) => $"new {OperationType(shape)}(functor, {invoker})",
            _ => $"new {OperationType(shape)}({invoker})"
        };
        setup.Add($"return {operation};");
        return GeneratorTemplates.RenderBlock(string.Empty, string.Join("\n", setup));
    }

    private static string BuildBody(
        IterationModel shape,
        bool profiling,
        int methodId,
        string closedMethodName,
        string contextName,
        string functorName)
    {
        SignatureProjection slots = shape.Api.Signature;
        var closedArguments = new List<string>(shape.HasEntityTarget
            ? new[] { "world", "operationEntities", "in operationQuery" }
            : new[] { "world", "in operationQuery" });
        if (slots.HasExplicitIds)
        {
            closedArguments.Add(slots.HasDynamicIds ? "operationComponentIds" : slots.ComponentIdArguments("componentId"));
        }

        if (shape.HasContext)
        {
            closedArguments.Add(SignatureProjection.ContextArgument(shape.ContextMode, contextName));
        }

        closedArguments.Add(shape.IsFunctor
            ? SignatureProjection.ContextArgument(shape.FunctorPassMode, functorName)
            : "action");
        if (shape.Parallel)
        {
            closedArguments.Add("workerCount");
        }

        string invoke = closedMethodName + StateGeneric(shape, slots.HasGenericSelectors ? slots.GenericList() : string.Empty)
            + "(" + string.Join(", ", closedArguments) + ");";
        var lines = new List<string>();
        string indent = "    ";
        if (profiling)
        {
            lines.Add($"    global::DeltaECS.Profiling.ProfilerRuntime.Enter({methodId});");
            lines.Add("    try");
            lines.Add("    {");
            indent = "        ";
        }
        if (!shape.IsFunctor)
        {
            lines.Add(indent + "global::Delta.ECS.GeneratedForEachRuntime.ThrowIfNull(action, nameof(action));");
        }

        lines.Add(indent + invoke);
        if (profiling)
        {
            lines.Add("    }");
            lines.Add("    finally");
            lines.Add("    {");
            lines.Add($"        global::DeltaECS.Profiling.ProfilerRuntime.Leave({methodId});");
            lines.Add("    }");
        }
        return string.Join("\n", lines);
    }

    private static string RenderMethod(string documentation, string signature, string body, string? profileName)
    {
        string profile = profileName is null
            ? string.Empty
            : $"""
                [global::DeltaECS.Profiling.ProfiledMethodMetadataAttribute({StableProfileMethodId(profileName)}, "{profileName}")]
                """.TrimEnd();
        return $"""
            {documentation}
            {profile}
            [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]
            {signature}
            {GeneratorTemplates.Indent(body, "    ")}
            """.TrimEnd();
    }

    private static string AppendArchetypeWriteSetup(IterationModel shape, string indent)
    {
        int writeCount = shape.ComponentModels.Count(static component => component.IsWrite);
        if (writeCount > 1)
        {
            string routes = string.Join(", ", GeneratorTemplates.WriteIndices(shape.ComponentModels).Select(index => "route" + index));
            return $"""
                {indent}var stampWriter = new {ArchetypeStampWriterName(shape)}({routes});
                {indent}execution.MarkArchetypeWrites(ref stampWriter);
                """.TrimEnd();
        }

        return string.Join("\n", GeneratorTemplates.WriteIndices(shape.ComponentModels)
            .Select(index => $"{indent}execution.MarkArchetypeWrite(route{index});"));
    }

    private static string AppendQueryComponentRoutes(IterationModel shape, string indent)
    {
        SignatureProjection slots = shape.Api.Signature;
        if (!shape.HasEntity && !slots.HasExplicitIds)
        {
            return string.Empty;
        }

        return string.Join("\n", GeneratorTemplates.Indexed(
            shape.ComponentModels.Length,
            index => !shape.HasEntity || shape.ComponentModels[index].IsWrite,
            index => $"{indent}int route{index} = GeneratedForEachRuntime.Get{(shape.ComponentModels[index].IsWrite ? "Write" : "Read")}QueryComponentIndex(access{index});"
            ));
    }

    private static string AccessSetup(IterationModel shape)
    {
        SignatureProjection slots = shape.Api.Signature;
        return string.Join("\n", GeneratorTemplates.Indexed(shape.ComponentModels.Length, index =>
        {
            bool routeOnly = shape is { HasEntity: false, HasEntityTarget: false }
                             && !slots.HasExplicitIds
                             && !shape.Parallel;
            string componentType = ComponentType(shape, index);
            if (shape.IsStamp)
            {
                return slots.HasExplicitIds
                    ? slots.HasGenericSelectors
                        ? $"var access{index} = GeneratedForEachRuntime.GetPreparedStampAccess<{componentType}>(in query, {slots.ComponentIdArgument(index, "componentId")});"
                        : $"var access{index} = GeneratedForEachRuntime.GetPreparedStampAccess(in query, {slots.ComponentIdArgument(index, "componentId")});"
                    : $"var access{index} = GeneratedForEachRuntime.GetPreparedStampAccess<{componentType}> (in query);";
            }
            string variable = (routeOnly ? "int route" : "var access") + index;
            string accessKind = shape.ComponentModels[index].IsWrite ? "Write" : "Read";
            string method = routeOnly ? "GetPrepared" + accessKind + "Route" : "GetPrepared" + accessKind + "Access";
            string generic = !slots.HasExplicitIds || routeOnly ? $"<{componentType}>" : string.Empty;
            string arguments = string.Join(", ", new[]
            {
                "in query",
                slots.HasExplicitIds ? slots.ComponentIdArgument(index, "componentId") : null,
                !slots.HasExplicitIds || routeOnly ? null : $"typeof({componentType})",
            }.Where(static value => !string.IsNullOrEmpty(value)));
            return $"{variable} = GeneratedForEachRuntime.{method}{generic}({arguments});";
        }));
    }

    private static string ActionType(IterationModel shape)
    {
        SignatureProjection slots = shape.Api.Signature;
        string generic = shape.IsStamp
            ? string.Join(", ", Enumerable.Repeat("Stamp", shape.Components.Length))
            : slots.HasGenericSelectors
                ? slots.GenericList()
                : string.Join(", ", shape.ComponentModels.Select(static component => component.ResolvedTypeName));
        string suffix = IsAllWrite(shape.ComponentModels) ? string.Empty : "_" + shape.Pattern;
        if (shape.HasContext)
        {
            string contextSuffix = ContextDelegateSuffix(shape.ContextMode);
            return SignatureProjection.TypeWithArguments(
                (shape.HasEntity ? "ForEachContextEntityAction" : "ForEachContextAction") + contextSuffix + suffix,
                SignatureProjection.JoinGeneric(shape.IsFunctor || !slots.HasGenericSelectors ? ContextType(shape) : "TContext", generic));
        }

        return SignatureProjection.TypeWithArguments(shape.HasEntity ? "ForEachEntityAction" + suffix : "ForEachAction" + suffix, generic);
    }

    private static string ContextDelegateSuffix(ContextModeKind mode) => mode switch
    {
        ContextModeKind.In => "In",
        ContextModeKind.RefReadonly => "RefReadonly",
        ContextModeKind.Value => "Value",
        _ => string.Empty
    };

    private static string StateGeneric(IterationModel shape, string generic)
        => !shape.Api.Signature.HasGenericSelectors
            ? string.Empty
            : SignatureProjection.TypeArguments(shape.IsFunctor
                ? generic
                : shape.HasContext ? SignatureProjection.JoinGeneric("TContext", generic) : generic);

    private static string ParallelInvokerName(IterationModel shape) => "DemandForEachParallelInvoker_" + GeneratorSupport.StableName(shape.Key);
    private static string ArchetypeStampWriterName(IterationModel shape) => "DemandForEachArchetypeStampWriter_" + GeneratorSupport.StableName(shape.Key);

    private static string ComponentType(IterationModel shape, int index) => shape.ComponentModels[index].TypeName;

    private static string CallbackComponentType(IterationModel shape, int index) => shape.IsStamp ? "global::Delta.ECS.Stamp" : shape.ComponentModels[index].ResolvedTypeName;

    private static string InNamespace(string namespaceName, string typeName)
        => namespaceName.Length == 0 ? "global::" + typeName : "global::" + namespaceName + "." + typeName;

    private static string ContextType(IterationModel shape) => shape.IsFunctor || shape.ImplicitComponents
            ? shape.ContextType ?? "TContext"
            : "TContext";

    private static string ConstructorName(string name)
    {
        int index = name.IndexOf('<');
        return index < 0 ? name : name.Substring(0, index);
    }

    private static bool IsAllWrite(IReadOnlyList<ComponentModel> components)
        => components.All(static component => component.IsWrite);


