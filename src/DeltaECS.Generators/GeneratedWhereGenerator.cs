using System;
using System.Collections.Immutable;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Delta.ECS.Generators;

/// <summary>Generates stack-only read-only predicate views for query-wide mutation terminals.</summary>
[Generator]
public sealed class GeneratedWhereGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor WritablePredicate = new(
        "DECSGEN006",
        "Where predicate is read-only",
        "Where predicates cannot write components; use 'in' or 'ref readonly' parameters and mutate in a terminal callback",
        "Where",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);
    private static readonly DiagnosticDescriptor EntityPredicateRequiresWhereEntity = new(
        "DECSGEN007",
        "Where predicate does not receive Entity",
        "Where predicates cannot receive Entity; use 'WhereEntity' for an entity parameter",
        "Where",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private const string InterceptorHeader = """
        // <auto-generated />
        #nullable enable
        #pragma warning disable CS0436

        """;
    private const string InterceptorFooter = """
        }

        namespace System.Runtime.CompilerServices
        {

        file sealed class InterceptsLocationAttribute : global::System.Attribute
        {
            internal InterceptsLocationAttribute(int version, string data) { }
        }
        }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(
            GeneratorPipeline.Input(context)
                .Combine(context.AnalyzerConfigOptionsProvider.Select(
                    static (provider, _) => GeneratorSupport.IsInterceptionEnabled(provider.GlobalOptions))),
            static (productionContext, input) => Execute(
                input.Left.Compilation,
                input.Left.Invocations,
                productionContext,
                input.Right));
    }

    private static void Execute(
        Compilation compilation,
        ImmutableArray<InvocationCandidate> discoveredInvocations,
        SourceProductionContext context,
        bool interceptorsEnabled)
    {
        var shapes = new ShapeRegistry<PredicateModel>(static shape => shape.Key);
        var whereCalls = new Dictionary<InvocationExpressionSyntax, PredicateModel>();
        var interceptionSites = new Dictionary<string, List<WhereInterceptionSite>>(StringComparer.Ordinal);
        bool languageSupportsInterceptors = GeneratorSupport.SupportsInterceptors(compilation);
        ImmutableArray<InvocationCandidate> invocations = GeneratorSupport.ExcludeGenerated(discoveredInvocations);
        foreach (InvocationCandidate invocationCandidate in invocations)
        {
            InvocationExpressionSyntax invocation = invocationCandidate.Invocation;
            SemanticModel model = compilation.GetSemanticModel(invocation.SyntaxTree);
            if (!TryReadPredicate(model, invocation, out PredicateModel? candidate)
                || candidate is null)
            {
                if (IsWritablePredicate(model, invocation))
                {
                    context.ReportDiagnostic(Diagnostic.Create(WritablePredicate, invocation.GetLocation()));
                }
                else if (IsEntityPredicateWithoutWhereEntity(model, invocation))
                {
                    context.ReportDiagnostic(Diagnostic.Create(EntityPredicateRequiresWhereEntity, invocation.GetLocation()));
                }

                continue;
            }

            PredicateModel shape = shapes.GetOrAdd(
                candidate,
                static (existing, duplicate) => existing.Merge(duplicate));

            whereCalls[invocation] = shape;
        }

        foreach (InvocationCandidate invocationCandidate in invocations)
        {
            InvocationExpressionSyntax invocation = invocationCandidate.Invocation;
            SemanticModel model = compilation.GetSemanticModel(invocation.SyntaxTree);
            if (!TryGetWhereReceiver(invocation, out InvocationExpressionSyntax? whereInvocation)
                || !whereCalls.TryGetValue(whereInvocation, out PredicateModel? shape)
                || !TryReadTerminal(model, invocation, out TerminalModel? terminal)
                || terminal is null)
            {
                continue;
            }

            shape.Terminals.GetOrAdd(
                terminal,
                static (existing, duplicate) => existing.Merge(duplicate));

            if (interceptorsEnabled
                && languageSupportsInterceptors
                && !shape.IsFunctor
                && (terminal.IsCallback || terminal.Kind is TerminalKind.Destroy or TerminalKind.Add or TerminalKind.Remove)
                && TryCreateInterceptionSite(model, whereInvocation, invocation, shape, terminal, invocation.SyntaxTree, out WhereInterceptionSite? site)
                && site is { } interceptionSite)
            {
                if (!interceptionSites.TryGetValue(shape.Key, out List<WhereInterceptionSite>? sites))
                {
                    sites = new List<WhereInterceptionSite>();
                    interceptionSites.Add(shape.Key, sites);
                }

                sites.Add(interceptionSite);
            }
        }

        foreach (PredicateModel shape in shapes.Ordered())
        {
            string hash = GeneratorSupport.StableName(shape.Key);
            context.AddSource("GeneratedWhere_" + hash + ".g.cs", Render(shape));
            if (interceptionSites.TryGetValue(shape.Key, out List<WhereInterceptionSite>? sites))
            {
                foreach (WhereInterceptionSite site in sites)
                {
                    context.AddSource(
                        "GeneratedWhereInterceptor_" + site.Id + ".g.cs",
                        RenderInterceptor(site));
                }
            }
        }
    }

    private static bool TryCreateInterceptionSite(
        SemanticModel model,
        InvocationExpressionSyntax whereInvocation,
        InvocationExpressionSyntax terminalInvocation,
        PredicateModel shape,
        TerminalModel terminal,
        SyntaxTree tree,
        out WhereInterceptionSite? site)
    {
        site = null;
        if (whereInvocation.ArgumentList.Arguments.Count is not (2 or 3))
        {
            return false;
        }

        ExpressionSyntax predicateExpression = whereInvocation.ArgumentList.Arguments[whereInvocation.ArgumentList.Arguments.Count - 1].Expression;
        LambdaExpressionSyntax? predicate = predicateExpression as LambdaExpressionSyntax;
        IMethodSymbol? predicateMethod = null;
        if (predicate is not null)
        {
            if (!predicate.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.StaticKeyword)))
            {
                return false;
            }
        }
        else if (!TryGetStaticMethodGroupTarget(model, predicateExpression, out predicateMethod))
        {
            return false;
        }

        LambdaExpressionSyntax? action = null;
        IMethodSymbol? actionMethod = null;
        if (terminal.IsCallback && !terminal.IsFunctor)
        {
            if (terminalInvocation.ArgumentList.Arguments.Count != 1)
            {
                return false;
            }

            ExpressionSyntax actionExpression = terminalInvocation.ArgumentList.Arguments[0].Expression;
            action = actionExpression as LambdaExpressionSyntax;
            if (action is not null)
            {
                if (!action.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.StaticKeyword)))
                {
                    return false;
                }
            }
            else if (!TryGetStaticMethodGroupTarget(model, actionExpression, out actionMethod))
            {
                return false;
            }
        }
        else if (terminal.IsCallback
            && (terminalInvocation.ArgumentList.Arguments.Count != (terminal.HasContext ? 2 : 1)
                || !terminalInvocation.ArgumentList.Arguments.Last().RefKindKeyword.IsKind(SyntaxKind.RefKeyword)))
        {
            return false;
        }

        if (!GeneratorSupport.TryGetInterceptionLocation(model, terminalInvocation, out string locationData, out string attributeSyntax))
        {
            return false;
        }

        if ((predicate is not null && !AreLambdaReferencesAccessible(model, predicate))
            || (action is not null && !AreLambdaReferencesAccessible(model, action)))
        {
            return false;
        }

        ParameterSyntax[] predicateParameters = predicate is null ? Array.Empty<ParameterSyntax>() : LambdaParameters(predicate);
        ParameterSyntax[] actionParameters = action is null ? Array.Empty<ParameterSyntax>() : LambdaParameters(action);
        int predicateComponentStart = (shape.HasContext ? 1 : 0) + (shape.HasEntity ? 1 : 0);
        string[] predicateComponents = predicate is null
            ? shape.Components
            : predicateParameters
                .Skip(predicateComponentStart)
                .Select(parameter => GeneratorSupport.DisplayType(model.GetTypeInfo(parameter.Type!).Type!))
                .ToArray();
        int actionComponentStart = terminal.HasEntity ? 1 : 0;
        string[] actionComponents = action is null
            ? terminal.Components
            : actionParameters
                .Skip(actionComponentStart)
                .Select(parameter => GeneratorSupport.DisplayType(model.GetTypeInfo(parameter.Type!).Type!))
                .ToArray();

        var usings = tree.GetRoot()
            .DescendantNodes()
            .OfType<UsingDirectiveSyntax>()
            .Select(static directive => directive.ToString())
            .Distinct(StringComparer.Ordinal)
            .ToArray();
        ISymbol? enclosing = model.GetEnclosingSymbol(terminalInvocation.SpanStart);
        if (enclosing is not null)
        {
            string namespaceName = enclosing.ContainingNamespace?.ToDisplayString() ?? string.Empty;
            if (namespaceName.Length > 0)
            {
                usings = usings
                    .Append("using global::" + namespaceName + ";")
                    .Distinct(StringComparer.Ordinal)
                    .ToArray();
            }

            if (enclosing.ContainingType is { Arity: 0 } containingType
                && GeneratorSupport.IsAccessibleSymbol(containingType))
            {
                usings = usings
                    .Append("using static " + containingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ";")
                    .Distinct(StringComparer.Ordinal)
                    .ToArray();
            }
        }
        string id = GeneratorSupport.StableName(shape.Key + "|" + terminal.Key + "|" + locationData);
        site = new WhereInterceptionSite(
            id,
            shape,
            terminal,
            predicate,
            action,
            predicateMethod,
            actionMethod,
            predicateComponents,
            actionComponents,
            attributeSyntax,
            usings);
        return true;
    }

    private static string RenderInterceptor(WhereInterceptionSite site)
    {
        PredicateModel shape = site.Shape;
        TerminalModel terminal = site.Terminal;
        string hash = GeneratorSupport.StableName(shape.Key);
        string terminalHash = GeneratorSupport.StableName(terminal.SignatureKey);
        string[] viewTypeArguments = shape.HasContext
            ? new[] { InterceptedPredicateContextType(shape) }.Concat(site.PredicateComponents).ToArray()
            : site.PredicateComponents;
        var source = new StringBuilder(24 * 1024);
        if (!site.Usings.Any(static value => value.Trim() is "using Delta.ECS;" or "using global::Delta.ECS;"))
        {
            source.AppendLine("using global::Delta.ECS;");
        }

        foreach (string usingDirective in site.Usings)
        {
            source.AppendLine(usingDirective);
        }

        source.Append("namespace Delta.ECS.Generated\n{\n\nfile static class GeneratedWhereInterceptor_")
            .Append(site.Id).AppendLine();
        source.AppendLine("{");
        RenderInterceptedPredicate(source, site);
        if (terminal.IsCallback && !terminal.IsFunctor)
        {
            RenderInterceptedAction(source, site);
        }
        if (terminal.IsCallback)
        {
            RenderInterceptedWhereLoop(source, site);
        }
        else
        {
            RenderInterceptedStructuralLoop(source, site);
        }
        source.Append("    ").Append(site.Attribute).AppendLine();
        source.Append("    internal static ")
            .Append(terminal.IsCallback ? "void" : "int")
            .Append(" Intercept_").Append(site.Id)
            .Append(shape.HasContext
                ? "(this ref global::Delta.ECS.GeneratedWhereQuery_"
                : "(this in global::Delta.ECS.GeneratedWhereQuery_")
            .Append(hash).Append(TypeArguments(viewTypeArguments)).Append(" view");
        if (!terminal.IsCallback)
        {
            source.AppendLine(")");
        }
        else if (terminal.IsFunctor)
        {
            source.Append(", ");
            if (terminal.HasContext)
            {
                source.Append("ref ").Append(terminal.ContextType).Append(" context, ");
            }

            source.Append("ref ").Append(terminal.FunctorType).AppendLine(" action)");
        }
        else
        {
            source.Append(", ");
            source.Append("global::Delta.ECS.GeneratedWhereAction_").Append(hash).Append('_').Append(terminalHash)
                .Append(TypeArguments(site.ActionComponents)).AppendLine(" _)");
        }
        source.AppendLine("    {");
        source.AppendLine("        global::Delta.ECS.Query query = view.Query;");
        if (!terminal.IsCallback)
        {
            source.Append("        return Execute_").Append(site.Id).Append("(view.World, in query");
        }
        else
        {
            source.Append("        Execute_").Append(site.Id).Append("(view.World, in query");
        }
        if (shape.HasContext)
        {
            source.Append(", ref view.PredicateContext");
        }

        if (terminal.IsFunctor)
        {
            if (terminal.HasContext)
            {
                source.Append(", ref context");
            }

            source.Append(", ref action");
        }

        source.AppendLine(");");
        source.AppendLine("    }");
        source.AppendLine("}");
        return GeneratorTemplates.InterceptorTemplate(InterceptorHeader, source.ToString(), InterceptorFooter);
    }

    private static bool AreLambdaReferencesAccessible(SemanticModel model, LambdaExpressionSyntax lambda)
    {
        foreach (SyntaxNode node in lambda.Body.DescendantNodesAndSelf())
        {
            ISymbol? symbol = model.GetSymbolInfo(node).Symbol;
            if (symbol is null or IParameterSymbol or ILocalSymbol or IRangeVariableSymbol)
            {
                continue;
            }

            if (symbol is ITypeParameterSymbol || !GeneratorSupport.IsAccessibleSymbol(symbol))
            {
                return false;
            }
        }

        for (INamedTypeSymbol? type = model.GetEnclosingSymbol(lambda.SpanStart)?.ContainingType;
             type is not null;
             type = type.ContainingType)
        {
            if (type.Arity != 0)
            {
                return false;
            }
        }

        return model.GetEnclosingSymbol(lambda.SpanStart) is not IMethodSymbol { IsGenericMethod: true };
    }

    private static void RenderInterceptedPredicate(StringBuilder source, WhereInterceptionSite site)
    {
        PredicateModel shape = site.Shape;
        string[] parameters = site.PredicateParameterNames;
        source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        source.Append("    private static bool Predicate_").Append(site.Id).Append('(');
        int parameterIndex = 0;
        if (shape.HasContext)
        {
            source.Append("ref ").Append(InterceptedPredicateContextType(shape)).Append(' ')
            .Append(parameters[parameterIndex++]);
        }

        if (shape.HasEntity)
        {
            if (parameterIndex > 0)
            {
                source.Append(", ");
            }

            source.Append("Entity ").Append(parameters[parameterIndex++]);
        }

        for (int index = 0; index < shape.Arity; index++)
        {
            if (parameterIndex > 0)
            {
                source.Append(", ");
            }

            source.Append(GeneratorSupport.ParameterPrefix(shape.Pattern[index])).Append(site.PredicateComponents[index]).Append(' ')
                .Append(parameters[parameterIndex++]);
        }

        source.AppendLine(")");
        source.AppendLine("    {");
        if (site.PredicateBodyIsBlock)
        {
            AppendIndented(source, site.PredicateBody!, "        ");
        }
        else if (site.PredicateBody is not null)
        {
            source.Append("        return ").Append(site.PredicateBody).AppendLine(";");
        }
        else
        {
            source.Append("        return ");
            AppendMethodGroupInvocation(source, site.PredicateMethodGroupTarget!, shape.HasContext, shape.HasEntity, shape.Pattern, parameters);
            source.AppendLine(";");
        }

        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void RenderInterceptedAction(StringBuilder source, WhereInterceptionSite site)
    {
        TerminalModel terminal = site.Terminal;
        string[] parameters = site.ActionParameterNames;
        int parameterIndex = 0;
        source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        source.Append("    private static void Action_").Append(site.Id).Append("(");
        var declarations = new List<string>();
        if (terminal.HasEntity)
        {
            declarations.Add("Entity " + parameters[parameterIndex++]);
        }

        for (int index = 0; index < terminal.Arity; index++)
        {
            declarations.Add(
                GeneratorSupport.ParameterPrefix(terminal.Pattern[index])
                + site.ActionComponents[index]
                + " "
                + parameters[parameterIndex++]);
        }

        source.Append(string.Join(", ", declarations)).AppendLine(")");
        source.AppendLine("    {");
        if (site.ActionBodyIsBlock)
        {
            AppendIndented(source, site.ActionBody!, "        ");
        }
        else if (site.ActionBody is not null)
        {
            source.Append("        ").Append(site.ActionBody).AppendLine(";");
        }
        else
        {
            source.Append("        ");
            AppendMethodGroupInvocation(source, site.ActionMethodGroupTarget!, terminal.HasContext, terminal.HasEntity, terminal.Pattern, parameters);
            source.AppendLine(";");
        }

        source.AppendLine("    }");
        source.AppendLine();
    }

    private static string[] InterceptedPredicateParameterNames(PredicateModel shape)
    {
        var names = new List<string>();
        if (shape.HasContext)
        {
            names.Add("context");
        }

        if (shape.HasEntity)
        {
            names.Add("entity");
        }

        names.AddRange(Enumerable.Range(0, shape.Arity).Select(static index => "component" + index));
        return names.ToArray();
    }

    private static string[] InterceptedActionParameterNames(TerminalModel terminal)
    {
        var names = new List<string>();
        if (terminal.HasEntity)
        {
            names.Add("entity");
        }

        names.AddRange(Enumerable.Range(0, terminal.Arity).Select(static index => "component" + index));
        return names.ToArray();
    }

    private static void AppendMethodGroupInvocation(
        StringBuilder source,
        string target,
        bool hasContext,
        bool hasEntity,
        string pattern,
        IReadOnlyList<string> parameters)
    {
        var arguments = new List<string>();
        int parameterIndex = 0;
        if (hasContext)
        {
            arguments.Add("ref " + parameters[parameterIndex++]);
        }

        if (hasEntity)
        {
            arguments.Add(parameters[parameterIndex++]);
        }

        for (int index = 0; index < pattern.Length; index++)
        {
            arguments.Add(GeneratorSupport.InvocationPrefix(pattern[index]) + parameters[parameterIndex++]);
        }

        source.Append(target).Append('(').Append(string.Join(", ", arguments)).Append(')');
    }

    private static void RenderInterceptedWhereLoop(StringBuilder source, WhereInterceptionSite site)
    {
        PredicateModel shape = site.Shape;
        TerminalModel terminal = site.Terminal;
        string executeName = "Execute_" + site.Id;
        source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        source.Append("    private static void ").Append(executeName)
            .Append("(global::Delta.ECS.World world, in global::Delta.ECS.Query query");
        if (shape.HasContext)
        {
            source.Append(", ref ").Append(InterceptedPredicateContextType(shape)).Append(" predicateContext");
        }

        if (terminal.IsFunctor && terminal.HasContext)
        {
            source.Append(", ref ").Append(terminal.ContextType).Append(" context");
        }

        if (terminal.IsFunctor)
        {
            source.Append(", ref ").Append(terminal.FunctorType).Append(" action");
        }

        source.AppendLine(")");
        source.AppendLine("    {");
        source.AppendLine("        using var execution = global::Delta.ECS.GeneratedForEachRuntime.OpenDense(world, in query);");
        int accessCount = shape.Arity + terminal.Arity;
        for (int index = 0; index < accessCount; index++)
        {
            string componentType = index < shape.Arity ? site.PredicateComponents[index] : site.ActionComponents[index - shape.Arity];
            string pattern = index < shape.Arity ? shape.Pattern : terminal.Pattern;
            source.Append("        var access").Append(index).Append(" = global::Delta.ECS.GeneratedForEachRuntime.GetPrepared")
                .Append(GeneratorSupport.IsWrite(pattern[index < shape.Arity ? index : index - shape.Arity]) ? "Write" : "Read")
                .Append("Access<").Append(componentType).AppendLine(">(in query);");
        }

        string writes = WriteIndices(shape.Pattern, terminal.Pattern, shape.Arity);
        source.Append("        execution.MarkArchetypeWrites(").Append(writes).AppendLine(");");
        source.AppendLine("        while (execution.MoveNextTrusted(out var slots))");
        source.AppendLine("        {");
        for (int index = 0; index < accessCount; index++)
        {
            string componentType = index < shape.Arity ? site.PredicateComponents[index] : site.ActionComponents[index - shape.Arity];
            string pattern = index < shape.Arity ? shape.Pattern : terminal.Pattern;
            source.Append("            ref ")
                .Append(componentType).Append(" row").Append(index).Append(" = ref slots.GetGenerated")
                .Append(GeneratorSupport.IsWrite(pattern[index < shape.Arity ? index : index - shape.Arity]) ? "Write" : "Read")
                .Append("Reference<").Append(componentType).Append(">(access").Append(index).AppendLine(");");
        }

        source.AppendLine("            for (int index = 0; index < slots.Count; index++)");
        source.AppendLine("            {");
        source.Append("                Entity __whereEntity_").Append(site.Id).AppendLine(" = slots.EntityAt(index);");
        for (int index = 0; index < shape.Arity; index++)
        {
            source.Append("                ref ")
                .Append(site.PredicateComponents[index]).Append(" __wherePredicateComponent").Append(index)
                .Append(" = ref global::System.Runtime.CompilerServices.Unsafe.Add(ref ")
                .Append("row")
                .Append(index).Append(", index);").AppendLine();
        }

        source.Append("                if (!Predicate_").Append(site.Id).Append('(');
        if (shape.HasContext)
        {
            source.Append("ref predicateContext");
        }

        if (shape.HasEntity)
        {
            if (shape.HasContext)
            {
                source.Append(", ");
            }

            source.Append("__whereEntity_").Append(site.Id);
        }

        for (int index = 0; index < shape.Arity; index++)
        {
            if (shape.HasContext || shape.HasEntity || index > 0)
            {
                source.Append(", ");
            }

            source.Append(GeneratorSupport.InvocationPrefix(shape.Pattern[index])).Append("__wherePredicateComponent").Append(index);
        }

        source.AppendLine("))");
        source.AppendLine("                {");
        source.AppendLine("                    continue;");
        source.AppendLine("                }");
        for (int index = 0; index < terminal.Arity; index++)
        {
            source.Append("                ref ")
                .Append(site.ActionComponents[index]).Append(" __whereActionComponent").Append(index)
                .Append(" = ref global::System.Runtime.CompilerServices.Unsafe.Add(ref ")
                .Append("row")
                .Append(shape.Arity + index).Append(", index);").AppendLine();
        }

        if (terminal.IsFunctor)
        {
            source.Append("                action.Invoke(");
            if (terminal.HasContext)
            {
                source.Append("ref context");
                if (terminal.HasEntity || terminal.Arity > 0)
                {
                    source.Append(", ");
                }
            }

            if (terminal.HasEntity)
            {
                source.Append("__whereEntity_").Append(site.Id);
                if (terminal.Arity > 0)
                {
                    source.Append(", ");
                }
            }
        }
        else
        {
            source.Append("                Action_").Append(site.Id).Append('(');
            if (terminal.HasEntity)
            {
                source.Append("__whereEntity_").Append(site.Id);
                if (terminal.Arity > 0)
                {
                    source.Append(", ");
                }
            }
        }

        for (int index = 0; index < terminal.Arity; index++)
        {
            if (index > 0)
            {
                source.Append(", ");
            }

            source.Append(GeneratorSupport.InvocationPrefix(terminal.Pattern[index])).Append("__whereActionComponent").Append(index);
        }

        source.AppendLine(");");

        source.AppendLine("            }");
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void RenderInterceptedStructuralLoop(StringBuilder source, WhereInterceptionSite site)
    {
        PredicateModel shape = site.Shape;
        TerminalModel terminal = site.Terminal;
        string invokerName = "StructuralInvoker_" + site.Id;
        string executeName = "Execute_" + site.Id;

        source.Append("    private struct ").Append(invokerName).AppendLine(" : global::Delta.ECS.IGeneratedWhereStructuralInvoker");
        source.AppendLine("    {");
        if (shape.HasContext)
        {
            source.Append("        private ").Append(InterceptedPredicateContextType(shape)).AppendLine(" _predicateContext;");
        }

        for (int index = 0; index < shape.Arity; index++)
        {
            source.Append("        private readonly int _access").Append(index).AppendLine(";");
        }

        source.Append("        internal ").Append(invokerName).Append('(');
        if (shape.HasContext)
        {
            source.Append(InterceptedPredicateContextType(shape)).Append(" predicateContext");
        }

        for (int index = 0; index < shape.Arity; index++)
        {
            if (index > 0 || shape.HasContext)
            {
                source.Append(", ");
            }

            source.Append("int access").Append(index);
        }

        source.AppendLine(")");
        source.AppendLine("        {");
        if (shape.HasContext)
        {
            source.AppendLine("            _predicateContext = predicateContext;");
        }

        for (int index = 0; index < shape.Arity; index++)
        {
            source.Append("            _access").Append(index).Append(" = access").Append(index).AppendLine(";");
        }

        source.AppendLine("        }");
        source.AppendLine();
        source.AppendLine("        public void Execute(ref GeneratedQuerySlots slots, ref GeneratedWhereStructuralContext context)");
        source.AppendLine("        {");
        source.AppendLine("            if (slots.Count == 0)");
        source.AppendLine("            {");
        source.AppendLine("                return;");
        source.AppendLine("            }");
        RenderRowLocals(source, shape.Pattern, shape.Arity, site.PredicateComponents, "T", "            ");
        source.AppendLine("            int runStart = 0;");
        source.AppendLine("            bool runSelected = false;");
        source.AppendLine("            for (int index = 0; index < slots.Count; index++)");
        source.AppendLine("            {");
        RenderComponentLocals(source, shape.Pattern, shape.Arity, site.PredicateComponents, "T", "                ");
        source.AppendLine("                Entity entity = slots.EntityAt(index);");
        source.Append("                bool selected = Predicate_").Append(site.Id).Append('(');
        AppendInterceptedPredicateArguments(source, shape, "_predicateContext");
        source.AppendLine(");");
        source.AppendLine("                if (index != 0 && selected != runSelected)");
        source.AppendLine("                {");
