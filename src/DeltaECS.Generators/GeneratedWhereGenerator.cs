    {
        string typeName = "GeneratedWhereQuery_" + hash;
        source.AppendLine("    private readonly World _world;");
        source.AppendLine("    private readonly Query _query;");
        if (shape.HasContext)
        {
            source.Append("    private Span<").Append(PredicateContextType(shape)).AppendLine("> _predicateContext;");
        }

        if (shape.IsFunctor)
        {
            source.Append("    private Span<").Append(shape.FunctorType).AppendLine("> _predicate;");
        }
        else
        {
            source.Append("    private readonly GeneratedWherePredicate_").Append(hash).Append(PredicateGenericTypes(shape)).AppendLine(" _predicate;");
        }

        source.Append("    internal ").Append(typeName).Append('(').Append("World world, in Query query, ");
        if (shape.HasContext)
        {
            source.Append("ref ").Append(PredicateContextType(shape)).Append(" context, ");
        }

        if (shape.IsFunctor)
        {
            source.Append("ref ").Append(shape.FunctorType).AppendLine(" predicate)");
        }
        else
        {
            source.Append("GeneratedWherePredicate_").Append(hash).Append(PredicateGenericTypes(shape)).AppendLine(" predicate)");
        }
        source.AppendLine("    {");
        source.AppendLine("        _world = world;");
        source.AppendLine("        _query = query;");
        if (shape.HasContext)
        {
            source.Append("        _predicateContext = global::System.Runtime.InteropServices.MemoryMarshal.CreateSpan(ref context, 1);").AppendLine();
        }

        if (shape.IsFunctor)
        {
            source.Append("        _predicate = global::System.Runtime.InteropServices.MemoryMarshal.CreateSpan(ref predicate, 1);").AppendLine();
        }
        else
        {
            source.AppendLine("        _predicate = predicate;");
        }
        source.AppendLine("    }");
        source.AppendLine();
        source.AppendLine("    internal World World => _world;");
        source.AppendLine("    internal Query Query => _query;");
        if (shape.HasContext)
        {
            source.Append("    internal ref ").Append(PredicateContextType(shape)).AppendLine(" PredicateContext => ref _predicateContext[0];");
        }

        foreach (TerminalModel terminal in shape.Terminals.Ordered())
        {
            RenderViewTerminal(source, shape, terminal, hash);
        }

    }

    private static void RenderViewTerminal(StringBuilder source, PredicateModel shape, TerminalModel terminal, string hash)
    {
        string terminalHash = GeneratorSupport.StableName(terminal.SignatureKey);
        string invokerName = "GeneratedWhereInvoker_" + hash + '_' + terminalHash;
        string generic = terminal.Kind is TerminalKind.Add or TerminalKind.Remove || (terminal.IsCallback && !terminal.IsFunctor)
            ? GeneratorSupport.GenericList(terminal.Arity, "U")
            : string.Empty;
        string genericParameters = GeneratorSupport.GenericParameters(generic);
        string actionType = terminal.IsCallback ? ActionType(terminal, hash, terminalHash) : string.Empty;
        string signature = terminal.Kind switch
        {
            TerminalKind.Destroy => "public int Destroy()",
            TerminalKind.Add => "public int Add" + genericParameters + "()",
            TerminalKind.Remove => "public int Remove" + genericParameters + "()",
            TerminalKind.ForEach => terminal.IsFunctor
                ? "internal void ForEach" + (terminal.HasContext ? "(" + "ref " + terminal.ContextType + " context, ref " + actionType + " action)" : "(ref " + actionType + " action)")
                : "public void ForEach" + genericParameters + "(" + actionType + " action)",
            TerminalKind.ForEachEntity => terminal.IsFunctor
                ? "internal void ForEachEntity" + (terminal.HasContext ? "(" + "ref " + terminal.ContextType + " context, ref " + actionType + " action)" : "(ref " + actionType + " action)")
                : "public void ForEachEntity" + genericParameters + "(" + actionType + " action)",
            _ => string.Empty
        };
        source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        source.Append("    ").AppendLine(signature);
        source.AppendLine("    {");
        if (terminal.IsCallback && !terminal.IsFunctor)
        {
            source.AppendLine("        GeneratedForEachRuntime.ThrowIfNull(action, nameof(action));");
        }

        source.AppendLine("        GeneratedForEachRuntime.ValidateGeneratedWhere(_world, in _query);");
        int accessCount = shape.Arity + (terminal.IsCallback ? terminal.Arity : 0);
        for (int index = 0; index < accessCount; index++)
        {
            string componentType = index < shape.Arity
                ? shape.IsFunctor ? shape.Components[index] : "T" + (index + 1)
                : terminal.IsFunctor ? terminal.Components[index - shape.Arity] : "U" + (index - shape.Arity + 1);
            string pattern = index < shape.Arity ? shape.Pattern : terminal.Pattern;
            int patternIndex = index < shape.Arity ? index : index - shape.Arity;
            source.Append("        var access").Append(index).Append(" = GeneratedForEachRuntime.GetPrepared")
                .Append(GeneratorSupport.IsWrite(pattern[patternIndex]) ? "Write" : "Read")
                .Append("Access<").Append(componentType).AppendLine(">(in _query);");
        }

        string invokerGeneric = GeneratorSupport.GenericParameters(
            JoinGeneric(
                shape.IsFunctor ? string.Empty : PredicateGenericList(shape),
                terminal.IsCallback && !terminal.IsFunctor ? GeneratorSupport.GenericList(terminal.Arity, "U") : string.Empty));
        source.Append("        var invoker = new ").Append(invokerName).Append(invokerGeneric)
            .Append(shape.IsFunctor ? "(_predicate[0]" : "(_predicate");
        if (shape.HasContext)
        {
            source.Append(", _predicateContext[0]");
        }

        if (terminal.IsCallback)
        {
            if (terminal.HasContext)
            {
                source.Append(", context");
            }

            source.Append(", action");
        }

        for (int index = 0; index < accessCount; index++)
        {
            source.Append(", access").Append(index);
        }

        source.AppendLine(");");
        string writes = WriteIndices(shape.Pattern, terminal.Pattern, shape.Arity);
        bool returnsCount = terminal.Kind is TerminalKind.Destroy or TerminalKind.Add or TerminalKind.Remove;
        if (returnsCount)
        {
            source.AppendLine("        int __whereResult;");
        }

        if (terminal.Kind is TerminalKind.Add or TerminalKind.Remove)
        {
            source.Append("        Span<ComponentId> components = stackalloc ComponentId[").Append(terminal.Arity).AppendLine("];");
            for (int index = 0; index < terminal.Arity; index++)
            {
                source.Append("        components[").Append(index).Append("] = _world.Layouts.GetPrimary<U").Append(index + 1).AppendLine(">();");
            }
        }

        switch (terminal.Kind)
        {
            case TerminalKind.Destroy:
                source.Append("        __whereResult = GeneratedForEachRuntime.ExecuteGeneratedWhereDestroy(_world, in _query, ref invoker, ").Append(writes).AppendLine(");");
                break;
            case TerminalKind.Add:
                source.Append("        __whereResult = GeneratedForEachRuntime.ExecuteGeneratedWhereAdd(_world, in _query, ref invoker, ").Append(writes).AppendLine(", components);");
                break;
            case TerminalKind.Remove:
                source.Append("        __whereResult = GeneratedForEachRuntime.ExecuteGeneratedWhereRemove(_world, in _query, ref invoker, ").Append(writes).AppendLine(", components);");
                break;
            default:
                source.Append("        GeneratedForEachRuntime.ExecuteGeneratedWhereForEach(_world, in _query, ref invoker, ").Append(writes).AppendLine(");");
                break;
        }

        if (shape.IsFunctor)
        {
            source.AppendLine("        _predicate[0] = invoker.Predicate;");
        }

        if (shape.HasContext)
        {
            source.AppendLine("        _predicateContext[0] = invoker.PredicateContext;");
        }

        if (terminal.IsFunctor && terminal.IsCallback)
        {
            if (terminal.HasContext)
            {
                source.AppendLine("        context = invoker.Context;");
            }

            source.AppendLine("        action = invoker.Action;");
        }

        if (returnsCount)
        {
            source.AppendLine("        return __whereResult;");
        }

        source.AppendLine("    }");
        source.AppendLine();
        if (terminal.IsCallback && !terminal.IsFunctor)
        {
            foreach (string[] components in terminal.StaticMethodGroupComponents)
            {
                string concreteActionType = "GeneratedWhereAction_" + hash + '_' + terminalHash + TypeArguments(components);
                string method = terminal.HasEntity ? "ForEachEntity" : "ForEach";
                source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
                source.Append("    internal void ").Append(method).Append('(').Append(concreteActionType).AppendLine(" action)");
                source.AppendLine("    {");
                source.Append("        ").Append(method).Append(TypeArguments(components)).AppendLine("(action);");
                source.AppendLine("    }");
                source.AppendLine();
            }
        }
    }

    private static void RenderExtensionBody(StringBuilder source, PredicateModel shape, string hash)
    {
        string typeName = "GeneratedWhereQuery_" + hash;
        source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        source.Append("    ").Append(shape.IsFunctor ? "internal static " : "public static ").Append(typeName).Append(PredicateGenericTypes(shape))
            .Append(shape.HasEntity ? " WhereEntity" : " Where").Append(PredicateGenericParameters(shape))
            .Append("(this World world, in Query query, ");
        if (shape.HasContext)
        {
            source.Append("ref ").Append(PredicateContextType(shape)).Append(" context, ");
        }

        if (shape.IsFunctor)
        {
            source.Append("ref ").Append(shape.FunctorType).AppendLine(" predicate)");
        }
        else
        {
            source.Append("GeneratedWherePredicate_").Append(hash).Append(PredicateGenericTypes(shape)).AppendLine(" predicate)");
        }
        source.AppendLine("    {");
        source.AppendLine("        GeneratedForEachRuntime.ThrowIfNull(world, nameof(world));");
        if (!shape.IsFunctor)
        {
            source.AppendLine("        GeneratedForEachRuntime.ThrowIfNull(predicate, nameof(predicate));");
        }

        source.Append("        return new ").Append(typeName).Append(PredicateGenericTypes(shape)).Append("(world, in query, ");
        if (shape.HasContext)
        {
            source.Append("ref context, ");
        }

        if (shape.IsFunctor)
        {
            source.AppendLine("ref predicate);");
        }
        else
        {
            source.AppendLine("predicate);");
        }
        source.AppendLine("    }");
        foreach (string[] components in shape.StaticMethodGroupComponents)
        {
            string concretePredicateType = "GeneratedWherePredicate_" + hash + TypeArguments(components);
            string method = shape.HasEntity ? "WhereEntity" : "Where";
            source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
            source.Append("    internal static ").Append(typeName).Append(TypeArguments(components)).Append(' ').Append(method)
                .Append("(this World world, in Query query, ");
            if (shape.HasContext)
            {
                source.Append("ref ").Append(shape.ContextType).Append(" context, ");
            }

            source.Append(concretePredicateType).AppendLine(" predicate)");
            source.AppendLine("    {");
            source.Append("        return ").Append(method).Append(TypeArguments(components)).Append("(world, in query, ");
            if (shape.HasContext)
            {
                source.Append("ref context, ");
            }

            source.AppendLine("predicate);");
            source.AppendLine("    }");
        }
    }

    private static string WriteIndices(string predicatePattern, string terminalPattern, int predicateArity)
    {
        var values = new List<string>();
        for (int index = 0; index < predicatePattern.Length; index++)
        {
            if (GeneratorSupport.IsWrite(predicatePattern[index]))
            {
                values.Add("GeneratedForEachRuntime.GetWriteQueryComponentIndex(access" + index + ")");
            }
        }

        for (int index = 0; index < terminalPattern.Length; index++)
        {
            if (GeneratorSupport.IsWrite(terminalPattern[index]))
            {
                values.Add("GeneratedForEachRuntime.GetWriteQueryComponentIndex(access" + (predicateArity + index) + ")");
            }
        }

        if (values.Count == 0)
        {
            return "global::System.ReadOnlySpan<int>.Empty";
        }

        return "stackalloc int[] { " + string.Join(", ", values) + " }";
    }

    private static string AccessType(char mode) => GeneratorSupport.IsWrite(mode) ? "WriteAccess" : "ReadAccess";

    private static string PredicateGenericList(PredicateModel shape)
        => shape.IsFunctor
            ? string.Empty
            : JoinGeneric(shape.HasContext ? "C" : string.Empty, GeneratorSupport.GenericList(shape.Arity));

    private static string PredicateGenericParameters(PredicateModel shape)
        => GeneratorSupport.GenericParameters(PredicateGenericList(shape));

    private static string PredicateGenericTypes(PredicateModel shape)
        => PredicateGenericParameters(shape);

    private static string PredicateContextType(PredicateModel shape)
        => shape.IsFunctor ? shape.ContextType! : "C";

    private static string InterceptedPredicateContextType(PredicateModel shape)
        => shape.ContextType ?? "global::System.Object";

    private static string TypeArguments(string[] types)
        => types.Length == 0 ? string.Empty : "<" + string.Join(", ", types) + ">";

    private static string JoinGeneric(string first, string second)
        => string.IsNullOrEmpty(first) ? second : string.IsNullOrEmpty(second) ? first : first + ", " + second;

    private sealed class PredicateModel
    {
        internal PredicateModel(
            string pattern,
            bool isFunctor,
            string? functorType,
            bool hasEntity,
            bool hasContext,
            string? contextType,
            string[]? components)
        {
            Pattern = pattern;
            IsFunctor = isFunctor;
            FunctorType = functorType;
            HasEntity = hasEntity;
            HasContext = hasContext;
            ContextType = contextType;
            Components = components ?? Array.Empty<string>();
            var slots = isFunctor
                ? Components.Select((component, index) => new ComponentModel(
                    index,
                    component,
                    SelectorKind.Inferred,
                    GeneratorSupport.AccessKindFrom(index < Pattern.Length ? Pattern[index] : 'I'))).ToImmutableArray()
                : ImmutableArray<ComponentModel>.Empty;

            Api = new ApiModel(
                OperationKind.Where,
                TargetKind.World,
                QueryMode.Required,
                new SelectorModel(SelectorKind.Inferred, slots),
                new ContextModel(hasContext ? ContextModeKind.Value : ContextModeKind.None, contextType),
                new CallbackModel(
                    isFunctor ? CallbackSource.Functor : CallbackSource.Lambda,
                    hasEntity,
                    functorType),
                new ExecutionModel(ExecutionKind.Dense, ValueKind.Component),
                pattern: Pattern);
        }

        internal string Pattern { get; }
        internal int Arity => Pattern.Length;
        internal bool IsFunctor { get; }
        internal string? FunctorType { get; }
        internal bool HasEntity { get; }
        internal bool HasContext { get; }
        internal string? ContextType { get; }
        internal string[] Components { get; }
        internal ApiModel Api { get; }
        internal ShapeRegistry<TerminalModel> Terminals { get; } = new(static terminal => terminal.SignatureKey);
        internal List<string[]> StaticMethodGroupComponents { get; } = new();
        internal string Key => Api.SignatureKey;

        internal void Merge(PredicateModel candidate)
        {
            if (!IsFunctor && candidate.Components.Length > 0)
            {
                AddUnique(StaticMethodGroupComponents, candidate.Components);
            }
        }

        internal void RegisterStaticMethodGroup()
            => AddUnique(StaticMethodGroupComponents, Components);

        private static void AddUnique(List<string[]> values, string[] candidate)
        {
            if (!values.Any(existing => existing.SequenceEqual(candidate, StringComparer.Ordinal)))
            {
                values.Add(candidate);
            }
        }
    }

    private sealed class TerminalModel
    {
        internal TerminalModel(
            TerminalKind kind,
            string pattern,
            int arity,
            bool hasEntity,
            bool isFunctor = false,
            string? functorType = null,
            bool hasContext = false,
            string? contextType = null,
            string[]? components = null,
            string? methodGroupTarget = null)
        {
            Kind = kind;
            Pattern = pattern;
            Arity = arity;
            HasEntity = hasEntity;
            IsFunctor = isFunctor;
            FunctorType = functorType;
            HasContext = hasContext;
            ContextType = contextType;
            Components = components ?? Array.Empty<string>();
            MethodGroupTarget = methodGroupTarget;
            var slots = isFunctor
                ? Components.Select((component, index) => new ComponentModel(
                    index,
                    component,
                    SelectorKind.Inferred,
                    GeneratorSupport.AccessKindFrom(index < Pattern.Length ? Pattern[index] : 'I'))).ToImmutableArray()
                : ImmutableArray<ComponentModel>.Empty;

            Api = new ApiModel(
                OperationKind.Where,
                TargetKind.World,
                QueryMode.Required,
                new SelectorModel(SelectorKind.Inferred, slots),
                new ContextModel(hasContext ? ContextModeKind.Value : ContextModeKind.None, contextType),
                new CallbackModel(
                    isFunctor ? CallbackSource.Functor : CallbackSource.Lambda,
                    hasEntity,
                    functorType),
                new ExecutionModel(ExecutionKind.Dense, ValueKind.Component),
                Kind + "|" + arity.ToString(CultureInfo.InvariantCulture),
                Pattern);
        }

        internal TerminalKind Kind { get; }
        internal string Pattern { get; }
        internal int Arity { get; }
        internal bool HasEntity { get; }
        internal bool IsFunctor { get; }
        internal string? FunctorType { get; }
        internal bool HasContext { get; }
        internal string? ContextType { get; }
        internal string[] Components { get; }
        internal string? MethodGroupTarget { get; }
        internal ApiModel Api { get; }
        internal List<string[]> StaticMethodGroupComponents { get; } = new();
        internal bool IsCallback => Kind is TerminalKind.ForEach or TerminalKind.ForEachEntity;
        internal string SignatureKey => Api.SignatureKey;
        internal string Key => SignatureKey
            + "|" + string.Join(";", Components);

        internal void Merge(TerminalModel candidate)
        {
            if (!IsFunctor && candidate.MethodGroupTarget is not null)
            {
                AddUnique(StaticMethodGroupComponents, candidate.Components);
            }
        }

        internal void RegisterStaticMethodGroup()
            => AddUnique(StaticMethodGroupComponents, Components);

        private static void AddUnique(List<string[]> values, string[] candidate)
        {
            if (!values.Any(existing => existing.SequenceEqual(candidate, StringComparer.Ordinal)))
            {
                values.Add(candidate);
            }
        }
    }

    private sealed class WhereInterceptionSite
    {
        internal WhereInterceptionSite(
            string id,
            PredicateModel shape,
            TerminalModel terminal,
            LambdaExpressionSyntax? predicate,
            LambdaExpressionSyntax? action,
            IMethodSymbol? predicateMethodGroup,
            IMethodSymbol? actionMethodGroup,
            string[] predicateComponents,
            string[] actionComponents,
            string attribute,
            string[] usings)
        {
            Id = id;
            Shape = shape;
            Terminal = terminal;
            PredicateMethodGroupTarget = predicateMethodGroup is null ? null : StaticMethodGroupTarget(predicateMethodGroup);
            ActionMethodGroupTarget = actionMethodGroup is null ? null : StaticMethodGroupTarget(actionMethodGroup);
            PredicateComponents = predicateComponents;
            ActionComponents = actionComponents;
            Attribute = attribute;
            Usings = usings;
            PredicateParameterNames = predicate is null
                ? InterceptedPredicateParameterNames(shape)
                : LambdaParameters(predicate).Select(static parameter => parameter.Identifier.ValueText).ToArray();
            ActionParameterNames = action is null
                ? InterceptedActionParameterNames(terminal)
                : LambdaParameters(action).Select(static parameter => parameter.Identifier.ValueText).ToArray();
            PredicateBody = predicate switch
            {
                { Body: BlockSyntax block } => block.Statements.ToFullString(),
                { Body: ExpressionSyntax expression } => expression.ToString(),
                _ => null
            };
            ActionBody = action switch
            {
                { Body: BlockSyntax block } => block.Statements.ToFullString(),
                { Body: ExpressionSyntax expression } => expression.ToString(),
                _ => null
            };
            PredicateBodyIsBlock = predicate?.Body is BlockSyntax;
            ActionBodyIsBlock = action?.Body is BlockSyntax;
        }

        internal string Id { get; }
        internal PredicateModel Shape { get; }
        internal TerminalModel Terminal { get; }
        internal string[] PredicateParameterNames { get; }
        internal string[] ActionParameterNames { get; }
        internal string? PredicateBody { get; }
        internal string? ActionBody { get; }
        internal bool PredicateBodyIsBlock { get; }
        internal bool ActionBodyIsBlock { get; }
        internal string? PredicateMethodGroupTarget { get; }
        internal string? ActionMethodGroupTarget { get; }
        internal string[] PredicateComponents { get; }
        internal string[] ActionComponents { get; }
        internal string Attribute { get; }
        internal string[] Usings { get; }
    }

