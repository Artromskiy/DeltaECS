/// <summary>Generates stack-only read-only predicate views for query-wide mutation terminals.</summary>
[Generator]
public sealed class GeneratedWhereGenerator : IIncrementalGenerator
{
    private const int MaxArity = 256;
    private static readonly DiagnosticDescriptor WritablePredicate = new(
        "DECSGEN006",
        "Where predicate is read-only",
        "Where predicates cannot write components; use 'in' or 'ref readonly' parameters and mutate in a terminal callback",
        "Where",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);
    private static readonly DiagnosticDescriptor EntityPredicateRequiresWhereEntity = new(
        "DECSGEN007",
        "Where predicate does not receive Entity",
        "Where predicates cannot receive Entity; use 'WhereEntity' for an entity parameter",
        "Where",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private const string Header = """
        // <auto-generated />
        #nullable enable
        using global::System;
        namespace Delta.ECS
        {

        """;
    private const int FirstInterceptorLanguageVersion = 1100;
    private const string InterceptorNamespace = "Delta.ECS.Generated";
    private const string InterceptorHeader = """
        // <auto-generated />
        #nullable enable
        #pragma warning disable CS0436

        """;
    private const string InterceptorFooter = """
        }

        namespace System.Runtime.CompilerServices
        {

        file sealed class InterceptsLocationAttribute : global::System.Attribute
        {
            internal InterceptsLocationAttribute(int version, string data) { }
        }
        }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(
            context.CompilationProvider.Combine(
                context.AnalyzerConfigOptionsProvider.Select(
                    static (provider, _) => IsInterceptionEnabled(provider.GlobalOptions))),
            static (productionContext, input) => Execute(input.Left, productionContext, input.Right));
    }

    private static void Execute(Compilation compilation, SourceProductionContext context, bool interceptorsEnabled)
    {
        var shapes = new Dictionary<string, PredicateShape>(StringComparer.Ordinal);
        var whereCalls = new Dictionary<InvocationExpressionSyntax, PredicateShape>();
        var interceptionSites = new Dictionary<string, List<WhereInterceptionSite>>(StringComparer.Ordinal);
        bool languageSupportsInterceptors = SupportsInterceptors(compilation);
        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            SemanticModel model = compilation.GetSemanticModel(tree);
            foreach (InvocationExpressionSyntax invocation in tree.GetRoot().DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
                if (!TryReadPredicate(model, invocation, out PredicateShape? candidate)
                    || candidate is null)
                {
                    if (IsWritablePredicate(model, invocation))
                    {
                        context.ReportDiagnostic(Diagnostic.Create(WritablePredicate, invocation.GetLocation()));
                    }
                    else if (IsEntityPredicateWithoutWhereEntity(model, invocation))
                    {
                        context.ReportDiagnostic(Diagnostic.Create(EntityPredicateRequiresWhereEntity, invocation.GetLocation()));
                    }

                    continue;
                }

                if (!shapes.TryGetValue(candidate.Key, out PredicateShape? shape))
                {
                    shape = candidate;
                    shapes.Add(shape.Key, shape);
                }

                whereCalls[invocation] = shape;
            }
        }

        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            SemanticModel model = compilation.GetSemanticModel(tree);
            foreach (InvocationExpressionSyntax invocation in tree.GetRoot().DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
                if (!TryGetWhereReceiver(invocation, out InvocationExpressionSyntax? whereInvocation)
                    || !whereCalls.TryGetValue(whereInvocation, out PredicateShape? shape)
                    || !TryReadTerminal(model, invocation, out TerminalShape? terminal)
                    || terminal is null)
                {
                    continue;
                }

                if (!shape.Terminals.ContainsKey(terminal.SignatureKey))
                {
                    shape.Terminals.Add(terminal.SignatureKey, terminal);
                }

                if (interceptorsEnabled
                    && languageSupportsInterceptors
                    && !shape.IsFunctor
                    && (terminal.IsCallback || terminal.Kind is TerminalKind.Destroy or TerminalKind.Add or TerminalKind.Remove)
                    && TryCreateInterceptionSite(model, whereInvocation, invocation, shape, terminal, tree, out WhereInterceptionSite? site)
                    && site is { } interceptionSite)
                {
                    if (!interceptionSites.TryGetValue(shape.Key, out List<WhereInterceptionSite>? sites))
                    {
                        sites = new List<WhereInterceptionSite>();
                        interceptionSites.Add(shape.Key, sites);
                    }

                    sites.Add(interceptionSite);
                }
            }
        }

        foreach (PredicateShape shape in shapes.Values.OrderBy(static value => value.Key, StringComparer.Ordinal))
        {
            string hash = StableName(shape.Key);
            context.AddSource("GeneratedWhere_" + hash + ".g.cs", Render(shape));
            if (interceptionSites.TryGetValue(shape.Key, out List<WhereInterceptionSite>? sites))
            {
                foreach (WhereInterceptionSite site in sites)
                {
                    context.AddSource(
                        "GeneratedWhereInterceptor_" + site.Id + ".g.cs",
                        RenderInterceptor(site));
                }
            }
        }
    }

    private static bool IsInterceptionEnabled(AnalyzerConfigOptions options)
        => options.TryGetValue("build_property.InterceptorsNamespaces", out string? namespaces)
            && namespaces
                .Split(new[] { ';' }, StringSplitOptions.RemoveEmptyEntries)
                .Any(static value => string.Equals(value.Trim(), InterceptorNamespace, StringComparison.Ordinal));

    private static bool SupportsInterceptors(Compilation compilation)
        => compilation.SyntaxTrees.FirstOrDefault()?.Options is CSharpParseOptions options
            && (int)options.LanguageVersion >= FirstInterceptorLanguageVersion;

    private static bool TryCreateInterceptionSite(
        SemanticModel model,
        InvocationExpressionSyntax whereInvocation,
        InvocationExpressionSyntax terminalInvocation,
        PredicateShape shape,
        TerminalShape terminal,
        SyntaxTree tree,
        out WhereInterceptionSite? site)
    {
        site = null;
        if (whereInvocation.ArgumentList.Arguments.Count != 2
            || whereInvocation.ArgumentList.Arguments[1].Expression is not LambdaExpressionSyntax predicate
            || !predicate.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.StaticKeyword)))
        {
            return false;
        }

        LambdaExpressionSyntax? action = null;
        if (terminal.IsCallback && !terminal.IsFunctor)
        {
            if (terminalInvocation.ArgumentList.Arguments.Count != 1
                || terminalInvocation.ArgumentList.Arguments[0].Expression is not LambdaExpressionSyntax lambda
                || !lambda.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.StaticKeyword)))
            {
                return false;
            }

            action = lambda;
        }
        else if (terminal.IsCallback
            && (terminalInvocation.ArgumentList.Arguments.Count != (terminal.HasContext ? 2 : 1)
                || !terminalInvocation.ArgumentList.Arguments.Last().RefKindKeyword.IsKind(SyntaxKind.RefKeyword)))
        {
            return false;
        }

        if (!TryGetInterceptionLocation(model, terminalInvocation, out string locationData, out string attributeSyntax))
        {
            return false;
        }

        if (!AreLambdaReferencesAccessible(model, predicate)
            || (action is not null && !AreLambdaReferencesAccessible(model, action)))
        {
            return false;
        }

        ParameterSyntax[] predicateParameters = LambdaParameters(predicate);
        ParameterSyntax[] actionParameters = action is null ? Array.Empty<ParameterSyntax>() : LambdaParameters(action);
        string[] predicateComponents = predicateParameters
            .Skip(shape.HasEntity ? 1 : 0)
            .Select(parameter => DisplayType(model.GetTypeInfo(parameter.Type!).Type!))
            .ToArray();
        int actionComponentStart = terminal.HasEntity ? 1 : 0;
        string[] actionComponents = action is null
            ? terminal.Components
            : actionParameters
                .Skip(actionComponentStart)
                .Select(parameter => DisplayType(model.GetTypeInfo(parameter.Type!).Type!))
                .ToArray();

        var usings = tree.GetRoot()
            .DescendantNodes()
            .OfType<UsingDirectiveSyntax>()
            .Select(static directive => directive.ToString())
            .Distinct(StringComparer.Ordinal)
            .ToArray();
        ISymbol? enclosing = model.GetEnclosingSymbol(terminalInvocation.SpanStart);
        if (enclosing is not null)
        {
            string namespaceName = enclosing.ContainingNamespace?.ToDisplayString() ?? string.Empty;
            if (namespaceName.Length > 0)
            {
                usings = usings
                    .Append("using global::" + namespaceName + ";")
                    .Distinct(StringComparer.Ordinal)
                    .ToArray();
            }

            if (enclosing.ContainingType is { Arity: 0 } containingType
                && IsAccessibleToGeneratedCode(containingType))
            {
                usings = usings
                    .Append("using static " + containingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ";")
                    .Distinct(StringComparer.Ordinal)
                    .ToArray();
            }
        }
        string id = StableName(shape.Key + "|" + terminal.Key + "|" + locationData);
        site = new WhereInterceptionSite(
            id,
            shape,
            terminal,
            predicate,
            action,
            predicateComponents,
            actionComponents,
            attributeSyntax,
            usings);
        return true;
    }

    private static bool TryGetInterceptionLocation(
        SemanticModel model,
        InvocationExpressionSyntax invocation,
        out string data,
        out string attributeSyntax)
    {
        data = string.Empty;
        attributeSyntax = string.Empty;
        MethodInfo? getLocation = typeof(Microsoft.CodeAnalysis.CSharp.CSharpExtensions)
            .GetMethods(BindingFlags.Public | BindingFlags.Static)
            .FirstOrDefault(static method =>
            {
                if (method.Name != "GetInterceptableLocation")
                {
                    return false;
                }

                ParameterInfo[] parameters = method.GetParameters();
                return parameters.Length == 3
                    && parameters[0].ParameterType == typeof(SemanticModel)
                    && parameters[1].ParameterType == typeof(InvocationExpressionSyntax);
            });
        if (getLocation is null)
        {
            return false;
        }

        object? location = getLocation.Invoke(null, new object?[] { model, invocation, default });
        if (location is null)
        {
            return false;
        }

        data = location.GetType().GetProperty("Data")?.GetValue(location) as string ?? string.Empty;
        if (data.Length == 0)
        {
            return false;
        }

        MethodInfo? getAttribute = typeof(Microsoft.CodeAnalysis.CSharp.CSharpExtensions)
            .GetMethods(BindingFlags.Public | BindingFlags.Static)
            .FirstOrDefault(static method => method.Name == "GetInterceptsLocationAttributeSyntax"
                && method.GetParameters().Length == 1);
        if (getAttribute is null)
        {
            return false;
        }

        attributeSyntax = getAttribute.Invoke(null, new[] { location })?.ToString() ?? string.Empty;
        return attributeSyntax.Length > 0;
    }

    private static string RenderInterceptor(WhereInterceptionSite site)
    {
        PredicateShape shape = site.Shape;
        TerminalShape terminal = site.Terminal;
        string hash = StableName(shape.Key);
        string terminalHash = StableName(terminal.SignatureKey);
        var source = new StringBuilder(24 * 1024);
        source.Append(InterceptorHeader);
        if (!site.Usings.Any(static value => value.Trim() is "using Delta.ECS;" or "using global::Delta.ECS;"))
        {
            source.AppendLine("using global::Delta.ECS;");
        }

        foreach (string usingDirective in site.Usings)
        {
            source.AppendLine(usingDirective);
        }

        source.Append("namespace Delta.ECS.Generated\n{\n\nfile static class GeneratedWhereInterceptor_")
            .Append(site.Id).AppendLine();
        source.AppendLine("{");
        RenderInterceptedPredicate(source, site);
        if (terminal.IsCallback && !terminal.IsFunctor)
        {
            RenderInterceptedAction(source, site);
        }
        if (terminal.IsCallback)
        {
            RenderInterceptedWhereLoop(source, site);
        }
        else
        {
            RenderInterceptedStructuralLoop(source, site);
        }
        source.Append("    ").Append(site.Attribute).AppendLine();
        source.Append("    internal static ")
            .Append(terminal.IsCallback ? "void" : "int")
            .Append(" Intercept_").Append(site.Id)
            .Append("(this in global::Delta.ECS.GeneratedWhereQuery_")
            .Append(hash).Append(TypeArguments(site.PredicateComponents)).Append(" view");
        if (!terminal.IsCallback)
        {
            source.AppendLine(")");
        }
        else if (terminal.IsFunctor)
        {
            source.Append(", ");
            if (terminal.HasContext)
            {
                source.Append("ref ").Append(terminal.ContextType).Append(" context, ");
            }

            source.Append("ref ").Append(terminal.FunctorType).AppendLine(" action)");
        }
        else
        {
            source.Append(", ");
            source.Append("global::Delta.ECS.GeneratedWhereAction_").Append(hash).Append('_').Append(terminalHash)
                .Append(TypeArguments(site.ActionComponents)).AppendLine(" _)");
        }
        source.AppendLine("    {");
        source.AppendLine("        global::Delta.ECS.Query query = view.Query;");
        if (!terminal.IsCallback)
        {
            source.Append("        return Execute_").Append(site.Id).Append("(view.World, in query");
        }
        else
        {
            source.Append("        Execute_").Append(site.Id).Append("(view.World, in query");
        }
        if (terminal.IsFunctor)
        {
            if (terminal.HasContext)
            {
                source.Append(", ref context");
            }

            source.Append(", ref action");
        }

        source.AppendLine(");");
        source.AppendLine("    }");
        source.AppendLine("}");
        source.Append(InterceptorFooter);
        return GeneratedSourceFormatter.Format(source.ToString());
    }

    private static bool AreLambdaReferencesAccessible(SemanticModel model, LambdaExpressionSyntax lambda)
    {
        foreach (SyntaxNode node in lambda.Body.DescendantNodesAndSelf())
        {
            ISymbol? symbol = model.GetSymbolInfo(node).Symbol;
            if (symbol is null or IParameterSymbol or ILocalSymbol or IRangeVariableSymbol)
            {
                continue;
            }

            if (symbol is ITypeParameterSymbol || !IsAccessibleToGeneratedCode(symbol))
            {
                return false;
            }
        }

        for (INamedTypeSymbol? type = model.GetEnclosingSymbol(lambda.SpanStart)?.ContainingType;
             type is not null;
             type = type.ContainingType)
        {
            if (type.Arity != 0)
            {
                return false;
            }
        }

        return model.GetEnclosingSymbol(lambda.SpanStart) is not IMethodSymbol { IsGenericMethod: true };
    }

    private static void RenderInterceptedPredicate(StringBuilder source, WhereInterceptionSite site)
    {
        PredicateShape shape = site.Shape;
        ParameterSyntax[] parameters = LambdaParameters(site.Predicate);
        source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        source.Append("    private static bool Predicate_").Append(site.Id).Append('(');
        int parameterIndex = 0;
        if (shape.HasEntity)
        {
            source.Append("Entity ").Append(parameters[parameterIndex++].Identifier.ValueText);
        }

        for (int index = 0; index < shape.Arity; index++)
        {
            if (parameterIndex > 0)
            {
                source.Append(", ");
            }

            source.Append(ParameterPrefix(shape.Pattern[index])).Append(site.PredicateComponents[index]).Append(' ')
                .Append(parameters[parameterIndex++].Identifier.ValueText);
        }

        source.AppendLine(")");
        source.AppendLine("    {");
        if (site.Predicate.Body is BlockSyntax block)
        {
            AppendIndented(source, block.Statements.ToFullString(), "        ");
        }
        else
        {
            source.Append("        return ").Append(site.Predicate.Body).AppendLine(";");
        }

        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void RenderInterceptedAction(StringBuilder source, WhereInterceptionSite site)
    {
        TerminalShape terminal = site.Terminal;
        ParameterSyntax[] parameters = LambdaParameters(site.Action!);
        int parameterIndex = 0;
        source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        source.Append("    private static void Action_").Append(site.Id).Append("(");
        var declarations = new List<string>();
        if (terminal.HasEntity)
        {
            declarations.Add("Entity " + parameters[parameterIndex++].Identifier.ValueText);
        }

        for (int index = 0; index < terminal.Arity; index++)
        {
            declarations.Add(
                ParameterPrefix(terminal.Pattern[index])
                + site.ActionComponents[index]
                + " "
                + parameters[parameterIndex++].Identifier.ValueText);
        }

        source.Append(string.Join(", ", declarations)).AppendLine(")");
        source.AppendLine("    {");
        if (site.Action!.Body is BlockSyntax block)
        {
            AppendIndented(source, block.Statements.ToFullString(), "        ");
        }
        else
        {
            source.Append("        ").Append(site.Action!.Body).AppendLine(";");
        }

        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void RenderInterceptedWhereLoop(StringBuilder source, WhereInterceptionSite site)
    {
        PredicateShape shape = site.Shape;
        TerminalShape terminal = site.Terminal;
        string executeName = "Execute_" + site.Id;
        source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        source.Append("    private static void ").Append(executeName)
            .Append("(global::Delta.ECS.World world, in global::Delta.ECS.Query query");
        if (terminal.IsFunctor && terminal.HasContext)
        {
            source.Append(", ref ").Append(terminal.ContextType).Append(" context");
        }

        if (terminal.IsFunctor)
        {
            source.Append(", ref ").Append(terminal.FunctorType).Append(" action");
        }

        source.AppendLine(")");
        source.AppendLine("    {");
        source.AppendLine("        using var execution = global::Delta.ECS.GeneratedForEachRuntime.OpenDense(world, in query);");
        int accessCount = shape.Arity + terminal.Arity;
        for (int index = 0; index < accessCount; index++)
        {
            string componentType = index < shape.Arity ? site.PredicateComponents[index] : site.ActionComponents[index - shape.Arity];
            string pattern = index < shape.Arity ? shape.Pattern : terminal.Pattern;
            source.Append("        var access").Append(index).Append(" = global::Delta.ECS.GeneratedForEachRuntime.GetPrepared")
                .Append(IsWrite(pattern[index < shape.Arity ? index : index - shape.Arity]) ? "Write" : "Read")
                .Append("Access<").Append(componentType).AppendLine(">(in query);");
        }

        string writes = WriteIndices(shape.Pattern, terminal.Pattern, shape.Arity);
        source.Append("        execution.MarkArchetypeWrites(").Append(writes).AppendLine(");");
        source.AppendLine("        while (execution.MoveNextTrusted(out var slots))");
        source.AppendLine("        {");
        for (int index = 0; index < accessCount; index++)
        {
            string componentType = index < shape.Arity ? site.PredicateComponents[index] : site.ActionComponents[index - shape.Arity];
            string pattern = index < shape.Arity ? shape.Pattern : terminal.Pattern;
            source.Append("            ref ")
                .Append(componentType).Append(" row").Append(index).Append(" = ref slots.GetGenerated")
                .Append(IsWrite(pattern[index < shape.Arity ? index : index - shape.Arity]) ? "Write" : "Read")
                .Append("Reference<").Append(componentType).Append(">(access").Append(index).AppendLine(");");
        }

        source.AppendLine("            for (int index = 0; index < slots.Count; index++)");
        source.AppendLine("            {");
        source.Append("                Entity __whereEntity_").Append(site.Id).AppendLine(" = slots.EntityAt(index);");
        for (int index = 0; index < shape.Arity; index++)
        {
            source.Append("                ref ")
                .Append(site.PredicateComponents[index]).Append(" __wherePredicateComponent").Append(index)
                .Append(" = ref global::System.Runtime.CompilerServices.Unsafe.Add(ref ")
                .Append("row")
                .Append(index).Append(", index);").AppendLine();
        }

        source.Append("                if (!Predicate_").Append(site.Id).Append('(');
        if (shape.HasEntity)
        {
            source.Append("__whereEntity_").Append(site.Id);
        }

        for (int index = 0; index < shape.Arity; index++)
        {
            if (shape.HasEntity || index > 0)
            {
                source.Append(", ");
            }

            source.Append(InvocationPrefix(shape.Pattern[index])).Append("__wherePredicateComponent").Append(index);
        }

        source.AppendLine("))");
        source.AppendLine("                {");
        source.AppendLine("                    continue;");
        source.AppendLine("                }");
        for (int index = 0; index < terminal.Arity; index++)
        {
            source.Append("                ref ")
                .Append(site.ActionComponents[index]).Append(" __whereActionComponent").Append(index)
                .Append(" = ref global::System.Runtime.CompilerServices.Unsafe.Add(ref ")
                .Append("row")
                .Append(shape.Arity + index).Append(", index);").AppendLine();
        }

        if (terminal.IsFunctor)
        {
            source.Append("                action.Invoke(");
            if (terminal.HasContext)
            {
                source.Append("ref context");
                if (terminal.HasEntity || terminal.Arity > 0)
                {
                    source.Append(", ");
                }
            }

            if (terminal.HasEntity)
            {
                source.Append("__whereEntity_").Append(site.Id);
                if (terminal.Arity > 0)
                {
                    source.Append(", ");
                }
            }
        }
        else
        {
            source.Append("                Action_").Append(site.Id).Append('(');
            if (terminal.HasEntity)
            {
                source.Append("__whereEntity_").Append(site.Id);
                if (terminal.Arity > 0)
                {
                    source.Append(", ");
                }
            }
        }

        for (int index = 0; index < terminal.Arity; index++)
        {
            if (index > 0)
            {
                source.Append(", ");
            }

            source.Append(InvocationPrefix(terminal.Pattern[index])).Append("__whereActionComponent").Append(index);
        }

        source.AppendLine(");");

        source.AppendLine("            }");
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void RenderInterceptedStructuralLoop(StringBuilder source, WhereInterceptionSite site)
    {
        PredicateShape shape = site.Shape;
        TerminalShape terminal = site.Terminal;
        string invokerName = "StructuralInvoker_" + site.Id;
        string executeName = "Execute_" + site.Id;

        source.Append("    private struct ").Append(invokerName).AppendLine(" : global::Delta.ECS.IGeneratedWhereStructuralInvoker");
        source.AppendLine("    {");
        for (int index = 0; index < shape.Arity; index++)
        {
            source.Append("        private readonly int _access").Append(index).AppendLine(";");
        }

        source.Append("        internal ").Append(invokerName).Append('(');
        for (int index = 0; index < shape.Arity; index++)
        {
            if (index > 0)
            {
                source.Append(", ");
            }

            source.Append("int access").Append(index);
        }

        source.AppendLine(")");
        source.AppendLine("        {");
        for (int index = 0; index < shape.Arity; index++)
        {
            source.Append("            _access").Append(index).Append(" = access").Append(index).AppendLine(";");
        }

        source.AppendLine("        }");
        source.AppendLine();
        source.AppendLine("        public void Execute(ref GeneratedQuerySlots slots, ref GeneratedWhereStructuralContext context)");
        source.AppendLine("        {");
        source.AppendLine("            if (slots.Count == 0)");
        source.AppendLine("            {");
        source.AppendLine("                return;");
        source.AppendLine("            }");
        RenderRowLocals(source, shape.Pattern, shape.Arity, site.PredicateComponents, "T", "            ");
        source.AppendLine("            int runStart = 0;");
        source.AppendLine("            bool runSelected = false;");
        source.AppendLine("            for (int index = 0; index < slots.Count; index++)");
        source.AppendLine("            {");
        RenderComponentLocals(source, shape.Pattern, shape.Arity, site.PredicateComponents, "T", "                ");
        source.AppendLine("                Entity entity = slots.EntityAt(index);");
        source.Append("                bool selected = Predicate_").Append(site.Id).Append('(');
        AppendInterceptedPredicateArguments(source, shape);
        source.AppendLine(");");
        source.AppendLine("                if (index != 0 && selected != runSelected)");
        source.AppendLine("                {");
        source.AppendLine("                    context.ProcessRun(runStart, index - runStart, runSelected);");
        source.AppendLine("                    runStart = index;");
        source.AppendLine("                }");
        source.AppendLine("                runSelected = selected;");
        source.AppendLine("            }");
        source.AppendLine("            context.ProcessRun(runStart, slots.Count - runStart, runSelected);");
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine();

        source.Append("    private static int ").Append(executeName)
            .AppendLine("(global::Delta.ECS.World world, in global::Delta.ECS.Query query)");
        source.AppendLine("    {");
        for (int index = 0; index < shape.Arity; index++)
        {
            source.Append("        var access").Append(index).Append(" = global::Delta.ECS.GeneratedForEachRuntime.GetPrepared")
                .Append(IsWrite(shape.Pattern[index]) ? "Write" : "Read")
                .Append("Access<").Append(site.PredicateComponents[index]).AppendLine(">(in query);");
        }

        source.Append("        var invoker = new ").Append(invokerName).Append('(');
        for (int index = 0; index < shape.Arity; index++)
        {
            if (index > 0)
            {
                source.Append(", ");
            }

            source.Append("global::Delta.ECS.GeneratedForEachRuntime.Get")
                .Append(IsWrite(shape.Pattern[index]) ? "Write" : "Read")
                .Append("QueryComponentIndex(access").Append(index).Append(')');
        }

        source.AppendLine(");");
        if (terminal.Kind is TerminalKind.Add or TerminalKind.Remove)
        {
            source.Append("        global::System.Span<global::Delta.ECS.ComponentId> components = stackalloc global::Delta.ECS.ComponentId[")
                .Append(terminal.Arity).AppendLine("];");
            for (int index = 0; index < terminal.Arity; index++)
            {
                source.Append("        components[").Append(index).Append("] = world.Layouts.GetPrimary<")
                    .Append(site.ActionComponents[index]).AppendLine(">();");
            }
        }

        source.Append("        return global::Delta.ECS.GeneratedForEachRuntime.ExecuteGeneratedWhere");
        source.Append(terminal.Kind switch
        {
            TerminalKind.Destroy => "Destroy",
            TerminalKind.Add => "Add",
            TerminalKind.Remove => "Remove",
            _ => string.Empty
        });
        source.Append("(world, in query, ref invoker, ")
            .Append(WriteIndices(shape.Pattern, string.Empty, shape.Arity));
        if (terminal.Kind is TerminalKind.Add or TerminalKind.Remove)
        {
            source.Append(", components");
        }

        source.AppendLine(");");
        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void AppendInterceptedPredicateArguments(StringBuilder source, PredicateShape shape)
    {
        bool hasArgument = false;
        if (shape.HasEntity)
        {
            source.Append("entity");
            hasArgument = true;
        }

        for (int index = 0; index < shape.Arity; index++)
        {
            if (hasArgument)
            {
                source.Append(", ");
            }

            source.Append(InvocationPrefix(shape.Pattern[index])).Append("component").Append(index);
            hasArgument = true;
        }
    }

    private static void AppendIndented(StringBuilder source, string text, string indent)
    {
        foreach (string line in text.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None))
        {
            source.Append(indent).AppendLine(line);
        }
    }

    private static bool TryReadPredicate(
        SemanticModel model,
        InvocationExpressionSyntax invocation,
        out PredicateShape? shape)
    {
        shape = null;
        if (invocation.Expression is not MemberAccessExpressionSyntax member
            || member.Name is not IdentifierNameSyntax methodName
            || methodName.Identifier.ValueText is not ("Where" or "WhereEntity")
            || invocation.ArgumentList.Arguments.Count is not (2 or 3)
            || !invocation.ArgumentList.Arguments[0].RefKindKeyword.IsKind(SyntaxKind.InKeyword)
            || !IsNamedType(model.GetTypeInfo(member.Expression).Type, "World"))
        {
            return false;
        }

        bool hasEntity = methodName.Identifier.ValueText == "WhereEntity";

        ArgumentSyntax predicateArgument = invocation.ArgumentList.Arguments[invocation.ArgumentList.Arguments.Count - 1];
        if (predicateArgument.Expression is not LambdaExpressionSyntax lambda)
        {
            ArgumentSyntax? contextArgument = invocation.ArgumentList.Arguments.Count == 3
                ? invocation.ArgumentList.Arguments[1]
                : null;
            return TryReadFunctorPredicate(model, predicateArgument, contextArgument, hasEntity, out shape);
        }

        ArgumentSyntax? lambdaContextArgument = invocation.ArgumentList.Arguments.Count == 3
            ? invocation.ArgumentList.Arguments[1]
            : null;
        bool hasContext = lambdaContextArgument is not null;
        ITypeSymbol? contextType = null;
        ParameterSyntax[] parameters = LambdaParameters(lambda);
        int parameterStart = 0;
        if (hasContext)
        {
            if (!lambdaContextArgument!.RefKindKeyword.IsKind(SyntaxKind.RefKeyword)
                || parameters.Length == 0
                || !IsContextParameter(model, parameters[0], lambdaContextArgument, out contextType))
            {
                return false;
            }

            parameterStart = 1;
        }

        if (hasEntity)
        {
            if (parameters.Length <= parameterStart || !IsEntityParameter(model, parameters[parameterStart]))
            {
                return false;
            }

            parameterStart++;
        }
        else if (parameters.Skip(parameterStart).Any(parameter => IsEntityParameter(model, parameter)))
        {
            return false;
        }

        string pattern = new string(parameters
            .Skip(parameterStart)
            .Select(parameter => PatternLetter(parameter))
            .ToArray());
        if (pattern.Length > MaxArity
            || parameters.Skip(parameterStart).Any(parameter =>
                !HasTypedAccessibleParameter(model, parameter)
                || PatternLetter(parameter) == 'W'))
        {
            return false;
        }

        shape = new PredicateShape(
            pattern,
            isFunctor: false,
            functorType: null,
            hasEntity,
            hasContext,
            contextType is null ? null : DisplayType(contextType),
            components: null);
        return true;
    }

    private static bool TryReadFunctorPredicate(
        SemanticModel model,
        ArgumentSyntax argument,
        ArgumentSyntax? contextArgument,
        bool hasEntity,
        out PredicateShape? shape)
    {
        shape = null;
        if (!argument.RefKindKeyword.IsKind(SyntaxKind.RefKeyword)
            || model.GetTypeInfo(argument.Expression).Type is not INamedTypeSymbol functorType
            || !HasPredicateMarker(functorType)
            || !IsAccessibleToGeneratedCode(functorType))
        {
            return false;
        }

        bool hasContext = contextArgument is not null;
        ITypeSymbol? contextType = null;
        if (hasContext)
        {
            if (!contextArgument!.RefKindKeyword.IsKind(SyntaxKind.RefKeyword)
                || model.GetTypeInfo(contextArgument.Expression).Type is not ITypeSymbol actualContext)
            {
                return false;
            }

            contextType = actualContext;
        }

        IMethodSymbol[] invokes = functorType.GetMembers("Invoke")
            .OfType<IMethodSymbol>()
            .Where(static method => !method.IsStatic && method.ReturnType.SpecialType == SpecialType.System_Boolean)
            .Where(method => HasValidPredicatePrefix(method, hasContext, hasEntity, contextType))
            .Where(method => method.Parameters.Skip((hasContext ? 1 : 0) + (hasEntity ? 1 : 0)).All(
                static parameter => IsSupportedPredicateRefKind(parameter.RefKind)))
            .ToArray();
        if (invokes.Length != 1)
        {
            return false;
        }

        IMethodSymbol invoke = invokes[0];
        int componentStart = (hasContext ? 1 : 0) + (hasEntity ? 1 : 0);
        IParameterSymbol[] components = invoke.Parameters.Skip(componentStart).ToArray();
        if (!hasEntity
            && components.Any(static component => component.RefKind == RefKind.None && IsEntityType(component.Type)))
        {
            return false;
        }

        if (components.Length > MaxArity
            || components.Any(static parameter => !IsAccessibleToGeneratedCode(parameter.Type)))
        {
            return false;
        }

        string pattern = new(components.Select(static parameter => PatternLetter(parameter.RefKind)).ToArray());
        shape = new PredicateShape(
            pattern,
            isFunctor: true,
            functorType: DisplayType(functorType),
            hasEntity,
            hasContext,
            contextType: hasContext && contextType is { } resolvedContext ? DisplayType(resolvedContext) : null,
            components: components.Select(static parameter => DisplayType(parameter.Type)).ToArray());
        return true;
    }

    private static bool HasPredicateMarker(INamedTypeSymbol functorType)
    {
        INamedTypeSymbol[] markers = functorType.AllInterfaces
            .Where(static type => type.ContainingNamespace.ToDisplayString() == "Delta.ECS")
            .Where(static type => type.Name == "IWherePredicate")
            .ToArray();
        return markers.Length == 1;
    }

    private static bool HasValidPredicatePrefix(
        IMethodSymbol method,
        bool hasContext,
        bool hasEntity,
        ITypeSymbol? contextType)
    {
        int index = 0;
        if (hasContext)
        {
            if (method.Parameters.Length == 0
                || method.Parameters[0].RefKind != RefKind.Ref
                || !SymbolEqualityComparer.Default.Equals(method.Parameters[0].Type, contextType))
            {
                return false;
            }

            index++;
        }

        if (hasEntity)
        {
            if (method.Parameters.Length <= index
                || method.Parameters[index].RefKind != RefKind.None
                || !IsEntityType(method.Parameters[index].Type))
            {
                return false;
            }

            index++;
        }

        return method.Parameters.Length >= index;
    }

    private static bool IsSupportedPredicateRefKind(RefKind refKind)
        => refKind is RefKind.None or RefKind.In
            || (int)refKind is 4 or 5;

    private static bool IsWritablePredicate(SemanticModel model, InvocationExpressionSyntax invocation)
    {
        if (invocation.Expression is not MemberAccessExpressionSyntax member
            || member.Name is not IdentifierNameSyntax methodName
            || methodName.Identifier.ValueText is not ("Where" or "WhereEntity")
            || invocation.ArgumentList.Arguments.Count is not (2 or 3)
            || !invocation.ArgumentList.Arguments[0].RefKindKeyword.IsKind(SyntaxKind.InKeyword)
            || !IsNamedType(model.GetTypeInfo(member.Expression).Type, "World")
            || invocation.ArgumentList.Arguments[invocation.ArgumentList.Arguments.Count - 1].Expression is not LambdaExpressionSyntax lambda)
        {
            return false;
        }

        ParameterSyntax[] parameters = LambdaParameters(lambda);
        int parameterStart = invocation.ArgumentList.Arguments.Count == 3 ? 1 : 0;
        return parameters.Length > parameterStart
            && parameters.Skip(parameterStart + (methodName.Identifier.ValueText == "WhereEntity" ? 1 : 0))
                .Any(static parameter => PatternLetter(parameter) == 'W');
    }

    private static bool IsEntityPredicateWithoutWhereEntity(SemanticModel model, InvocationExpressionSyntax invocation)
    {
        if (invocation.Expression is not MemberAccessExpressionSyntax member
            || member.Name is not IdentifierNameSyntax methodName
            || methodName.Identifier.ValueText != "Where"
            || invocation.ArgumentList.Arguments.Count is not (2 or 3)
            || !invocation.ArgumentList.Arguments[0].RefKindKeyword.IsKind(SyntaxKind.InKeyword)
            || !IsNamedType(model.GetTypeInfo(member.Expression).Type, "World"))
        {
            return false;
        }

        ArgumentSyntax predicateArgument = invocation.ArgumentList.Arguments[invocation.ArgumentList.Arguments.Count - 1];
        if (predicateArgument.Expression is LambdaExpressionSyntax lambda)
        {
            ParameterSyntax[] parameters = LambdaParameters(lambda);
            int parameterStart = invocation.ArgumentList.Arguments.Count == 3 ? 1 : 0;
            return parameters.Skip(parameterStart).Any(parameter => IsEntityParameter(model, parameter));
        }

        if (!predicateArgument.RefKindKeyword.IsKind(SyntaxKind.RefKeyword)
            || model.GetTypeInfo(predicateArgument.Expression).Type is not INamedTypeSymbol functorType
            || !HasPredicateMarker(functorType))
        {
            return false;
        }

        int componentStart = invocation.ArgumentList.Arguments.Count == 3 ? 1 : 0;
        return functorType.GetMembers("Invoke")
            .OfType<IMethodSymbol>()
            .Where(static method => !method.IsStatic && method.ReturnType.SpecialType == SpecialType.System_Boolean)
            .Any(method => method.Parameters
                .Skip(componentStart)
                .Any(parameter => parameter.RefKind == RefKind.None && IsEntityType(parameter.Type)));
    }

    private static bool TryGetWhereReceiver(
        InvocationExpressionSyntax invocation,
        out InvocationExpressionSyntax whereInvocation)
    {
        whereInvocation = null!;
        return invocation.Expression is MemberAccessExpressionSyntax member
            && member.Expression is InvocationExpressionSyntax candidate
            && candidate.Expression is MemberAccessExpressionSyntax whereMember
            && whereMember.Name is IdentifierNameSyntax whereName
            && whereName.Identifier.ValueText is "Where" or "WhereEntity"
            && (whereInvocation = candidate) is not null;
    }

    private static bool TryReadTerminal(
        SemanticModel model,
        InvocationExpressionSyntax invocation,
        out TerminalShape? terminal)
    {
        terminal = null;
        if (invocation.Expression is not MemberAccessExpressionSyntax member)
        {
            return false;
        }

        string name = member.Name.Identifier.ValueText;
        if (name == "Destroy" && member.Name is IdentifierNameSyntax && invocation.ArgumentList.Arguments.Count == 0)
        {
            terminal = new TerminalShape(TerminalKind.Destroy, string.Empty, 0, hasEntity: false);
            return true;
        }

        if (name is "Add" or "Remove"
            && member.Name is GenericNameSyntax genericName
            && invocation.ArgumentList.Arguments.Count == 0
            && genericName.TypeArgumentList.Arguments.Count is >= 1 and <= MaxArity)
        {
            terminal = new TerminalShape(
                name == "Add" ? TerminalKind.Add : TerminalKind.Remove,
                string.Empty,
                genericName.TypeArgumentList.Arguments.Count,
                hasEntity: false,
                components: genericName.TypeArgumentList.Arguments
                    .Select(argument => DisplayType(model.GetTypeInfo(argument).Type!))
                    .ToArray());
            return true;
        }

        if (name is "ForEach" or "ForEachEntity"
            && member.Name is IdentifierNameSyntax
            && TryReadFunctorTerminal(model, invocation, name == "ForEachEntity", out terminal))
        {
            return true;
        }

        if (name is not ("ForEach" or "ForEachEntity")
            || member.Name is not IdentifierNameSyntax
            || invocation.ArgumentList.Arguments.Count != 1
            || invocation.ArgumentList.Arguments[0].Expression is not LambdaExpressionSyntax lambda)
        {
            return false;
        }

        ParameterSyntax[] parameters = LambdaParameters(lambda);
        bool hasEntity = name == "ForEachEntity";
        int componentStart = 0;
        if (hasEntity)
        {
            if (parameters.Length == 0 || !IsEntityParameter(model, parameters[0], allowImplicit: true))
            {
                return false;
            }

            componentStart = 1;
        }

        ParameterSyntax[] components = parameters.Skip(componentStart).ToArray();
        if (components.Length > MaxArity || components.Any(parameter => !HasTypedAccessibleParameter(model, parameter)))
        {
            return false;
        }

        terminal = new TerminalShape(
            hasEntity ? TerminalKind.ForEachEntity : TerminalKind.ForEach,
            new string(components.Select(PatternLetter).ToArray()),
            components.Length,
            hasEntity);
        return true;
    }

    private static bool TryReadFunctorTerminal(
        SemanticModel model,
        InvocationExpressionSyntax invocation,
        bool namedEntity,
        out TerminalShape? terminal)
    {
        terminal = null;
        if (invocation.ArgumentList.Arguments.Count == 0)
        {
            return false;
        }

        ArgumentSyntax functorArgument = invocation.ArgumentList.Arguments[invocation.ArgumentList.Arguments.Count - 1];
        if (!functorArgument.RefKindKeyword.IsKind(SyntaxKind.RefKeyword)
            || model.GetTypeInfo(functorArgument.Expression).Type is not INamedTypeSymbol functorType
            || !TryGetForEachMarker(functorType, out bool hasContext, out bool hasEntity, out ITypeSymbol? contextType)
            || namedEntity != hasEntity
            || !IsAccessibleToGeneratedCode(functorType))
        {
            return false;
        }

        if (hasContext)
        {
            if (invocation.ArgumentList.Arguments.Count != 2
                || !invocation.ArgumentList.Arguments[0].RefKindKeyword.IsKind(SyntaxKind.RefKeyword)
                || model.GetTypeInfo(invocation.ArgumentList.Arguments[0].Expression).Type is not ITypeSymbol actualContext
                || !SymbolEqualityComparer.Default.Equals(actualContext, contextType))
            {
                return false;
            }
        }
        else if (invocation.ArgumentList.Arguments.Count != 1)
        {
            return false;
        }

        int prefixCount = (hasContext ? 1 : 0) + (hasEntity ? 1 : 0);
        IMethodSymbol[] invokes = functorType.GetMembers("Invoke")
            .OfType<IMethodSymbol>()
            .Where(static method => !method.IsStatic && method.ReturnsVoid)
            .Where(method => HasValidForEachPrefix(method, hasContext, hasEntity, contextType))
            .Where(method => method.Parameters.Skip(prefixCount).All(
                static parameter => IsSupportedCallbackRefKind(parameter.RefKind)))
            .ToArray();
        if (invokes.Length != 1)
        {
            return false;
        }

        IMethodSymbol invoke = invokes[0];
        IParameterSymbol[] components = invoke.Parameters.Skip(prefixCount).ToArray();
        if (components.Length > MaxArity || components.Any(static parameter => !IsAccessibleToGeneratedCode(parameter.Type)))
        {
            return false;
        }

        terminal = new TerminalShape(
            namedEntity ? TerminalKind.ForEachEntity : TerminalKind.ForEach,
            new string(components.Select(static parameter => PatternLetter(parameter.RefKind)).ToArray()),
            components.Length,
            namedEntity,
            isFunctor: true,
            functorType: DisplayType(functorType),
            hasContext,
            contextType: hasContext && contextType is { } resolvedContext ? DisplayType(resolvedContext) : null,
            components: components.Select(static parameter => DisplayType(parameter.Type)).ToArray());
        return true;
    }

    private static bool TryGetForEachMarker(
        INamedTypeSymbol functorType,
        out bool hasContext,
        out bool hasEntity,
        out ITypeSymbol? contextType)
    {
        hasContext = false;
        hasEntity = false;
        contextType = null;
        INamedTypeSymbol[] markers = functorType.AllInterfaces
            .Where(static type => type.ContainingNamespace.ToDisplayString() == "Delta.ECS")
            .Where(static type => type.Name is "IForEach" or "IForEachEntity" or "IForEachContext" or "IForEachContextEntity")
            .ToArray();
        if (markers.Length != 1)
        {
            return false;
        }

        INamedTypeSymbol marker = markers[0];
        hasContext = marker.Name is "IForEachContext" or "IForEachContextEntity";
        hasEntity = marker.Name is "IForEachEntity" or "IForEachContextEntity";
        contextType = hasContext ? marker.TypeArguments[0] : null;
        return true;
    }

    private static bool HasValidForEachPrefix(
        IMethodSymbol method,
        bool hasContext,
        bool hasEntity,
        ITypeSymbol? contextType)
    {
        int index = 0;
        if (hasContext)
        {
            if (method.Parameters.Length == 0
                || method.Parameters[0].RefKind != RefKind.Ref
                || !SymbolEqualityComparer.Default.Equals(method.Parameters[0].Type, contextType))
            {
                return false;
            }

            index++;
        }

        if (hasEntity)
        {
            if (method.Parameters.Length <= index
                || method.Parameters[index].RefKind != RefKind.None
                || !IsEntityType(method.Parameters[index].Type))
            {
                return false;
            }

            index++;
        }

        return method.Parameters.Length >= index;
    }

    private static bool IsSupportedCallbackRefKind(RefKind refKind)
        => refKind is RefKind.None or RefKind.In or RefKind.Ref
            || (int)refKind is 4 or 5;

    private static bool HasTypedAccessibleParameter(SemanticModel model, ParameterSyntax parameter)
    {
        ITypeSymbol? type = parameter.Type is null ? null : model.GetTypeInfo(parameter.Type).Type;
        return type is not null
            && type.TypeKind != TypeKind.Error
            && type is not ITypeParameterSymbol
            && IsAccessibleToGeneratedCode(type)
            && IsSupportedRefKind(parameter);
    }

    private static bool IsSupportedRefKind(ParameterSyntax parameter)
    {
        bool hasRef = parameter.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.RefKeyword));
        bool hasReadonly = parameter.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.ReadOnlyKeyword));
        bool hasIn = parameter.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.InKeyword));
        return !hasIn || (!hasRef && !hasReadonly);
    }

    private static bool IsEntityParameter(SemanticModel model, ParameterSyntax parameter, bool allowImplicit = false)
        => parameter.Modifiers.Count == 0
            && ((parameter.Type is not null && IsNamedType(model.GetTypeInfo(parameter.Type).Type, "Entity"))
                || (allowImplicit && parameter.Type is null));

    private static bool IsContextParameter(
        SemanticModel model,
        ParameterSyntax parameter,
        ArgumentSyntax contextArgument,
        out ITypeSymbol? contextType)
    {
        contextType = parameter.Type is null ? null : model.GetTypeInfo(parameter.Type).Type;
        return parameter.Modifiers.Count == 1
            && parameter.Modifiers[0].IsKind(SyntaxKind.RefKeyword)
            && contextType is not null
            && contextType.TypeKind != TypeKind.Error
            && contextType is not ITypeParameterSymbol
            && IsAccessibleToGeneratedCode(contextType)
            && model.GetTypeInfo(contextArgument.Expression).Type is ITypeSymbol argumentType
            && SymbolEqualityComparer.Default.Equals(contextType, argumentType);
    }

    private static bool IsNamedType(ITypeSymbol? type, string name)
        => type is INamedTypeSymbol named
            && named.Name == name
            && named.ContainingNamespace.ToDisplayString() == "Delta.ECS";

    private static bool IsEntityType(ITypeSymbol type)
        => IsNamedType(type, "Entity");

    private static string DisplayType(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol { IsTupleType: true } tuple)
        {
            return "(" + string.Join(", ", tuple.TupleElements.Select(static element => DisplayType(element.Type))) + ")";
        }

        return type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    }

    private static bool IsAccessibleToGeneratedCode(ISymbol symbol)
    {
        if (symbol.DeclaredAccessibility is Accessibility.Private
            or Accessibility.Protected
            or Accessibility.ProtectedAndInternal)
        {
            return false;
        }

        for (INamedTypeSymbol? type = symbol.ContainingType; type is not null; type = type.ContainingType)
        {
            if (type.DeclaredAccessibility is Accessibility.Private
                or Accessibility.Protected
                or Accessibility.ProtectedAndInternal)
            {
                return false;
            }
        }

        return symbol is not ITypeSymbol typeSymbol || IsAccessibleToGeneratedCode(typeSymbol);
    }

    private static ParameterSyntax[] LambdaParameters(LambdaExpressionSyntax lambda)
        => lambda switch
        {
            ParenthesizedLambdaExpressionSyntax parenthesized => parenthesized.ParameterList.Parameters.ToArray(),
            SimpleLambdaExpressionSyntax simple => new[] { simple.Parameter },
            _ => Array.Empty<ParameterSyntax>()
        };

    private static char PatternLetter(ParameterSyntax parameter)
    {
        bool hasRef = parameter.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.RefKeyword));
        bool hasReadonly = parameter.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.ReadOnlyKeyword));
        if (hasRef && hasReadonly)
        {
            return 'R';
        }

        if (hasRef)
        {
            return 'W';
        }

        return parameter.Modifiers.Any(static modifier => modifier.IsKind(SyntaxKind.InKeyword)) ? 'I' : 'V';
    }

    private static char PatternLetter(RefKind refKind)
        => refKind switch
        {
            RefKind.In => 'I',
            RefKind.Ref => 'W',
            (RefKind)4 or (RefKind)5 => 'R',
            _ => 'V'
        };

    private static bool IsAccessibleToGeneratedCode(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol array)
        {
            return IsAccessibleToGeneratedCode(array.ElementType);
        }

        if (type is not INamedTypeSymbol named)
        {
            return true;
        }

        return named.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal
            && (named.ContainingType is null || IsAccessibleToGeneratedCode(named.ContainingType));
    }

    private static string Render(PredicateShape shape)
    {
        string hash = StableName(shape.Key);
        var source = new StringBuilder(32 * 1024);
        source.Append(Header);
        RenderPredicateDelegate(source, shape, hash);
        foreach (TerminalShape terminal in shape.Terminals.Values.OrderBy(static value => value.SignatureKey, StringComparer.Ordinal))
        {
            RenderActionDelegate(source, terminal, hash);
            RenderInvoker(source, shape, terminal, hash);
        }

        RenderView(source, shape, hash);
        RenderExtension(source, shape, hash);
        source.AppendLine("}");
        return GeneratedSourceFormatter.Format(source.ToString());
    }

    private static void RenderPredicateDelegate(StringBuilder source, PredicateShape shape, string hash)
    {
        if (shape.IsFunctor)
        {
            return;
        }

        source.Append("public delegate bool GeneratedWherePredicate_").Append(hash).Append(PredicateGenericParameters(shape));
        source.Append('(');
        bool hasParameter = false;
        if (shape.HasContext)
        {
            source.Append("ref ").Append(PredicateContextType(shape)).Append(" context");
            hasParameter = true;
        }

        if (shape.HasEntity)
        {
            if (hasParameter)
            {
                source.Append(", ");
            }

            source.Append("Entity entity");
            hasParameter = true;
        }

        for (int index = 0; index < shape.Arity; index++)
        {
            if (hasParameter)
            {
                source.Append(", ");
            }

            source.Append(ParameterPrefix(shape.Pattern[index])).Append("T").Append(index + 1).Append(" component").Append(index);
            hasParameter = true;
        }

        source.AppendLine(");");
    }

    private static void RenderActionDelegate(StringBuilder source, TerminalShape terminal, string predicateHash)
    {
        if (!terminal.IsCallback || terminal.IsFunctor)
        {
            return;
        }

        string hash = StableName(terminal.SignatureKey);
        source.Append("public delegate void GeneratedWhereAction_").Append(predicateHash).Append('_').Append(hash)
            .Append(GenericTypes(terminal.Arity, "U")).Append('(');
        var parameters = new List<string>();
        if (terminal.HasEntity)
        {
            parameters.Add("Entity entity");
        }

        for (int index = 0; index < terminal.Arity; index++)
        {
            parameters.Add(ParameterPrefix(terminal.Pattern[index]) + "U" + (index + 1) + " component" + index);
        }

        source.Append(string.Join(", ", parameters)).AppendLine(");");
    }

    private static void RenderInvoker(StringBuilder source, PredicateShape shape, TerminalShape terminal, string hash)
    {
        string terminalHash = StableName(terminal.SignatureKey);
        string invokerName = "GeneratedWhereInvoker_" + hash + '_' + terminalHash;
        string generic = JoinGeneric(
            shape.IsFunctor ? string.Empty : PredicateGenericList(shape),
            terminal.IsCallback && !terminal.IsFunctor ? GenericList(terminal.Arity, "U") : string.Empty);
        string contract = terminal.IsCallback ? "IGeneratedWhereInvoker" : "IGeneratedWhereStructuralInvoker";
        source.Append("internal struct ").Append(invokerName).Append(GenericParameters(generic)).Append(" : ").AppendLine(contract);
        source.AppendLine("{");
        source.Append("    private readonly ").Append(PredicateType(shape, hash)).AppendLine(" _predicate;");
        if (shape.HasContext)
        {
            source.Append("    private ").Append(PredicateContextType(shape)).AppendLine(" _predicateContext;");
        }

        if (terminal.IsCallback)
        {
            source.Append("    private readonly ").Append(ActionType(terminal, hash, terminalHash)).AppendLine(" _action;");
            if (terminal.HasContext)
            {
                source.Append("    private ").Append(terminal.ContextType).AppendLine(" _context;");
            }
        }

        int accessCount = shape.Arity + (terminal.IsCallback ? terminal.Arity : 0);
        for (int index = 0; index < accessCount; index++)
        {
            source.Append("    private readonly int _access").Append(index).AppendLine(";");
        }

        source.Append("    internal ").Append(invokerName).Append('(')
            .Append(PredicateType(shape, hash)).Append(" predicate");
        if (shape.HasContext)
        {
            source.Append(", ").Append(PredicateContextType(shape)).Append(" predicateContext");
        }

        if (terminal.IsCallback)
        {
            if (terminal.HasContext)
            {
                source.Append(", ").Append(terminal.ContextType).Append(" context");
            }

            source.Append(", ").Append(ActionType(terminal, hash, terminalHash)).Append(" action");
        }

        for (int index = 0; index < accessCount; index++)
        {
            source.Append(", ").Append(AccessType(index < shape.Arity ? shape.Pattern[index] : terminal.Pattern[index - shape.Arity]))
                .Append(" access").Append(index);
        }

        source.AppendLine(")");
        source.AppendLine("    {");
        source.AppendLine("        _predicate = predicate;");
        if (shape.HasContext)
        {
            source.AppendLine("        _predicateContext = predicateContext;");
        }

        if (terminal.IsCallback)
        {
            if (terminal.HasContext)
            {
                source.AppendLine("        _context = context;");
            }

            source.AppendLine("        _action = action;");
        }

        for (int index = 0; index < accessCount; index++)
        {
            source.Append("        _access").Append(index).Append(" = GeneratedForEachRuntime.Get")
                .Append(index < shape.Arity ? IsWrite(shape.Pattern[index]) ? "Write" : "Read" : IsWrite(terminal.Pattern[index - shape.Arity]) ? "Write" : "Read")
                .AppendLine("QueryComponentIndex(access" + index + ");");
        }

        source.AppendLine("    }");
        source.AppendLine();
        if (shape.IsFunctor)
        {
            source.Append("    internal ").Append(shape.FunctorType).AppendLine(" Predicate => _predicate;");
        }

        if (shape.HasContext)
        {
            source.Append("    internal ").Append(PredicateContextType(shape)).AppendLine(" PredicateContext => _predicateContext;");
        }

        if (terminal.IsFunctor)
        {
            source.Append("    internal ").Append(terminal.FunctorType).AppendLine(" Action => _action;");
            if (terminal.HasContext)
            {
                source.Append("    internal ").Append(terminal.ContextType).AppendLine(" Context => _context;");
            }
        }

        if (terminal.IsCallback)
        {
            source.AppendLine("    public void Invoke(ref GeneratedQuerySlots slots)");
        }
        else
        {
            source.AppendLine("    public void Execute(ref GeneratedQuerySlots slots, ref GeneratedWhereStructuralContext context)");
        }

        source.AppendLine("    {");
        RenderRowLocals(source, shape.Pattern, shape.Arity, shape.IsFunctor ? shape.Components : null, "T", "        ");
        if (terminal.IsCallback)
        {
            RenderRowLocals(source, terminal.Pattern, terminal.Arity, terminal.IsFunctor ? terminal.Components : null, "U", "        ", shape.Arity);
        }

        if (!terminal.IsCallback)
        {
            source.AppendLine("        if (slots.Count == 0)");
            source.AppendLine("        {");
            source.AppendLine("            return;");
            source.AppendLine("        }");
            source.AppendLine("        int runStart = 0;");
            source.AppendLine("        bool runSelected = false;");
        }

        source.AppendLine("        for (int index = 0; index < slots.Count; index++)");
        source.AppendLine("        {");
        RenderComponentLocals(source, shape.Pattern, shape.Arity, shape.IsFunctor ? shape.Components : null, "T", "            ");
        source.AppendLine("            Entity entity = slots.EntityAt(index);");
        if (terminal.IsCallback)
        {
            source.Append("            if (!");
            RenderPredicateInvocation(source, shape);
            source.AppendLine(")");
            source.AppendLine("            {");
            source.AppendLine("                continue;");
            source.AppendLine("            }");
        }
        else
        {
            source.Append("            bool selected = ");
            RenderPredicateInvocation(source, shape);
            source.AppendLine(";");
            source.AppendLine("            if (index != 0 && selected != runSelected)");
            source.AppendLine("            {");
            source.AppendLine("                context.ProcessRun(runStart, index - runStart, runSelected);");
            source.AppendLine("                runStart = index;");
            source.AppendLine("            }");
            source.AppendLine("            runSelected = selected;");
            source.AppendLine("            if (!selected)");
            source.AppendLine("            {");
            source.AppendLine("                continue;");
            source.AppendLine("            }");
        }
        if (terminal.IsCallback)
        {
            RenderComponentLocals(source, terminal.Pattern, terminal.Arity, terminal.IsFunctor ? terminal.Components : null, "U", "            ", shape.Arity);
            if (terminal.IsFunctor)
            {
                source.Append("            _action.Invoke(");
                if (terminal.HasContext)
                {
                    source.Append("ref _context");
                    if (terminal.HasEntity || terminal.Arity > 0)
                    {
                        source.Append(", ");
                    }
                }
            }
            else
            {
                source.Append("            _action(");
            }
            var arguments = new List<string>();
            if (terminal.HasEntity)
            {
                arguments.Add("entity");
            }

            for (int index = 0; index < terminal.Arity; index++)
            {
                arguments.Add(InvocationPrefix(terminal.Pattern[index]) + "component" + (shape.Arity + index));
            }

            source.Append(string.Join(", ", arguments)).AppendLine(");");
        }

        source.AppendLine("        }");
        if (!terminal.IsCallback)
        {
            source.AppendLine("        context.ProcessRun(runStart, slots.Count - runStart, runSelected);");
        }

        source.AppendLine("    }");
        source.AppendLine("}");
        source.AppendLine();
    }

    private static void RenderPredicateInvocation(StringBuilder source, PredicateShape shape)
    {
        source.Append(shape.IsFunctor ? "_predicate.Invoke(" : "_predicate(");
        bool hasArgument = false;
        if (shape.HasContext)
        {
            source.Append("ref _predicateContext");
            hasArgument = true;
        }

        if (shape.HasEntity)
        {
            if (hasArgument)
            {
                source.Append(", ");
            }

            source.Append("entity");
            hasArgument = true;
        }

        for (int index = 0; index < shape.Arity; index++)
        {
            if (hasArgument)
            {
                source.Append(", ");
            }

            source.Append(InvocationPrefix(shape.Pattern[index])).Append("component").Append(index);
            hasArgument = true;
        }

        source.Append(')');
    }

    private static void RenderRowLocals(
        StringBuilder source,
        string pattern,
        int arity,
        string[]? concreteTypes,
        string genericPrefix,
        string indent,
        int indexOffset = 0)
    {
        for (int index = 0; index < arity; index++)
        {
            int accessIndex = index + indexOffset;
            string componentType = concreteTypes is null ? genericPrefix + (index + 1).ToString(CultureInfo.InvariantCulture) : concreteTypes[index];
            source.Append(indent).Append("ref ")
                .Append(componentType).Append(" row").Append(accessIndex)
                .Append(" = ref slots.GetGenerated").Append(IsWrite(pattern[index]) ? "Write" : "Read")
                .Append("Reference<").Append(componentType).Append(">(_access").Append(accessIndex).AppendLine(");");
        }
    }

    private static void RenderComponentLocals(
        StringBuilder source,
        string pattern,
        int arity,
        string[]? concreteTypes,
        string genericPrefix,
        string indent,
        int indexOffset = 0)
    {
        for (int index = 0; index < arity; index++)
        {
            int accessIndex = index + indexOffset;
            string componentType = concreteTypes is null ? genericPrefix + (index + 1).ToString(CultureInfo.InvariantCulture) : concreteTypes[index];
            source.Append(indent).Append("ref ")
                .Append(componentType).Append(" component").Append(accessIndex)
                .Append(" = ref global::System.Runtime.CompilerServices.Unsafe.Add(")
                .Append("ref row")
                .Append(accessIndex)
                .Append(", index);")
                .AppendLine();
        }
    }

    private static string PredicateType(PredicateShape shape, string hash)
        => shape.IsFunctor
            ? shape.FunctorType!
            : "GeneratedWherePredicate_" + hash + PredicateGenericTypes(shape);

    private static string ActionType(TerminalShape terminal, string predicateHash, string terminalHash)
        => terminal.IsFunctor
            ? terminal.FunctorType!
            : "GeneratedWhereAction_" + predicateHash + '_' + terminalHash + GenericTypes(terminal.Arity, "U");

    private static void RenderView(StringBuilder source, PredicateShape shape, string hash)
    {
        string typeName = "GeneratedWhereQuery_" + hash;
        source.Append(shape.IsFunctor ? "internal ref struct " : shape.HasContext ? "public ref struct " : "public readonly ref struct ")
            .Append(typeName).Append(PredicateGenericTypes(shape)).AppendLine();
        source.AppendLine("{");
        source.AppendLine("    private readonly World _world;");
        source.AppendLine("    private readonly Query _query;");
        if (shape.HasContext)
        {
            source.Append("    private Span<").Append(PredicateContextType(shape)).AppendLine("> _predicateContext;");
        }

        if (shape.IsFunctor)
        {
            source.Append("    private Span<").Append(shape.FunctorType).AppendLine("> _predicate;");
        }
        else
        {
            source.Append("    private readonly GeneratedWherePredicate_").Append(hash).Append(PredicateGenericTypes(shape)).AppendLine(" _predicate;");
        }

        source.Append("    internal ").Append(typeName).Append('(').Append("World world, in Query query, ");
        if (shape.HasContext)
        {
            source.Append("ref ").Append(PredicateContextType(shape)).Append(" context, ");
        }

        if (shape.IsFunctor)
        {
            source.Append("ref ").Append(shape.FunctorType).AppendLine(" predicate)");
        }
        else
        {
            source.Append("GeneratedWherePredicate_").Append(hash).Append(PredicateGenericTypes(shape)).AppendLine(" predicate)");
        }
        source.AppendLine("    {");
        source.AppendLine("        _world = world;");
        source.AppendLine("        _query = query;");
        if (shape.HasContext)
        {
            source.Append("        _predicateContext = global::System.Runtime.InteropServices.MemoryMarshal.CreateSpan(ref context, 1);").AppendLine();
        }

        if (shape.IsFunctor)
        {
            source.Append("        _predicate = global::System.Runtime.InteropServices.MemoryMarshal.CreateSpan(ref predicate, 1);").AppendLine();
        }
        else
        {
            source.AppendLine("        _predicate = predicate;");
        }
        source.AppendLine("    }");
        source.AppendLine();
        source.AppendLine("    internal World World => _world;");
        source.AppendLine("    internal Query Query => _query;");

        foreach (TerminalShape terminal in shape.Terminals.Values.OrderBy(static value => value.SignatureKey, StringComparer.Ordinal))
        {
            RenderViewTerminal(source, shape, terminal, hash);
        }

        source.AppendLine("}");
        source.AppendLine();
    }

    private static void RenderViewTerminal(StringBuilder source, PredicateShape shape, TerminalShape terminal, string hash)
    {
        string terminalHash = StableName(terminal.SignatureKey);
        string invokerName = "GeneratedWhereInvoker_" + hash + '_' + terminalHash;
        string generic = terminal.Kind is TerminalKind.Add or TerminalKind.Remove || (terminal.IsCallback && !terminal.IsFunctor)
            ? GenericList(terminal.Arity, "U")
            : string.Empty;
        string genericParameters = GenericParameters(generic);
        string actionType = terminal.IsCallback ? ActionType(terminal, hash, terminalHash) : string.Empty;
        string signature = terminal.Kind switch
        {
            TerminalKind.Destroy => "public int Destroy()",
            TerminalKind.Add => "public int Add" + genericParameters + "()",
            TerminalKind.Remove => "public int Remove" + genericParameters + "()",
            TerminalKind.ForEach => terminal.IsFunctor
                ? "internal void ForEach" + (terminal.HasContext ? "(" + "ref " + terminal.ContextType + " context, ref " + actionType + " action)" : "(ref " + actionType + " action)")
                : "public void ForEach" + genericParameters + "(" + actionType + " action)",
            TerminalKind.ForEachEntity => terminal.IsFunctor
                ? "internal void ForEachEntity" + (terminal.HasContext ? "(" + "ref " + terminal.ContextType + " context, ref " + actionType + " action)" : "(ref " + actionType + " action)")
                : "public void ForEachEntity" + genericParameters + "(" + actionType + " action)",
            _ => string.Empty
        };
        source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        source.Append("    ").AppendLine(signature);
        source.AppendLine("    {");
        if (terminal.IsCallback && !terminal.IsFunctor)
        {
            source.AppendLine("        GeneratedForEachRuntime.ThrowIfNull(action, nameof(action));");
        }

        source.AppendLine("        GeneratedForEachRuntime.ValidateGeneratedWhere(_world, in _query);");
        int accessCount = shape.Arity + (terminal.IsCallback ? terminal.Arity : 0);
        for (int index = 0; index < accessCount; index++)
        {
            string componentType = index < shape.Arity
                ? shape.IsFunctor ? shape.Components[index] : "T" + (index + 1)
                : terminal.IsFunctor ? terminal.Components[index - shape.Arity] : "U" + (index - shape.Arity + 1);
            string pattern = index < shape.Arity ? shape.Pattern : terminal.Pattern;
            int patternIndex = index < shape.Arity ? index : index - shape.Arity;
            source.Append("        var access").Append(index).Append(" = GeneratedForEachRuntime.GetPrepared")
                .Append(IsWrite(pattern[patternIndex]) ? "Write" : "Read")
                .Append("Access<").Append(componentType).AppendLine(">(in _query);");
        }

        string invokerGeneric = GenericParameters(
            JoinGeneric(
                shape.IsFunctor ? string.Empty : PredicateGenericList(shape),
                terminal.IsCallback && !terminal.IsFunctor ? GenericList(terminal.Arity, "U") : string.Empty));
        source.Append("        var invoker = new ").Append(invokerName).Append(invokerGeneric)
            .Append(shape.IsFunctor ? "(_predicate[0]" : "(_predicate");
        if (shape.HasContext)
        {
            source.Append(", _predicateContext[0]");
        }

        if (terminal.IsCallback)
        {
            if (terminal.HasContext)
            {
                source.Append(", context");
            }

            source.Append(", action");
        }

        for (int index = 0; index < accessCount; index++)
        {
            source.Append(", access").Append(index);
        }

        source.AppendLine(");");
        string writes = WriteIndices(shape.Pattern, terminal.Pattern, shape.Arity);
        bool returnsCount = terminal.Kind is TerminalKind.Destroy or TerminalKind.Add or TerminalKind.Remove;
        if (returnsCount)
        {
            source.AppendLine("        int __whereResult;");
        }

        if (terminal.Kind is TerminalKind.Add or TerminalKind.Remove)
        {
            source.Append("        Span<ComponentId> components = stackalloc ComponentId[").Append(terminal.Arity).AppendLine("];");
            for (int index = 0; index < terminal.Arity; index++)
            {
                source.Append("        components[").Append(index).Append("] = _world.Layouts.GetPrimary<U").Append(index + 1).AppendLine(">();");
            }
        }

        switch (terminal.Kind)
        {
            case TerminalKind.Destroy:
                source.Append("        __whereResult = GeneratedForEachRuntime.ExecuteGeneratedWhereDestroy(_world, in _query, ref invoker, ").Append(writes).AppendLine(");");
                break;
            case TerminalKind.Add:
                source.Append("        __whereResult = GeneratedForEachRuntime.ExecuteGeneratedWhereAdd(_world, in _query, ref invoker, ").Append(writes).AppendLine(", components);");
                break;
            case TerminalKind.Remove:
                source.Append("        __whereResult = GeneratedForEachRuntime.ExecuteGeneratedWhereRemove(_world, in _query, ref invoker, ").Append(writes).AppendLine(", components);");
                break;
            default:
                source.Append("        GeneratedForEachRuntime.ExecuteGeneratedWhereForEach(_world, in _query, ref invoker, ").Append(writes).AppendLine(");");
                break;
        }

        if (shape.IsFunctor)
        {
            source.AppendLine("        _predicate[0] = invoker.Predicate;");
        }

        if (shape.HasContext)
        {
            source.AppendLine("        _predicateContext[0] = invoker.PredicateContext;");
        }

        if (terminal.IsFunctor && terminal.IsCallback)
        {
            if (terminal.HasContext)
            {
                source.AppendLine("        context = invoker.Context;");
            }

            source.AppendLine("        action = invoker.Action;");
        }

        if (returnsCount)
        {
            source.AppendLine("        return __whereResult;");
        }

        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void RenderExtension(StringBuilder source, PredicateShape shape, string hash)
    {
        string typeName = "GeneratedWhereQuery_" + hash;
        source.Append(shape.IsFunctor ? "internal static class GeneratedWhereExtensions_" : "public static class GeneratedWhereExtensions_")
            .Append(hash).AppendLine();
        source.AppendLine("{");
        source.AppendLine("    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        source.Append("    ").Append(shape.IsFunctor ? "internal static " : "public static ").Append(typeName).Append(PredicateGenericTypes(shape))
            .Append(shape.HasEntity ? " WhereEntity" : " Where").Append(PredicateGenericParameters(shape))
            .Append("(this World world, in Query query, ");
        if (shape.HasContext)
        {
            source.Append("ref ").Append(PredicateContextType(shape)).Append(" context, ");
        }

        if (shape.IsFunctor)
        {
            source.Append("ref ").Append(shape.FunctorType).AppendLine(" predicate)");
        }
        else
        {
            source.Append("GeneratedWherePredicate_").Append(hash).Append(PredicateGenericTypes(shape)).AppendLine(" predicate)");
        }
        source.AppendLine("    {");
        source.AppendLine("        GeneratedForEachRuntime.ThrowIfNull(world, nameof(world));");
        if (!shape.IsFunctor)
        {
            source.AppendLine("        GeneratedForEachRuntime.ThrowIfNull(predicate, nameof(predicate));");
        }

        source.Append("        return new ").Append(typeName).Append(PredicateGenericTypes(shape)).Append("(world, in query, ");
        if (shape.HasContext)
        {
            source.Append("ref context, ");
        }

        if (shape.IsFunctor)
        {
            source.AppendLine("ref predicate);");
        }
        else
        {
            source.AppendLine("predicate);");
        }
        source.AppendLine("    }");
        source.AppendLine("}");
    }

    private static string WriteIndices(string predicatePattern, string terminalPattern, int predicateArity)
    {
        var values = new List<string>();
        for (int index = 0; index < predicatePattern.Length; index++)
        {
            if (IsWrite(predicatePattern[index]))
            {
                values.Add("GeneratedForEachRuntime.GetWriteQueryComponentIndex(access" + index + ")");
            }
        }

        for (int index = 0; index < terminalPattern.Length; index++)
        {
            if (IsWrite(terminalPattern[index]))
            {
                values.Add("GeneratedForEachRuntime.GetWriteQueryComponentIndex(access" + (predicateArity + index) + ")");
            }
        }

        if (values.Count == 0)
        {
            return "global::System.ReadOnlySpan<int>.Empty";
        }

        return "stackalloc int[] { " + string.Join(", ", values) + " }";
    }

    private static string AccessType(char mode) => IsWrite(mode) ? "WriteAccess" : "ReadAccess";

    private static bool IsWrite(char mode) => mode == 'W';

    private static string ParameterPrefix(char mode)
        => mode switch
        {
            'R' => "ref readonly ",
            'W' => "ref ",
            'I' => "in ",
            _ => string.Empty
        };

    private static string InvocationPrefix(char mode)
        => mode is 'R' or 'I' ? "in " : mode == 'W' ? "ref " : string.Empty;

    private static string GenericList(int arity, string prefix = "T")
    {
        if (arity == 0)
        {
            return string.Empty;
        }

        var values = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            values[index] = prefix + (index + 1).ToString(CultureInfo.InvariantCulture);
        }

        return string.Join(", ", values);
    }

    private static string GenericTypes(int arity, string prefix = "T")
        => GenericParameters(GenericList(arity, prefix));

    private static string PredicateGenericList(PredicateShape shape)
        => shape.IsFunctor
            ? string.Empty
            : JoinGeneric(shape.HasContext ? "C" : string.Empty, GenericList(shape.Arity));

    private static string PredicateGenericParameters(PredicateShape shape)
        => GenericParameters(PredicateGenericList(shape));

    private static string PredicateGenericTypes(PredicateShape shape)
        => PredicateGenericParameters(shape);

    private static string PredicateContextType(PredicateShape shape)
        => shape.IsFunctor ? shape.ContextType! : "C";

    private static string TypeArguments(string[] types)
        => types.Length == 0 ? string.Empty : "<" + string.Join(", ", types) + ">";

    private static string GenericParameters(int arity) => GenericTypes(arity);

    private static string GenericParameters(string generic)
        => string.IsNullOrEmpty(generic) ? string.Empty : "<" + generic + ">";

    private static string JoinGeneric(string first, string second)
        => string.IsNullOrEmpty(first) ? second : string.IsNullOrEmpty(second) ? first : first + ", " + second;

    private static string StableName(string value)
    {
        unchecked
        {
            uint hash = 2166136261;
            foreach (char character in value)
            {
                hash = (hash ^ character) * 16777619;
            }

            return hash.ToString("X8", CultureInfo.InvariantCulture);
        }
    }

    private sealed class PredicateShape
    {
        internal PredicateShape(
            string pattern,
            bool isFunctor,
            string? functorType,
            bool hasEntity,
            bool hasContext,
            string? contextType,
            string[]? components)
        {
            Pattern = pattern;
            IsFunctor = isFunctor;
            FunctorType = functorType;
            HasEntity = hasEntity;
            HasContext = hasContext;
            ContextType = contextType;
            Components = components ?? Array.Empty<string>();
        }

        internal string Pattern { get; }
        internal int Arity => Pattern.Length;
        internal bool IsFunctor { get; }
        internal string? FunctorType { get; }
        internal bool HasEntity { get; }
        internal bool HasContext { get; }
        internal string? ContextType { get; }
        internal string[] Components { get; }
        internal Dictionary<string, TerminalShape> Terminals { get; } = new(StringComparer.Ordinal);
        internal string Key => IsFunctor
            ? "Where|Functor|" + HasEntity + "|" + FunctorType + "|" + ContextType + "|" + Pattern + "|" + string.Join(";", Components)
            : "Where|" + HasEntity + "|" + ContextType + "|" + Pattern;
    }

    private sealed class TerminalShape
    {
        internal TerminalShape(
            TerminalKind kind,
            string pattern,
            int arity,
            bool hasEntity,
            bool isFunctor = false,
            string? functorType = null,
            bool hasContext = false,
            string? contextType = null,
            string[]? components = null)
        {
            Kind = kind;
            Pattern = pattern;
            Arity = arity;
            HasEntity = hasEntity;
            IsFunctor = isFunctor;
            FunctorType = functorType;
            HasContext = hasContext;
            ContextType = contextType;
            Components = components ?? Array.Empty<string>();
        }

        internal TerminalKind Kind { get; }
        internal string Pattern { get; }
        internal int Arity { get; }
        internal bool HasEntity { get; }
        internal bool IsFunctor { get; }
        internal string? FunctorType { get; }
        internal bool HasContext { get; }
        internal string? ContextType { get; }
        internal string[] Components { get; }
        internal bool IsCallback => Kind is TerminalKind.ForEach or TerminalKind.ForEachEntity;
        internal string SignatureKey => Kind
            + "|" + Pattern
            + "|" + Arity.ToString(CultureInfo.InvariantCulture)
            + "|" + HasEntity
            + "|" + IsFunctor
            + "|" + FunctorType
            + "|" + ContextType;
        internal string Key => SignatureKey
            + "|" + string.Join(";", Components);
    }

