        string typeName = filtered ? "FilteredEntitySequence" : "EntitySequence";
        source.Append("public readonly ref partial struct ").AppendLine(typeName);
        source.AppendLine("{");
        for (int arity = 1; arity <= 4; arity++)
        {
            int patternCount = 1 << arity;
            for (int bits = 0; bits < patternCount; bits++)
            {
                string pattern = AccessPattern(arity, bits);
                string suffix = PatternSuffix(pattern);
                string generic = GenericTypes(arity);
                string components = ComponentParameters(arity);
                string componentNames = ComponentNames(arity);
                string worldPrefix = filtered ? "_world.ForEach(_entities, in _query, " : "_world.ForEach(_entities, ";
                string functorWorldPrefix = filtered
                    ? $"_world.ForEach<TFunctor, {generic}>(_entities, in _query, "
                    : $"_world.ForEach<TFunctor, {generic}>(_entities, ";
                string contextFunctorWorldPrefix = filtered
                    ? $"_world.ForEach<TContext, TFunctor, {generic}>(_entities, in _query, "
                    : $"_world.ForEach<TContext, TFunctor, {generic}>(_entities, ";
                string tag = IsAllWrite(pattern) ? string.Empty : $", ForEachAccessTag_{pattern} access";
                string tagArgument = IsAllWrite(pattern) ? string.Empty : ", access";

                AppendInline(source, $"public void ForEach<{generic}>({components}, ForEachAction{suffix}<{generic}> action{tag})", $"{worldPrefix}{componentNames}, action{tagArgument});");
                AppendInline(source, $"public void ForEach<{generic}>({components}, ForEachEntityAction{suffix}<{generic}> action{tag})", $"{worldPrefix}{componentNames}, action{tagArgument});");
                AppendInline(source, $"public void ForEach<TContext, {generic}>(ref TContext context, {components}, ForEachContextAction{suffix}<TContext, {generic}> action{tag})", $"{worldPrefix}ref context, {componentNames}, action{tagArgument});");
                AppendInline(source, $"public void ForEach<TContext, {generic}>(ref TContext context, {components}, ForEachContextEntityAction{suffix}<TContext, {generic}> action{tag})", $"{worldPrefix}ref context, {componentNames}, action{tagArgument});");
                AppendInline(source, $"public void ForEach<TFunctor, {generic}>({components}, ref TFunctor functor{tag})", $"{functorWorldPrefix}{componentNames}, ref functor{tagArgument});", $"where TFunctor : struct, IForEach{suffix}<{generic}>");
                AppendInline(source, $"public void ForEach<TFunctor, {generic}>({components}, ref TFunctor functor, ForEachEntityTag entity{tag})", $"{functorWorldPrefix}{componentNames}, ref functor, entity{tagArgument});", $"where TFunctor : struct, IForEachEntity{suffix}<{generic}>");
                AppendInline(source, $"public void ForEach<TContext, TFunctor, {generic}>(ref TContext context, {components}, ref TFunctor functor{tag})", $"{contextFunctorWorldPrefix}ref context, {componentNames}, ref functor{tagArgument});", $"where TFunctor : struct, IForEachContext{suffix}<TContext, {generic}>");
                AppendInline(source, $"public void ForEach<TContext, TFunctor, {generic}>(ref TContext context, {components}, ref TFunctor functor, ForEachEntityTag entity{tag})", $"{contextFunctorWorldPrefix}ref context, {componentNames}, ref functor, entity{tagArgument});", $"where TFunctor : struct, IForEachContextEntity{suffix}<TContext, {generic}>");
            }
        }

        source.AppendLine("}");
    }

    private static void Append(StringBuilder source, string signature, string body, string? constraint = null)
    {
        source.Append("    ").AppendLine(signature);
        if (constraint is not null)
        {
            source.Append("        ").AppendLine(constraint);
        }
        source.AppendLine("    {");
        source.Append("        ").AppendLine(body);
        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void AppendInline(StringBuilder source, string signature, string body, string? constraint = null)
    {
        source.AppendLine("    [System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        Append(source, signature, body, constraint);
    }

    private static string AccessPattern(int arity, int bits)
    {
        var result = new char[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = (bits & (1 << index)) == 0 ? 'R' : 'W';
        }

        return new string(result);
    }

    private static bool IsAllWrite(string pattern)
    {
        for (int index = 0; index < pattern.Length; index++)
        {
            if (pattern[index] != 'W')
            {
                return false;
            }
        }

        return true;
    }

    private static string PatternSuffix(string pattern) => IsAllWrite(pattern) ? string.Empty : "_" + pattern;

    private static string GenericTypes(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "T" + (index + 1);
        }

        return string.Join(", ", result);
    }

    private static string ComponentParameters(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "ComponentId component" + (index + 1);
        }

        return string.Join(", ", result);
    }

    private static string ComponentNames(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "component" + (index + 1);
        }

        return string.Join(", ", result);
    }

    private static string RefParameters(string pattern)
    {
        var result = new string[pattern.Length];
        for (int index = 0; index < pattern.Length; index++)
        {
            result[index] = (pattern[index] == 'R' ? "in " : "ref ") + "T" + (index + 1) + " component" + (index + 1);
        }

        return string.Join(", ", result);
    }

    private static string AccessParameters(string pattern)
    {
        var result = new string[pattern.Length];
        for (int index = 0; index < pattern.Length; index++)
        {
            result[index] = (pattern[index] == 'R' ? "ReadAccess" : "WriteAccess") + " component" + (index + 1);
        }

        return string.Join(", ", result);
    }

    private static string AssignAccessFields(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "_component" + (index + 1) + " = component" + (index + 1) + ";";
        }

        return string.Join(" ", result);
    }

    private static string AccessArguments(string pattern)
    {
        var result = new string[pattern.Length];
        for (int index = 0; index < pattern.Length; index++)
        {
            result[index] = "ForEachRuntime.Access" + (pattern[index] == 'R' ? "Read" : "Write") + "<T" + (index + 1) + ">(this, in query, component" + (index + 1) + ")";
        }

        return string.Join(", ", result);
    }

    private static string AccessArgumentsFromSpan(string pattern)
    {
        var result = new string[pattern.Length];
        for (int index = 0; index < pattern.Length; index++)
        {
            result[index] = "ForEachRuntime.Access" + (pattern[index] == 'R' ? "Read" : "Write") + "<T" + (index + 1) + ">(this, in query, componentIds[" + index + "])";
        }

        return string.Join(", ", result);
    }

    private static string SequenceAccessArguments(string pattern, bool explicitIds)
        => explicitIds ? AccessArguments(pattern) : AccessArgumentsFromSpan(pattern);

    private static string SequenceSetup(string pattern, bool filtered, bool explicitIds)
    {
        if (filtered)
        {
            return explicitIds ? string.Empty : ComponentSetup(pattern.Length);
        }

        var assignments = new string[pattern.Length];
        for (int index = 0; index < pattern.Length; index++)
        {
            assignments[index] = $"componentIds[{index}] = component{index + 1};";
        }

        return $"Span<ComponentId> componentIds = stackalloc ComponentId[{pattern.Length}]; {string.Join(" ", assignments)} Query query = CreateSequenceQuery(componentIds); ";
    }

    private static string ComponentSetup(int arity) => $"Span<ComponentId> componentIds = stackalloc ComponentId[{arity}]; ForEachRuntime.ResolveComponentIds(in query, componentIds); ";

    private static string ValueStatements(string pattern)
    {
        var result = new string[pattern.Length];
        for (int index = 0; index < pattern.Length; index++)
        {
            result[index] = (pattern[index] == 'R' ? "in " : "ref ") + "value" + (index + 1) + ".Ref<T" + (index + 1) + ">(cursor)";
        }

        return string.Join(", ", result);
    }

    private static string ConstructorName(string name)
    {
        int genericStart = name.IndexOf('<');
        return genericStart < 0 ? name : name.Substring(0, genericStart);
    }

    private static string Bool(bool value) => value ? "true" : "false";

    private static string SequenceInvocation(string invocation) => invocation
        .Replace("cursor.Entities[cursor.CurrentIndex]", "cursor.Entity")
        .Replace("(cursor)", "(cursor.Slot)");
}
