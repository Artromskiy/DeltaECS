        source.AppendLine("    public void Invoke(ref QueryChunkCursor cursor) { while (cursor.MoveNext()) Functor.Invoke(ref Context, cursor.Entities[cursor.CurrentIndex]); }");
        source.AppendLine("}");
        source.AppendLine();
    }

    private static void RenderState(StringBuilder source, string name, string constructorParameters, string constructorBody, string invocation, string? actionType = null, string? stateTypes = null, string? interfaceType = null)
    {
        source.Append("internal struct ").Append(name).Append(" : IForEachInvoker");
        if (interfaceType is not null)
        {
            source.Append(" where TFunctor : struct, ").Append(interfaceType);
        }

        source.AppendLine();
        source.AppendLine("{");
        if (stateTypes is not null)
        {
            if (stateTypes.Contains("TContext", StringComparison.Ordinal))
            {
                source.AppendLine("    internal TContext Context;");
            }

            if (stateTypes.Contains("TFunctor", StringComparison.Ordinal))
            {
                source.AppendLine("    internal TFunctor Functor;");
            }
        }

        if (actionType is not null)
        {
            source.Append("    private readonly ").Append(actionType).AppendLine(" _action;");
        }
        var count = constructorParameters.Split(new[] { "WriteAccess" }, StringSplitOptions.None).Length - 1;
        for (int index = 1; index <= count; index++)
        {
            source.Append("    private readonly WriteAccess _component").Append(index).AppendLine(";");
        }

        source.Append("    internal ").Append(ConstructorName(name)).Append('(').Append(constructorParameters).Append(") { ").Append(constructorBody).AppendLine(" }");
        source.AppendLine("    public void Invoke(ref QueryChunkCursor cursor)");
        source.AppendLine("    {");
        for (int index = 1; index <= count; index++)
        {
            source.Append("        var value").Append(index).Append(" = cursor.GetWrite(_component").Append(index).AppendLine(");");
        }

        source.AppendLine("        while (cursor.MoveNext())");
        source.AppendLine("        {");
        source.Append("            ").AppendLine(invocation);
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine("}");
        source.AppendLine();
    }

    private static void RenderWorld(StringBuilder source)
    {
        source.AppendLine("public sealed partial class World");
        source.AppendLine("{");
        Append(source, "public void ForEach(in Query query, ForEachAction action)", "ArgumentNullException.ThrowIfNull(action); var state = new ForEachDelegateState(action); ForEachRuntime.Execute(this, in query, ref state);");
        Append(source, "public void ForEach<TContext>(in Query query, ref TContext context, ForEachContextAction<TContext> action)", "ArgumentNullException.ThrowIfNull(action); var state = new ForEachContextDelegateState<TContext>(context, action); ForEachRuntime.Execute(this, in query, ref state); context = state.Context;");
        Append(source, "public void ForEach(in Query query, ForEachEntityAction action)", "ArgumentNullException.ThrowIfNull(action); var state = new ForEachEntityDelegateState(action); ForEachRuntime.Execute(this, in query, ref state);");
        Append(source, "public void ForEach<TContext>(in Query query, ref TContext context, ForEachContextEntityAction<TContext> action)", "ArgumentNullException.ThrowIfNull(action); var state = new ForEachContextEntityDelegateState<TContext>(context, action); ForEachRuntime.Execute(this, in query, ref state); context = state.Context;");
        Append(source, "public void ForEach<TFunctor>(in Query query, ref TFunctor functor, ForEachEntityTag entity)", "var state = new ForEachEntityFunctorState<TFunctor>(functor); ForEachRuntime.Execute(this, in query, ref state); functor = state.Functor;", "where TFunctor : struct, IForEachEntity");
        Append(source, "public void ForEach<TContext, TFunctor>(in Query query, ref TContext context, ref TFunctor functor, ForEachEntityTag entity)", "var state = new ForEachContextEntityFunctorState<TContext, TFunctor>(context, functor); ForEachRuntime.Execute(this, in query, ref state); context = state.Context; functor = state.Functor;", "where TFunctor : struct, IForEachContextEntity<TContext>");
        Append(source, "public void ForEach<TFunctor>(in Query query, ref TFunctor functor)", "var state = new ForEachFunctorState<TFunctor>(functor); ForEachRuntime.Execute(this, in query, ref state); functor = state.Functor;", "where TFunctor : struct, IForEach");
        Append(source, "public void ForEach<TContext, TFunctor>(in Query query, ref TContext context, ref TFunctor functor)", "var state = new ForEachContextFunctorState<TContext, TFunctor>(context, functor); ForEachRuntime.Execute(this, in query, ref state); context = state.Context; functor = state.Functor;", "where TFunctor : struct, IForEachContext<TContext>");
        for (int arity = 1; arity <= 4; arity++)
        {
            RenderDelegateOverloads(source, arity, true);
            RenderDelegateOverloads(source, arity, false);
            RenderFunctorOverloads(source, arity, true);
            RenderFunctorOverloads(source, arity, false);
        }

        source.AppendLine("}");
    }

    private static void RenderDelegateOverloads(StringBuilder source, int arity, bool explicitIds)
    {
        var generic = GenericTypes(arity);
        var parameters = explicitIds ? ComponentParameters(arity) : string.Empty;
        var suffix = explicitIds ? ", " + parameters : string.Empty;
        var setup = explicitIds ? string.Empty : ComponentSetup(arity);
        var accesses = explicitIds ? AccessArguments(arity) : AccessArgumentsFromSpan(arity);
        Append(source, $"public void ForEach<{generic}>(in Query query{suffix}, ForEachAction<{generic}> action)", setup + $"ArgumentNullException.ThrowIfNull(action); var state = new ForEachDelegateState<{generic}>(action, {accesses}); ForEachRuntime.Execute(this, in query, ref state);");
        Append(source, $"public void ForEach<{generic}>(in Query query{suffix}, ForEachEntityAction<{generic}> action)", setup + $"ArgumentNullException.ThrowIfNull(action); var state = new ForEachEntityDelegateState<{generic}>(action, {accesses}); ForEachRuntime.Execute(this, in query, ref state);");
        Append(source, $"public void ForEach<TContext, {generic}>(in Query query, ref TContext context{suffix}, ForEachContextAction<TContext, {generic}> action)", setup + $"ArgumentNullException.ThrowIfNull(action); var state = new ForEachContextDelegateState<TContext, {generic}>(context, action, {accesses}); ForEachRuntime.Execute(this, in query, ref state); context = state.Context;");
        Append(source, $"public void ForEach<TContext, {generic}>(in Query query, ref TContext context{suffix}, ForEachContextEntityAction<TContext, {generic}> action)", setup + $"ArgumentNullException.ThrowIfNull(action); var state = new ForEachContextEntityDelegateState<TContext, {generic}>(context, action, {accesses}); ForEachRuntime.Execute(this, in query, ref state); context = state.Context;");
    }

    private static void RenderFunctorOverloads(StringBuilder source, int arity, bool explicitIds)
    {
        var generic = GenericTypes(arity);
        var parameters = explicitIds ? ComponentParameters(arity) : string.Empty;
        var suffix = explicitIds ? ", " + parameters : string.Empty;
        var setup = explicitIds ? string.Empty : ComponentSetup(arity);
        var accesses = explicitIds ? AccessArguments(arity) : AccessArgumentsFromSpan(arity);
        Append(source, $"public void ForEach<TFunctor, {generic}>(in Query query{suffix}, ref TFunctor functor)", setup + $"var state = new ForEachFunctorState<TFunctor, {generic}>(functor, {accesses}); ForEachRuntime.Execute(this, in query, ref state); functor = state.Functor;", $"where TFunctor : struct, IForEach<{generic}>");
        Append(source, $"public void ForEach<TFunctor, {generic}>(in Query query{suffix}, ref TFunctor functor, ForEachEntityTag entity)", setup + $"var state = new ForEachEntityFunctorState<TFunctor, {generic}>(functor, {accesses}); ForEachRuntime.Execute(this, in query, ref state); functor = state.Functor;", $"where TFunctor : struct, IForEachEntity<{generic}>");
        Append(source, $"public void ForEach<TContext, TFunctor, {generic}>(in Query query, ref TContext context{suffix}, ref TFunctor functor)", setup + $"var state = new ForEachContextFunctorState<TContext, TFunctor, {generic}>(context, functor, {accesses}); ForEachRuntime.Execute(this, in query, ref state); context = state.Context; functor = state.Functor;", $"where TFunctor : struct, IForEachContext<TContext, {generic}>");
        Append(source, $"public void ForEach<TContext, TFunctor, {generic}>(in Query query, ref TContext context{suffix}, ref TFunctor functor, ForEachEntityTag entity)", setup + $"var state = new ForEachContextEntityFunctorState<TContext, TFunctor, {generic}>(context, functor, {accesses}); ForEachRuntime.Execute(this, in query, ref state); context = state.Context; functor = state.Functor;", $"where TFunctor : struct, IForEachContextEntity<TContext, {generic}>");
