    private static void RenderState(StringBuilder source, string name, string pattern, string constructorParameters, string constructorBody, string invocation, string? actionType = null, string? stateTypes = null, string? interfaceType = null)
    {
        source.Append("internal struct ").Append(name).Append(" : IForEachInvoker, ISequenceInvoker");
        if (interfaceType is not null)
        {
            source.Append(" where TFunctor : struct, ").Append(interfaceType);
        }

        source.AppendLine();
        source.AppendLine("{");
        if (stateTypes is not null)
        {
            if (stateTypes.Contains("TContext", StringComparison.Ordinal))
            {
                source.AppendLine("    internal TContext Context;");
            }

            if (stateTypes.Contains("TFunctor", StringComparison.Ordinal))
            {
                source.AppendLine("    internal TFunctor Functor;");
            }
        }

        if (actionType is not null)
        {
            source.Append("    private readonly ").Append(actionType).AppendLine(" _action;");
        }
        for (int index = 0; index < pattern.Length; index++)
        {
            source.Append("    private readonly ").Append(pattern[index] == 'R' ? "ReadAccess" : "WriteAccess")
                .Append(" _component").Append(index + 1).AppendLine(";");
        }

        source.Append("    internal ").Append(ConstructorName(name)).Append('(').Append(constructorParameters).Append(") { ").Append(constructorBody).AppendLine(" }");
        source.AppendLine("    public void Invoke(ref QueryChunkCursor cursor)");
        source.AppendLine("    {");
        for (int index = 0; index < pattern.Length; index++)
        {
            source.Append("        var value").Append(index + 1).Append(" = cursor.")
                .Append(pattern[index] == 'R' ? "GetRead" : "GetWrite")
                .Append("(_component").Append(index + 1).AppendLine(");");
        }

        source.AppendLine("        while (cursor.MoveNext())");
        source.AppendLine("        {");
        source.Append("            ").AppendLine(invocation);
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine("    public void Invoke(ref SequenceElementCursor cursor)");
        source.AppendLine("    {");
        for (int index = 0; index < pattern.Length; index++)
        {
            source.Append("        var value").Append(index + 1).Append(" = cursor.Get(_component")
                .Append(index + 1).AppendLine(");");
        }

        source.Append("        ").AppendLine(SequenceInvocation(invocation));
        source.AppendLine("    }");
        source.AppendLine("}");
        source.AppendLine();
    }

