using System;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Delta.ECS.Generators;

[Generator]
public sealed class ForEachGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output =>
            output.AddSource("ForEach.g.cs", SourceText.From(Render(), Encoding.UTF8)));
    }

    private static string Render()
    {
        var source = new StringBuilder(128 * 1024);
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine("using System;");
        source.AppendLine("namespace Delta.ECS;");
        source.AppendLine();
        RenderContracts(source);
        RenderStates(source);
        RenderWorld(source);
        return source.ToString();
    }

    private static void RenderContracts(StringBuilder source)
    {
        source.AppendLine("public readonly struct ForEachEntityTag");
        source.AppendLine("{");
        source.AppendLine("    public static ForEachEntityTag Instance => default;");
        source.AppendLine("}");
        source.AppendLine("public delegate void ForEachEntityAction(Entity entity);");
        source.AppendLine("public delegate void ForEachAction();");
        source.AppendLine("public delegate void ForEachContextAction<TContext>(ref TContext context);");
        source.AppendLine("public delegate void ForEachContextEntityAction<TContext>(ref TContext context, Entity entity);");
        source.AppendLine("public interface IForEachEntity { void Invoke(Entity entity); }");
        source.AppendLine("public interface IForEach { void Invoke(); }");
        source.AppendLine("public interface IForEachContext<TContext> { void Invoke(ref TContext context); }");
        source.AppendLine("public interface IForEachContextEntity<TContext> { void Invoke(ref TContext context, Entity entity); }");
        source.AppendLine();

        for (int arity = 1; arity <= 4; arity++)
        {
            var generic = GenericTypes(arity);
            var refs = RefParameters(arity);
            source.Append("public delegate void ForEachAction<").Append(generic).Append(">(")
                .Append(refs).AppendLine(");");
            source.Append("public delegate void ForEachEntityAction<").Append(generic).Append(">(Entity entity, ")
                .Append(refs).AppendLine(");");
            source.Append("public delegate void ForEachContextAction<TContext, ").Append(generic).Append(">(ref TContext context, ")
                .Append(refs).AppendLine(");");
            source.Append("public delegate void ForEachContextEntityAction<TContext, ").Append(generic).Append(">(ref TContext context, Entity entity, ")
                .Append(refs).AppendLine(");");
            source.Append("public interface IForEach<").Append(generic).Append("> { void Invoke(")
                .Append(refs).AppendLine("); }");
            source.Append("public interface IForEachEntity<").Append(generic).Append("> { void Invoke(Entity entity, ")
                .Append(refs).AppendLine("); }");
            source.Append("public interface IForEachContext<TContext, ").Append(generic).Append("> { void Invoke(ref TContext context, ")
                .Append(refs).AppendLine("); }");
            source.Append("public interface IForEachContextEntity<TContext, ").Append(generic).Append("> { void Invoke(ref TContext context, Entity entity, ")
                .Append(refs).AppendLine("); }");
            source.AppendLine();
        }
    }

    private static void RenderStates(StringBuilder source)
    {
        RenderZeroStates(source);
        for (int arity = 1; arity <= 4; arity++)
        {
            var generic = GenericTypes(arity);
            var accesses = AccessParameters(arity);
            var values = ValueStatements(arity);
            RenderState(source, $"ForEachDelegateState<{generic}>", $"ForEachAction<{generic}> action, {accesses}", $"_action = action; {AssignAccessFields(arity)}", $"_action({values});", $"ForEachAction<{generic}>");
            RenderState(source, $"ForEachEntityDelegateState<{generic}>", $"ForEachEntityAction<{generic}> action, {accesses}", $"_action = action; {AssignAccessFields(arity)}", $"_action(cursor.Entities[cursor.CurrentIndex], {values});", $"ForEachEntityAction<{generic}>");
            RenderState(source, $"ForEachContextDelegateState<TContext, {generic}>", $"TContext context, ForEachContextAction<TContext, {generic}> action, {accesses}", $"Context = context; _action = action; {AssignAccessFields(arity)}", $"_action(ref Context, {values});", $"ForEachContextAction<TContext, {generic}>", "TContext");
            RenderState(source, $"ForEachContextEntityDelegateState<TContext, {generic}>", $"TContext context, ForEachContextEntityAction<TContext, {generic}> action, {accesses}", $"Context = context; _action = action; {AssignAccessFields(arity)}", $"_action(ref Context, cursor.Entities[cursor.CurrentIndex], {values});", $"ForEachContextEntityAction<TContext, {generic}>", "TContext");
            RenderState(source, $"ForEachFunctorState<TFunctor, {generic}>", $"TFunctor functor, {accesses}", $"Functor = functor; {AssignAccessFields(arity)}", $"Functor.Invoke({values});", null, "TFunctor", $"IForEach<{generic}>");
            RenderState(source, $"ForEachEntityFunctorState<TFunctor, {generic}>", $"TFunctor functor, {accesses}", $"Functor = functor; {AssignAccessFields(arity)}", $"Functor.Invoke(cursor.Entities[cursor.CurrentIndex], {values});", null, "TFunctor", $"IForEachEntity<{generic}>");
            RenderState(source, $"ForEachContextFunctorState<TContext, TFunctor, {generic}>", $"TContext context, TFunctor functor, {accesses}", $"Context = context; Functor = functor; {AssignAccessFields(arity)}", $"Functor.Invoke(ref Context, {values});", null, "TContext, TFunctor", $"IForEachContext<TContext, {generic}>");
            RenderState(source, $"ForEachContextEntityFunctorState<TContext, TFunctor, {generic}>", $"TContext context, TFunctor functor, {accesses}", $"Context = context; Functor = functor; {AssignAccessFields(arity)}", $"Functor.Invoke(ref Context, cursor.Entities[cursor.CurrentIndex], {values});", null, "TContext, TFunctor", $"IForEachContextEntity<TContext, {generic}>");
        }
    }

    private static void RenderZeroStates(StringBuilder source)
    {
        source.AppendLine("internal struct ForEachDelegateState : IForEachInvoker");
        source.AppendLine("{");
        source.AppendLine("    private readonly ForEachAction _action;");
        source.AppendLine("    internal ForEachDelegateState(ForEachAction action) => _action = action;");
        source.AppendLine("    public void Invoke(ref QueryChunkCursor cursor) { while (cursor.MoveNext()) _action(); }");
        source.AppendLine("}");
        source.AppendLine();
        source.AppendLine("internal struct ForEachContextDelegateState<TContext> : IForEachInvoker");
        source.AppendLine("{");
        source.AppendLine("    internal TContext Context;");
        source.AppendLine("    private readonly ForEachContextAction<TContext> _action;");
        source.AppendLine("    internal ForEachContextDelegateState(TContext context, ForEachContextAction<TContext> action) { Context = context; _action = action; }");
        source.AppendLine("    public void Invoke(ref QueryChunkCursor cursor) { while (cursor.MoveNext()) _action(ref Context); }");
        source.AppendLine("}");
        source.AppendLine();
        source.AppendLine("internal struct ForEachEntityDelegateState : IForEachInvoker");
        source.AppendLine("{");
        source.AppendLine("    private readonly ForEachEntityAction _action;");
        source.AppendLine("    internal ForEachEntityDelegateState(ForEachEntityAction action) => _action = action;");
