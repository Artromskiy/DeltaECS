        source.AppendLine("}");
        source.AppendLine();
        source.AppendLine("internal struct ForEachContextEntityDelegateState<TContext> : IForEachInvoker");
        source.AppendLine("{");
        source.AppendLine("    internal TContext Context;");
        source.AppendLine("    private readonly ForEachContextEntityAction<TContext> _action;");
