        source.AppendLine("    internal ForEachContextFunctorState(TContext context, TFunctor functor) { Context = context; Functor = functor; }");
        source.AppendLine("    public void Invoke(ref QueryChunkCursor cursor) { while (cursor.MoveNext()) Functor.Invoke(ref Context); }");
        source.AppendLine("}");
