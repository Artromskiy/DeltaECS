        for (int arity = 1; arity <= 4; arity++)
        {
            int patternCount = 1 << arity;
            for (int bits = 0; bits < patternCount; bits++)
            {
                string pattern = AccessPattern(arity, bits);
                RenderDelegateOverloads(source, pattern, explicitIds: true);
                RenderDelegateOverloads(source, pattern, explicitIds: false);
