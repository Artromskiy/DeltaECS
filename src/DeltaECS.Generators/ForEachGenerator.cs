        source.AppendLine("    public void Invoke(ref QueryChunkCursor cursor) { while (cursor.MoveNext()) Functor.Invoke(cursor.Entities[cursor.CurrentIndex]); }");
        source.AppendLine("}");
        source.AppendLine();
