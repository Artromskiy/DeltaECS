    private static void Append(StringBuilder source, string signature, string body, string? constraint = null)
    {
        source.Append("    ").AppendLine(signature);
        if (constraint is not null)
        {
            source.Append("        ").AppendLine(constraint);
        }
        source.AppendLine("    {");
        foreach (var line in body.Split('\n'))
        {
            source.Append("        ").AppendLine(line);
        }
        source.AppendLine("    }");
        source.AppendLine();
    }

    private static string GenericTypes(int arity) => string.Join(", ", TypeNames(arity, "T"));

    private static string[] TypeNames(int arity, string prefix)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = prefix + (index + 1);
        }
        return result;
    }

    private static string[] ComponentIds(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "component" + (index + 1);
        }
        return result;
    }

    private static string ComponentParameters(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "ComponentId component" + (index + 1);
        }
        return string.Join(", ", result);
    }

    private static string RefParameters(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "ref T" + (index + 1) + " component" + (index + 1);
        }
        return string.Join(", ", result);
    }

    private static string AccessParameters(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "WriteAccess component" + (index + 1);
        }
        return string.Join(", ", result);
    }

    private static string AssignAccessFields(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "_component" + (index + 1) + " = component" + (index + 1) + ";";
        }
        return string.Join(" ", result);
    }

    private static string AccessArguments(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "ForEachRuntime.AccessWrite<T" + (index + 1) + ">(this, in query, component" + (index + 1) + ")";
        }
        return string.Join(", ", result);
    }

    private static string AccessArgumentsFromSpan(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "ForEachRuntime.AccessWrite<T" + (index + 1) + ">(this, in query, componentIds[" + index + "])";
        }
        return string.Join(", ", result);
    }

    private static string ComponentSetup(int arity) => $"Span<ComponentId> componentIds = stackalloc ComponentId[{arity}]; ForEachRuntime.ResolveComponentIds(in query, componentIds); ";

    private static string AccessNames(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "access" + (index + 1);
        }
        return string.Join(", ", result);
    }

    private static string ValueStatements(int arity)
    {
        var result = new string[arity];
        for (int index = 0; index < arity; index++)
        {
            result[index] = "ref value" + (index + 1) + ".Ref<T" + (index + 1) + ">(cursor)";
        }
        return string.Join(", ", result);
    }

    private static string ConstructorName(string name)
    {
        int genericStart = name.IndexOf('<');
        return genericStart < 0 ? name : name.Substring(0, genericStart);
    }
}
