        }
    }

    private static void RenderStates(StringBuilder source)
    {
        RenderZeroStates(source);
        for (int arity = 1; arity <= 4; arity++)
        {
            int patternCount = 1 << arity;
            for (int bits = 0; bits < patternCount; bits++)
            {
                string pattern = AccessPattern(arity, bits);
                string suffix = PatternSuffix(pattern);
                string generic = GenericTypes(arity);
                string accesses = AccessParameters(pattern);
                string values = ValueStatements(pattern);

                RenderState(source, $"ForEachDelegateState{suffix}<{generic}>", pattern, $"ForEachAction{suffix}<{generic}> action, {accesses}", $"_action = action; {AssignAccessFields(arity)}", $"_action({values});", $"ForEachAction{suffix}<{generic}>");
                RenderState(source, $"ForEachEntityDelegateState{suffix}<{generic}>", pattern, $"ForEachEntityAction{suffix}<{generic}> action, {accesses}", $"_action = action; {AssignAccessFields(arity)}", $"_action(cursor.Entities[cursor.CurrentIndex], {values});", $"ForEachEntityAction{suffix}<{generic}>");
                RenderState(source, $"ForEachContextDelegateState{suffix}<TContext, {generic}>", pattern, $"TContext context, ForEachContextAction{suffix}<TContext, {generic}> action, {accesses}", $"Context = context; _action = action; {AssignAccessFields(arity)}", $"_action(ref Context, {values});", $"ForEachContextAction{suffix}<TContext, {generic}>", "TContext");
                RenderState(source, $"ForEachContextEntityDelegateState{suffix}<TContext, {generic}>", pattern, $"TContext context, ForEachContextEntityAction{suffix}<TContext, {generic}> action, {accesses}", $"Context = context; _action = action; {AssignAccessFields(arity)}", $"_action(ref Context, cursor.Entities[cursor.CurrentIndex], {values});", $"ForEachContextEntityAction{suffix}<TContext, {generic}>", "TContext");
                RenderState(source, $"ForEachFunctorState{suffix}<TFunctor, {generic}>", pattern, $"TFunctor functor, {accesses}", $"Functor = functor; {AssignAccessFields(arity)}", $"Functor.Invoke({values});", null, "TFunctor", $"IForEach{suffix}<{generic}>");
                RenderState(source, $"ForEachEntityFunctorState{suffix}<TFunctor, {generic}>", pattern, $"TFunctor functor, {accesses}", $"Functor = functor; {AssignAccessFields(arity)}", $"Functor.Invoke(cursor.Entities[cursor.CurrentIndex], {values});", null, "TFunctor", $"IForEachEntity{suffix}<{generic}>");
                RenderState(source, $"ForEachContextFunctorState{suffix}<TContext, TFunctor, {generic}>", pattern, $"TContext context, TFunctor functor, {accesses}", $"Context = context; Functor = functor; {AssignAccessFields(arity)}", $"Functor.Invoke(ref Context, {values});", null, "TContext, TFunctor", $"IForEachContext{suffix}<TContext, {generic}>");
                RenderState(source, $"ForEachContextEntityFunctorState{suffix}<TContext, TFunctor, {generic}>", pattern, $"TContext context, TFunctor functor, {accesses}", $"Context = context; Functor = functor; {AssignAccessFields(arity)}", $"Functor.Invoke(ref Context, cursor.Entities[cursor.CurrentIndex], {values});", null, "TContext, TFunctor", $"IForEachContextEntity{suffix}<TContext, {generic}>");
            }
        }
    }

